#!/usr/bin/env python3
"""Regenerate OMITTED_BY_GITIGNORE.md from what the repo ACTUALLY dropped.

WHY THIS IS A PROGRAM AND NOT A LIST. The list was hand-written, named eight
files, and was correct exactly until the next evidence file landed. Measured:
the gap grew to TEN -- the two A/B DEFs whose FN/FS counts the report cites as
its orientation evidence -- and the disclosure did not notice, because a
hand-list cannot.

Usage: gen_omitted.py <private-evidence-dir> <bundle-evidence-dir> > OMITTED...
"""
import hashlib, pathlib, sys, subprocess

priv, bundle = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
have = {str(p.relative_to(priv)) for p in priv.rglob("*") if p.is_file()}
# ASK GIT WHAT IS TRACKED, not the filesystem. `cp` fills the working tree with
# everything; the drop happens at `git add`. An earlier version of this script
# compared directories and reported "0 files absent" while ten were missing
# from the commit -- the exact confident-wrong answer it exists to prevent.
tracked = subprocess.run(["git", "ls-files", "--", str(bundle)],
                         capture_output=True, text=True).stdout.split()
kept = {str(pathlib.Path(t).relative_to(bundle)) for t in tracked}
missing = sorted(have - kept)

print("# What this bundle does NOT carry, and why\n")
print("GENERATED by `gen_omitted.py` -- do not hand-edit. An earlier version of")
print("this file was a hand-written list; it named eight files and was correct")
print("until the ninth was added. The gap reached TEN before anyone noticed,")
print("and the two it had missed were the A/B DEFs the report cites for its")
print("orientation evidence. A disclosure that cannot count is not one.\n")
print("`git add` SILENTLY SKIPS ignored paths -- no warning, no error, and the")
print("push reports success. These are dropped by the repo's own rules, and")
print("NOT force-added: the three capture bundles already under docs/capture/")
print("contain zero `.log` or `.def`.\n")
for f in missing:
    p = priv / f
    h = hashlib.sha256(p.read_bytes()).hexdigest()
    try:
        why = subprocess.run(["git", "check-ignore", "-v", f],
                             capture_output=True, text=True, cwd=priv).stdout.split(":")[:2]
        why = ":".join(why) if why else "ignored"
    except Exception:
        why = "ignored"
    print(f"    {f:<52} {h[:32]}...")
print(f"\n{len(missing)} file(s) absent. Their sha256 above is what the manifest")
print("records, so each stays checkable wherever it is retrieved from.\n")
print("WHAT IS LOST, honestly: the `.log` files are raw stdout whose VERDICTS and")
print("DENOMINATORS are quoted in `merge_preview/MERGE_PREVIEW.md`, which ships.")
print("The `.def` files are placed rings; every figure derived from them -- the")
print("81 components, the FN/FS orientation counts, pad and corner positions --")
print("is re-derived by `arithmetic_selfcheck.py` from the JSON artefacts, which")
print("ship. NO CLAIM IN RESULT.md RESTS ON AN ABSENT FILE ALONE.")
