// ring_counter — 8-bit one-hot ring counter. Reset (active-high) -> 8'b0000_0001.
// On each rising clk the single set bit shifts toward the MSB, wrapping MSB->LSB.
module ring_counter__rcvar_inner (
    input  wire       clk,
    input  wire       reset,
    output reg  [7:0] out
);
    always @(posedge clk) begin
        if (reset)
            out <= 8'b0000_0001;          // initial state: LSB set
        else
            out <= {out[6:0], out[7]};    // rotate left (MSB wraps to LSB)
    end
endmodule

