// sequence_detector — Moore FSM detecting the 4-bit sequence 1001 (overlap allowed).
// sequence_detected is high while the FSM is in S4 (one cycle after the completing bit).
// reset_n is active-low; the FSM returns to IDLE on reset.
module sequence_detector__rcvar_inner (
    input  wire clk,
    input  wire reset_n,
    input  wire data_in,
    output wire sequence_detected
);
    localparam IDLE = 3'd0,  // matched ""
               S1   = 3'd1,  // matched "1"
               S2   = 3'd2,  // matched "10"
               S3   = 3'd3,  // matched "100"
               S4   = 3'd4;  // matched "1001"
    reg [2:0] state;

    // Moore output: asserted while in the detected state
    assign sequence_detected = (state == S4);

    always @(posedge clk or negedge reset_n) begin
        if (!reset_n)
            state <= IDLE;
        else begin
            case (state)
                IDLE: state <= data_in ? S1   : IDLE;
                S1:   state <= data_in ? S1   : S2;
                S2:   state <= data_in ? S1   : S3;
                S3:   state <= data_in ? S4   : IDLE;
                S4:   state <= data_in ? S1   : S2;   // overlap: trailing "1" re-seeds
                default: state <= IDLE;
            endcase
        end
    end
endmodule

