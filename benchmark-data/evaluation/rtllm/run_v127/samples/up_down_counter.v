// up_down_counter — 16-bit synchronous up/down counter.
// Synchronous active-high reset clears to 0. up_down=1 increments, up_down=0 decrements.
module up_down_counter__rcvar_inner (
    input  wire        clk,
    input  wire        reset,
    input  wire        up_down,
    output reg  [15:0] count
);
    always @(posedge clk) begin
        if (reset)
            count <= 16'd0;
        else if (up_down)
            count <= count + 16'd1;
        else
            count <= count - 16'd1;
    end
endmodule

