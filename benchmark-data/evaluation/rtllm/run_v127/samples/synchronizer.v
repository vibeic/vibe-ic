// synchronizer: multi-bit MUX-based CDC synchronizer. data_in/data_en are
// referenced to clk_a; data_en is double-flopped into clk_b (two D-FFs) and
// gates the output data register. data_in is stable while data_en is high
// (>=3 clk_b) and changes no faster than every 10 clk_b cycles, so a MUX
// (data-register + enable handshake) safely crosses it without metastability
// on the data bus. Async active-low resets arstn (domain A) / brstn (domain B).
module synchronizer__rcvar_inner (
    input  wire       clk_a,
    input  wire       clk_b,
    input  wire       arstn,
    input  wire       brstn,
    input  wire [3:0] data_in,
    input  wire       data_en,
    output reg  [3:0] dataout
);

    // Domain A: capture data and enable
    reg [3:0] data_reg;
    reg       en_data_reg;

    always @(posedge clk_a or negedge arstn) begin
        if (!arstn)
            data_reg <= 4'd0;
        else
            data_reg <= data_in;
    end

    always @(posedge clk_a or negedge arstn) begin
        if (!arstn)
            en_data_reg <= 1'b0;
        else
            en_data_reg <= data_en;
    end

    // Domain B: two-stage synchronizer on the enable
    reg en_clap_one, en_clap_two;

    always @(posedge clk_b or negedge brstn) begin
        if (!brstn) begin
            en_clap_one <= 1'b0;
            en_clap_two <= 1'b0;
        end else begin
            en_clap_one <= en_data_reg;
            en_clap_two <= en_clap_one;
        end
    end

    // Domain B: gated output register (holds when enable is inactive)
    always @(posedge clk_b or negedge brstn) begin
        if (!brstn)
            dataout <= 4'd0;
        else if (en_clap_two)
            dataout <= data_reg;
        else
            dataout <= dataout;
    end

endmodule

