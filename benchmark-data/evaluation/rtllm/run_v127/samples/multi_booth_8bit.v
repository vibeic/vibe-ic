// multi_booth_8bit: 8-bit Radix-4 Booth-style multiplier per the stated spec.
// On reset (active high): multiplier <= sign-extended a, multiplicand <= sign-extended b.
// While ctr<16: shift multiplicand left by 1; if multiplier[ctr] then p += multiplicand;
// ctr++. When ctr reaches 16, rdy = 1.
module multi_booth_8bit__rcvar_inner (
    input             clk,
    input             reset,
    input      [7:0]  a,
    input      [7:0]  b,
    output reg [15:0] p,
    output reg        rdy
);

    reg [15:0] multiplier;
    reg [15:0] multiplicand;
    reg [4:0]  ctr;

    always @(posedge clk or posedge reset) begin
        if (reset) begin
            multiplier   <= {{8{a[7]}}, a};
            multiplicand <= {{8{b[7]}}, b};
            ctr          <= 5'd0;
            p            <= 16'd0;
            rdy          <= 1'b0;
        end
        else begin
            if (ctr < 5'd16) begin
                if (multiplier[ctr])
                    p <= p + multiplicand;
                multiplicand <= multiplicand << 1;
                ctr <= ctr + 5'd1;
            end
            else begin
                rdy <= 1'b1;
            end
        end
    end

endmodule

