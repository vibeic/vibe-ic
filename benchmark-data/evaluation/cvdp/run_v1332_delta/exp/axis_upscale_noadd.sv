// axis_upscale
// AXI-stream data upsizer: upscales single-channel 24-bit input data to 32-bit
// output with data-format controlled sign/carry extension of the extra bits.
// Single pipeline register stage. Active-low synchronous reset (resetn).

module axis_upscale__rcvar_inner (
    // Global signals
    input  wire        clk,
    input  wire        resetn,

    // Data format control
    input  wire        dfmt_enable,
    input  wire        dfmt_type,
    input  wire        dfmt_se,

    // AXI slave (input) side
    input  wire        s_axis_valid,
    input  wire [23:0] s_axis_data,
    output wire        s_axis_ready,

    // AXI master (output) side
    input  wire        m_axis_ready,
    output reg         m_axis_valid,
    output reg  [31:0] m_axis_data
);

    // Backpressure pass-through: the slave can accept a transfer whenever the
    // downstream master is ready to accept one.
    assign s_axis_ready = m_axis_ready;

    // Combinational data-format / upscale logic (24-bit -> 32-bit).
    //   - Lower 23 bits pass through unchanged.
    //   - Bit 23 carries the (optionally inverted) slave MSB.
    //   - Upper extension bits [31:24] are sign extended or zeroed.
    reg [31:0] data_out_d;

    always @(*) begin
        // Payload low bits pass straight through.
        data_out_d[22:0] = s_axis_data[22:0];

        if (dfmt_enable) begin
            // Carry-forward bit: inverted MSB when dfmt_type=1, else MSB.
            data_out_d[23]    = dfmt_type ? ~s_axis_data[23] : s_axis_data[23];
            // Extension: replicate the carry-forward bit when sign extension is
            // requested, otherwise fill with zeros.
            data_out_d[31:24] = {8{dfmt_se & data_out_d[23]}};
        end else begin
            // Data format disabled: pass MSB through and zero-fill extra bits.
            data_out_d[23]    = s_axis_data[23];
            data_out_d[31:24] = 8'b0;
        end
    end

    // Single pipeline register stage with active-low synchronous reset.
    always @(posedge clk) begin
        if (!resetn) begin
            m_axis_valid <= 1'b0;
            m_axis_data  <= 32'b0;
        end else begin
            m_axis_valid <= s_axis_valid;
            m_axis_data  <= data_out_d;
        end
    end

endmodule

