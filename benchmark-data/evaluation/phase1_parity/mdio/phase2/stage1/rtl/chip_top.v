//============================================================================
//  chip_top.v  --  IEEE 802.3 MDIO (Clause 22 / Clause 45) Station-Management
//                  master.  Fully-synchronous, single clock, active-low reset.
//
//  Protocol implemented (per L3_CMD_PROTOCOL / L8 timing constants):
//
//    Clause 22 frame (32 bits after a 32-bit preamble):
//        PRE(32 x '1')  ST=01  OP(2)  PHYAD(5)  REGAD(5)  TA(2)  DATA(16)
//          OP = 10 -> READ , OP = 01 -> WRITE
//          TA write = "10" (STA driven) ; TA read = "Z0" (STA Hi-Z bit-1,
//          PHY drives 0 on bit-2 -> sampled by STA).
//
//    Clause 45 frame (32 bits after a 32-bit preamble):
//        PRE(32 x '1')  ST=00  OP(2)  PRTAD(5)  DEVAD(5)  TA(2)  DATA(16)
//          OP = 00 -> ADDRESS, OP = 01 -> WRITE, OP = 11 -> READ,
//          OP = 10 -> READ_INC (read then post-increment register address)
//
//  Electrical / timing reference (L8_TIMING_WAVEFORM.timing_constants):
//      mdc_max = 2.5 MHz, mdc_min_period = 400 ns, setup/hold = 10 ns,
//      preamble_cycles = 32.  MDC is generated by an integer clock divider
//      from the synchronous core clock so that f_mdc = f_clk / (2*(DIV+1)).
//
//  Bus driver: MDIO is an open-drain / tri-state line.  This module exposes
//  the standard 3-signal tri-state primitive (mdio_o / mdio_oe / mdio_i) so a
//  pad / IOBUF can be attached at the SoC boundary.  No latches, no comb
//  loops, no multiply-driven nets; every state element is reset-initialised.
//
//  This is a faithful, self-contained DIGITAL core.  There is NO analog/PHY
//  content in an MDIO master; the only off-chip analog element is the external
//  pull-up resistor on the MDIO line, which lives on the board, not in RTL.
//  The downstream PHY is the protocol peer reached over MDC/MDIO -- it is not
//  instantiated here, but its behavioural attach point is the mdio_i input.
//============================================================================
`default_nettype none

module chip_top #(
    // MDC clock divider.  f_mdc = f_clk / (2*(MDC_DIV+1)).
    // Default 9 -> /20 -> 2.5 MHz from a 50 MHz core clock (L8 mdc_max_mhz).
    parameter integer MDC_DIV = 9
) (
    input  wire        clk,        // synchronous core clock
    input  wire        rst_n,      // active-low synchronous reset

    // ---- CPU / host command interface --------------------------------------
    input  wire        start,      // pulse high for 1 clk to launch a frame
    input  wire        clause45,   // 0 = Clause-22 frame, 1 = Clause-45 frame
    input  wire [1:0]  op,         // operation code (see header)
    input  wire [4:0]  phyad,      // PHYAD / PRTAD
    input  wire [4:0]  regad,      // REGAD / DEVAD
    input  wire [15:0] wdata,      // write data / address payload

    output reg  [15:0] rdata,      // captured read data
    output reg         busy,       // high while a frame is in flight
    output reg         done,       // 1-clk pulse when a frame completes
    output reg         rd_valid,   // high with done when frame was a read

    // ---- MDIO physical (2-wire) management interface ------------------------
    output reg         mdc,        // management data clock (to PHY)
    output wire        mdio_o,     // MDIO drive value     (to pad)
    output wire        mdio_oe,    // MDIO output-enable   (to pad: 1 = drive)
    input  wire        mdio_i      // MDIO sampled value   (from pad)
);

    //------------------------------------------------------------------------
    //  Frame field constants
    //------------------------------------------------------------------------
    localparam [1:0] OP22_READ  = 2'b10;
    localparam [1:0] OP22_WRITE = 2'b01;
    localparam [1:0] OP45_ADDR  = 2'b00;
    localparam [1:0] OP45_WRITE = 2'b01;
    localparam [1:0] OP45_READ  = 2'b11;
    localparam [1:0] OP45_RINC  = 2'b10;

    localparam [1:0] ST22 = 2'b01;
    localparam [1:0] ST45 = 2'b00;

    // Total bits driven/sampled in the post-preamble portion of the frame:
    //   ST(2)+OP(2)+PHYAD(5)+REGAD(5)+TA(2)+DATA(16) = 32 bits.
    localparam integer PRE_BITS   = 32;
    localparam integer FRAME_BITS = 32;

    //------------------------------------------------------------------------
    //  FSM
    //------------------------------------------------------------------------
    localparam [2:0] S_IDLE  = 3'd0,  // waiting for start
                     S_PRE   = 3'd1,  // 32 preamble '1' bits
                     S_HDR   = 3'd2,  // ST+OP+PHYAD+REGAD (14 bits, STA drives)
                     S_TA    = 3'd3,  // 2 turnaround bits
                     S_DATA  = 3'd4,  // 16 data bits (drive on write, sample on read)
                     S_DONE  = 3'd5;  // 1-clk completion flag

    reg [2:0]  state;

    //------------------------------------------------------------------------
    //  MDC generation (clock divider) + bit phase
    //  mdc toggles every (MDC_DIV+1) core clocks; one MDIO bit == one full
    //  mdc period.  We mark the falling edge of mdc (mdc_fall) as the moment
    //  the STA changes the line, and the rising edge (mdc_rise) as the moment
    //  data is valid / sampled -- matching the IEEE source/sample convention.
    //------------------------------------------------------------------------
    reg [15:0] mdc_cnt;
    reg        mdc_tick;            // 1-clk pulse at each mdc half-period edge
    wire       mdc_rise = mdc_tick & ~mdc;   // edge that takes mdc 0->1
    wire       mdc_fall = mdc_tick &  mdc;   // edge that takes mdc 1->0

    always @(posedge clk) begin
        if (!rst_n) begin
            mdc_cnt  <= 16'd0;
            mdc      <= 1'b0;
            mdc_tick <= 1'b0;
        end else if (state == S_IDLE) begin
            // Hold MDC low while idle so the next frame starts cleanly.
            mdc_cnt  <= 16'd0;
            mdc      <= 1'b0;
            mdc_tick <= 1'b0;
        end else if (mdc_cnt == MDC_DIV[15:0]) begin
            mdc_cnt  <= 16'd0;
            mdc      <= ~mdc;
            mdc_tick <= 1'b1;
        end else begin
            mdc_cnt  <= mdc_cnt + 16'd1;
            mdc_tick <= 1'b0;
        end
    end

    //------------------------------------------------------------------------
    //  Shift register, bit counter, captured command fields
    //------------------------------------------------------------------------
    reg [5:0]  bit_cnt;             // counts bits within the current state
    reg [13:0] hdr_sr;             // ST+OP+PHYAD+REGAD, MSB-first
    reg [15:0] data_sr;           // DATA shift register, MSB-first
    reg        is_read;            // current frame is a read-type op
    reg        sta_drive;          // 1 = STA owns the MDIO line this state
    reg        mdio_drv;           // value the STA drives when sta_drive=1

    //------------------------------------------------------------------------
    //  Tri-state output: drive only when sta_drive is asserted.
    //------------------------------------------------------------------------
    assign mdio_o  = mdio_drv;
    assign mdio_oe = sta_drive;

    //------------------------------------------------------------------------
    //  Main sequencer
    //------------------------------------------------------------------------
    always @(posedge clk) begin
        if (!rst_n) begin
            state     <= S_IDLE;
            bit_cnt   <= 6'd0;
            hdr_sr    <= 14'd0;
            data_sr   <= 16'd0;
            rdata     <= 16'd0;
            busy      <= 1'b0;
            done      <= 1'b0;
            rd_valid  <= 1'b0;
            is_read   <= 1'b0;
            sta_drive <= 1'b0;
            mdio_drv  <= 1'b1;       // idle line is high (released)
        end else begin
            // defaults (single-cycle strobes)
            done <= 1'b0;

            case (state)
            //----------------------------------------------------------------
            S_IDLE: begin
                busy      <= 1'b0;
                sta_drive <= 1'b0;
                mdio_drv  <= 1'b1;
                bit_cnt   <= 6'd0;
                if (start) begin
                    busy       <= 1'b1;
                    rd_valid   <= 1'b0;
                    // Build the 14-bit header MSB-first:
                    //   [13:12]=ST [11:10]=OP [9:5]=PHYAD [4:0]=REGAD
                    hdr_sr     <= { (clause45 ? ST45 : ST22),
                                    op, phyad, regad };
                    data_sr    <= wdata;
                    // Read-type ops (sample DATA from PHY):
                    //   Cl22 READ, Cl45 READ, Cl45 READ_INC.
                    is_read    <= clause45 ? ((op == OP45_READ) ||
                                              (op == OP45_RINC))
                                           : (op == OP22_READ);
                    sta_drive  <= 1'b1;   // STA drives the preamble
                    mdio_drv   <= 1'b1;   // preamble is all ones
                    bit_cnt    <= PRE_BITS[5:0];
                    state      <= S_PRE;
                end
            end

            //----------------------------------------------------------------
            //  32 preamble bits, all '1', STA driving.
            S_PRE: begin
                sta_drive <= 1'b1;
                mdio_drv  <= 1'b1;
                if (mdc_fall) begin
                    if (bit_cnt == 6'd1) begin
                        bit_cnt <= FRAME_BITS[5:0] - 6'd16 - 6'd2; // 14 hdr bits
                        // present first header bit (MSB) on the next fall
                        mdio_drv <= hdr_sr[13];
                        state    <= S_HDR;
                    end else begin
                        bit_cnt  <= bit_cnt - 6'd1;
                        mdio_drv <= 1'b1;
                    end
                end
            end

            //----------------------------------------------------------------
            //  14 header bits (ST+OP+PHYAD+REGAD), STA driving, MSB-first.
            S_HDR: begin
                sta_drive <= 1'b1;
                if (mdc_fall) begin
                    // shift up; drive the new MSB
                    hdr_sr   <= {hdr_sr[12:0], 1'b0};
                    mdio_drv <= hdr_sr[12];
                    if (bit_cnt == 6'd1) begin
                        bit_cnt <= 6'd2;       // 2 turnaround bits
                        state   <= S_TA;
                    end else begin
                        bit_cnt <= bit_cnt - 6'd1;
                    end
                end
            end

            //----------------------------------------------------------------
            //  2 turnaround bits.
            //    write : STA drives "10".
            //    read  : STA tri-states (bit 1 Hi-Z), PHY drives 0 (bit 2).
            S_TA: begin
                if (mdc_fall) begin
                    if (is_read) begin
                        sta_drive <= 1'b0;     // release the line for the PHY
                        mdio_drv  <= 1'b1;
                    end else begin
                        sta_drive <= 1'b1;
                        // first TA bit = 1, second TA bit = 0
                        mdio_drv  <= (bit_cnt == 6'd2) ? 1'b1 : 1'b0;
                    end
                    if (bit_cnt == 6'd1) begin
                        bit_cnt <= 6'd16;       // 16 data bits
                        // for a write, present DATA MSB on the next fall
                        if (!is_read) mdio_drv <= data_sr[15];
                        state   <= S_DATA;
                    end else begin
                        bit_cnt <= bit_cnt - 6'd1;
                    end
                end
            end

            //----------------------------------------------------------------
            //  16 data bits, MSB-first.
            //    write : STA drives data_sr, shifting up each fall.
            //    read  : STA samples mdio_i on the rising edge into data_sr.
            S_DATA: begin
                if (is_read) begin
                    sta_drive <= 1'b0;
                    // Sample on rising edge (data valid), MSB first.
                    if (mdc_rise) begin
                        data_sr <= {data_sr[14:0], mdio_i};
                    end
                    if (mdc_fall) begin
                        if (bit_cnt == 6'd1) begin
                            state <= S_DONE;
                        end else begin
                            bit_cnt <= bit_cnt - 6'd1;
                        end
                    end
                end else begin
                    sta_drive <= 1'b1;
                    if (mdc_fall) begin
                        data_sr  <= {data_sr[14:0], 1'b0};
                        mdio_drv <= data_sr[14];
                        if (bit_cnt == 6'd1) begin
                            state <= S_DONE;
                        end else begin
                            bit_cnt <= bit_cnt - 6'd1;
                        end
                    end
                end
            end

            //----------------------------------------------------------------
            S_DONE: begin
                sta_drive <= 1'b0;
                mdio_drv  <= 1'b1;
                busy      <= 1'b0;
                done      <= 1'b1;
                rd_valid  <= is_read;
                if (is_read) rdata <= data_sr;
                state     <= S_IDLE;
            end

            //----------------------------------------------------------------
            default: state <= S_IDLE;
            endcase
        end
    end

endmodule

`default_nettype wire
