// =====================================================================
// qspi_ctrl — QSPI / OSPI Master Flash Controller IP block
// ---------------------------------------------------------------------
// Protocol : Quad/Octal SPI (xSPI / QSPI / OSPI, JESD251), command-
//            oriented multi-IO serial NOR-flash master.
// Source   : Phase-1 L-docs for benchmark_phase1/qspi_ospi
//            (L1 datasheet, L3 cmd-protocol/phases, L4 register map,
//             L6 control-logic FSM, L8 RTL-constants, L9 integration)
//
// Function : A register-mapped, command-driven QSPI master.  Software
//            writes a command opcode, address, dummy-cycle count, lane
//            mode and byte count into a small CSR file, then sets START.
//            The command engine walks the canonical phase FSM
//              IDLE -> CMD(instruction) -> ADDR -> MODE/ALT -> DUMMY
//                   -> DATA(read or write) -> DONE
//            generating SCLK (SPI mode-0: CPOL=0/CPHA=0 — sample on the
//            rising SCLK edge, shift on the falling edge), shifting the
//            instruction / address / data MSB-first over IO0..IO3 with
//            per-phase lane width (single = IO0 out / IO1 in, quad =
//            IO0..IO3), absorbing a programmable dummy-cycle latency,
//            and capturing read data back into the CSR.
//
// Spec grounding (every rule traceable to an L-doc):
//   * Phase FSM IDLE->SELECT->INSTRUCTION->ADDRESS->MODE_BITS->DUMMY
//     ->DATA->DESELECT.                                            [L6 fsm_states]
//   * Each transaction framed by CS# low..high; MSB-first per line.  [L3 frame_format]
//   * Instruction 8-bit, address 3 byte (24-bit) default, programmable
//     dummy count, data 1..N bytes.                                [L3 command_phases, L8]
//   * Lane width per phase via S-A-D notation (1-1-1, 1-1-4,
//     1-4-4, ...).                                                 [L3 protocol_mode_notation]
//   * Fast Read 0x0B = 1-1-1, 8 dummy; Quad Output 0x6B = 1-1-4,
//     8 dummy; Quad I/O 0xEB = 1-4-4, 8 mode bits + 6 dummy;
//     WREN 0x06; RDSR 0x05.                                        [L3 read_mode_examples, L4]
//   * SPI mode 0/3 supported; this build uses mode-0 (CPOL=0 CPHA=0):
//     sample-on-rising / shift-on-falling.                         [L4 CPOL/CPHA, L8 spi_mode_0_and_3]
//   * CSR: SPICR1/2, SPIBR, SPISR, SPIDR (8-bit) at offsets 0..5.  [L4 registers]
//     This controller adds command-engine CSRs (cmd/addr/dummy/ctrl/
//     rdata) in the same 8-bit register space — a superset of the
//     legacy SPI CSR, since the legacy file alone cannot express the
//     QSPI multi-phase command (the L4 'notes' field states the IP is
//     command-oriented with opcode + phase protocol).
//   * IO lines bidirectional, direction set per phase; tri-stated when
//     not driven.                                                  [L3 channels, L9 default_signal_values]
//   * START/BUSY/DONE command handshake (busy=WIP-style while a frame
//     is in flight).                                               [L6 POLL_WIP, L9]
//
// Implementation style : single-clock SYNCHRONOUS master.  All state is
//   in the chip's `clk` domain.  SCLK is generated by a programmable
//   clock divider (SPIBR-style baud divisor); IO0..IO3 are driven through
//   registered output + a per-bit output-enable so the pad ring can be
//   tri-stated.  TRI-STATE EXISTS ONLY AT THE TOP BOUNDARY (the io_oe
//   output enables); all internal logic is 2-state.
//
// Hygiene: active-low synchronous reset on ALL state; every reg reset;
//   no inferred latches (FSM has default, every case has default); no
//   full/parallel-case reliance; reset-less regs N/A (all reset).
// =====================================================================

`timescale 1ns/1ps
`default_nettype none

module qspi_ctrl #(
    // Address width in bits (24 = 3-byte addressing, the default reach
    // of 16 MB per L3/L4).  4-byte (32) addressing is the other option.
    parameter integer ADDR_BITS  = 24,
    // Maximum payload data bytes captured/driven per transaction.  A
    // small read buffer keeps the design synthesis-friendly while still
    // exercising the full data phase.
    parameter integer DATA_BYTES = 4
) (
    input  wire                       clk,        // SoC bus clock (133 MHz typ, L8)
    input  wire                       rst_n,      // active-low sync reset

    // ----------------------------------------------------------------
    // CSR interface (lightweight addr/wdata/rdata/we/re — L4 implies an
    // 8-bit register file at a module base; we widen data to 32 so the
    // address / data-buffer CSRs are single-access).
    // ----------------------------------------------------------------
    input  wire [3:0]                 csr_addr,   // register index
    input  wire [31:0]                csr_wdata,
    input  wire                       csr_we,     // write strobe
    input  wire                       csr_re,     // read strobe
    output reg  [31:0]                csr_rdata,

    // ----------------------------------------------------------------
    // QSPI pad-facing signals (top boundary — tri-state lives HERE only)
    // ----------------------------------------------------------------
    output reg                        sclk,       // serial clock (controller -> device)
    output reg                        cs_n,       // active-low chip select (frames a command)
    output reg  [3:0]                 io_out,     // IO0..IO3 drive value
    output reg  [3:0]                 io_oe,      // IO0..IO3 output-enable (1=drive, 0=hi-Z)
    input  wire [3:0]                 io_in,      // IO0..IO3 sampled input

    // ----------------------------------------------------------------
    // Status sidebands
    // ----------------------------------------------------------------
    output reg                        busy,       // 1 while a command is in flight
    output reg                        done        // 1-clk strobe at end of a command
);

    localparam integer DATA_BITS = 8*DATA_BYTES;

    // -----------------------------------------------------------------
    // CSR register map (command-engine superset, 8-bit-addressable space)
    // -----------------------------------------------------------------
    //  index  name      meaning
    //   0      SPICR1    control: [3]=CPOL [2]=CPHA [0]=LSBFE  (L4 SPICR1)
    //   1      SPIBR     baud divisor (SCLK = clk / (2*(div+1)))  (L4 SPIBR)
    //   2      CMD       [7:0]=opcode, [11:8]=dummy_cycles,
    //                    [13:12]=lane_mode(0=1lane,1=quad-data,2=quad-io),
    //                    [14]=has_addr, [15]=is_read,
    //                    [23:16]=data byte count (1..DATA_BYTES)
    //   3      ADDR      [ADDR_BITS-1:0] flash address
    //   4      WDATA     write data buffer (LSB byte sent first within MSB-first bytes)
    //   5      SPISR     status (read-only): [0]=busy
    //   6      RDATA     captured read data buffer (read-only)
    //   7      START     write 1 to launch the command in CMD/ADDR/WDATA
    localparam [3:0] R_SPICR1 = 4'd0,
                     R_SPIBR  = 4'd1,
                     R_CMD    = 4'd2,
                     R_ADDR   = 4'd3,
                     R_WDATA  = 4'd4,
                     R_SPISR  = 4'd5,
                     R_RDATA  = 4'd6,
                     R_START  = 4'd7;

    // CSR storage
    reg [7:0]            spicr1;          // CPOL/CPHA/LSBFE etc.
    reg [7:0]            spibr;           // baud divisor field
    reg [7:0]            cmd_opcode;
    reg [3:0]            cmd_dummy;       // programmable dummy cycles (L3/L6)
    reg [1:0]            cmd_lane_mode;   // 0=1-1-1, 1=1-1-4 (quad data), 2=1-4-4 (quad io)
    reg                  cmd_has_addr;
    reg                  cmd_is_read;
    reg [7:0]            cmd_nbytes;      // data byte count
    reg [ADDR_BITS-1:0]  cmd_addr;
    reg [DATA_BITS-1:0]  wdata_buf;
    reg [DATA_BITS-1:0]  rdata_buf;

    wire start_pulse = csr_we && (csr_addr == R_START) && csr_wdata[0];

    // -----------------------------------------------------------------
    // SCLK baud generator: a free-running divider.  SCLK toggles when
    // the divider expires; one full SCLK period = 2*(div+1) clk cycles.
    // sclk_tick_rise marks the clk where SCLK goes 0->1 (sample edge),
    // sclk_tick_fall marks 1->0 (shift edge), in SPI mode-0.
    // -----------------------------------------------------------------
    reg  [7:0] baud_cnt;
    reg        sclk_en;       // gates SCLK toggling to active phases only
    wire [7:0] baud_top = spibr;             // 0 => fastest (toggle every clk)
    wire       baud_expire = (baud_cnt == baud_top);

    reg        sclk_rise;     // 1-clk: SCLK just went low->high
    reg        sclk_fall;     // 1-clk: SCLK just went high->low

    always @(posedge clk) begin
        if (!rst_n) begin
            baud_cnt  <= 8'd0;
            sclk      <= 1'b0;
            sclk_rise <= 1'b0;
            sclk_fall <= 1'b0;
        end else begin
            sclk_rise <= 1'b0;
            sclk_fall <= 1'b0;
            if (!sclk_en) begin
                // SCLK parked low (CPOL=0 idle) between active phases.
                baud_cnt <= 8'd0;
                sclk     <= 1'b0;
            end else if (baud_expire) begin
                baud_cnt <= 8'd0;
                sclk     <= ~sclk;
                if (~sclk) sclk_rise <= 1'b1;   // about to be high
                else       sclk_fall <= 1'b1;   // about to be low
            end else begin
                baud_cnt <= baud_cnt + 8'd1;
            end
        end
    end

    // -----------------------------------------------------------------
    // Command-phase FSM.  [L6 fsm_states]
    // -----------------------------------------------------------------
    localparam [2:0] S_IDLE  = 3'd0,  // CS# high, waiting for START
                     S_INSTR = 3'd1,  // shift 8-bit opcode (1 lane)
                     S_ADDR  = 3'd2,  // shift ADDR_BITS address (lane per mode)
                     S_DUMMY = 3'd3,  // programmable dummy cycles (no data)
                     S_DATA  = 3'd4,  // read or write data bytes
                     S_DONE  = 3'd5;  // raise done, deselect, back to IDLE

    reg [2:0]            state;
    reg [DATA_BITS-1:0]  shift_tx;        // MSB-first transmit shift register
    reg [DATA_BITS-1:0]  shift_rx;        // received-data accumulator
    reg [7:0]            bit_cnt;         // bits remaining in current phase
    reg [7:0]            dummy_cnt;       // dummy SCLK edges remaining
    reg [7:0]            byte_cnt;        // data bytes remaining (write path)
    reg [9:0]            rx_total;        // total READ data bits remaining

    // Lanes used in the DATA phase: quad (4) when lane_mode != 0, else 1.
    wire data_quad = (cmd_lane_mode != 2'd0);
    // Address phase quad only in 1-4-4 (lane_mode==2); 0x6B (1-1-4) keeps
    // a single-lane address.  Instruction is always single lane here
    // (1-1-1 / 1-1-4 / 1-4-4 all use a 1-lane instruction). [L3]
    wire addr_quad = (cmd_lane_mode == 2'd2);
    // Total data bits for a READ = nbytes * 8.
    wire [9:0] data_total_bits = {cmd_nbytes, 3'b000};  // nbytes * 8

    // -----------------------------------------------------------------
    // Sample read inputs on the SCLK RISING edge (mode-0).  Build the
    // received word MSB-first: shift left, insert new bit(s) at the LSB.
    // Single mode reads IO1 (MISO); quad mode reads IO3..IO0.
    // -----------------------------------------------------------------
    // (combinational selectors used inside the FSM block below)

    always @(posedge clk) begin
        if (!rst_n) begin
            state      <= S_IDLE;
            sclk_en    <= 1'b0;
            cs_n       <= 1'b1;          // deselected at reset
            io_out     <= 4'b0000;
            io_oe      <= 4'b0000;        // all hi-Z at reset (L9)
            shift_tx   <= {DATA_BITS{1'b0}};
            shift_rx   <= {DATA_BITS{1'b0}};
            bit_cnt    <= 8'd0;
            dummy_cnt  <= 8'd0;
            byte_cnt   <= 8'd0;
            rx_total   <= 10'd0;
            busy       <= 1'b0;
            done       <= 1'b0;
            rdata_buf  <= {DATA_BITS{1'b0}};
        end else begin
            done <= 1'b0;                  // single-cycle strobe by default

            case (state)
                // --------------------------------------------------------
                S_IDLE: begin
                    sclk_en <= 1'b0;
                    cs_n    <= 1'b1;
                    io_oe   <= 4'b0000;
                    busy    <= 1'b0;
                    if (start_pulse) begin
                        // Launch: select device, load instruction into the
                        // single-lane shifter (opcode in the top byte).
                        cs_n     <= 1'b0;
                        busy     <= 1'b1;
                        sclk_en  <= 1'b1;
                        shift_tx <= {cmd_opcode, {(DATA_BITS-8){1'b0}}};
                        bit_cnt  <= 8'd8;          // 8 opcode bits
                        io_oe    <= 4'b0001;       // drive IO0 only (instruction = 1 lane)
                        io_out   <= {3'b000, cmd_opcode[7]};
                        state    <= S_INSTR;
                    end
                end

                // --------------------------------------------------------
                // INSTRUCTION: 8-bit opcode, MSB-first, single lane (IO0).
                S_INSTR: begin
                    io_oe <= 4'b0001;
                    if (sclk_fall) begin
                        // shift out next bit on the falling edge (mode-0)
                        shift_tx <= {shift_tx[DATA_BITS-2:0], 1'b0};
                        io_out   <= {3'b000, shift_tx[DATA_BITS-2]};
                        bit_cnt  <= bit_cnt - 8'd1;
                        if (bit_cnt == 8'd1) begin
                            // instruction done; pick the next phase
                            if (cmd_has_addr) begin
                                shift_tx <= {cmd_addr, {(DATA_BITS-ADDR_BITS){1'b0}}};
                                bit_cnt  <= ADDR_BITS[7:0];
                                // first address bit driven on next falling edge
                                io_oe    <= addr_quad ? 4'b1111 : 4'b0001;
                                state    <= S_ADDR;
                            end else if (cmd_dummy != 4'd0) begin
                                dummy_cnt <= {4'd0, cmd_dummy};
                                io_oe     <= 4'b0000;   // release bus during dummy
                                state     <= S_DUMMY;
                            end else begin
                                byte_cnt  <= cmd_nbytes;
                                bit_cnt   <= 8'd8;
                                rx_total  <= data_total_bits;
                                shift_rx  <= {DATA_BITS{1'b0}};
                                io_oe     <= cmd_is_read ? 4'b0000 :
                                             (data_quad ? 4'b1111 : 4'b0001);
                                if (!cmd_is_read) begin
                                    shift_tx <= wdata_buf;
                                    io_out   <= data_quad ?
                                                wdata_buf[DATA_BITS-1:DATA_BITS-4] :
                                                {3'b000, wdata_buf[DATA_BITS-1]};
                                end
                                state    <= S_DATA;
                            end
                        end
                    end
                end

                // --------------------------------------------------------
                // ADDRESS: ADDR_BITS bits, MSB-first.  Single lane (IO0) for
                // 1-1-1/1-1-4; quad (IO0..3) for 1-4-4.  [L3]
                S_ADDR: begin
                    io_oe <= addr_quad ? 4'b1111 : 4'b0001;
                    if (sclk_fall) begin
                        if (addr_quad) begin
                            shift_tx <= {shift_tx[DATA_BITS-5:0], 4'b0000};
                            io_out   <= shift_tx[DATA_BITS-5 +: 4];
                            bit_cnt  <= bit_cnt - 8'd4;
                        end else begin
                            shift_tx <= {shift_tx[DATA_BITS-2:0], 1'b0};
                            io_out   <= {3'b000, shift_tx[DATA_BITS-2]};
                            bit_cnt  <= bit_cnt - 8'd1;
                        end
                        if ((addr_quad && bit_cnt <= 8'd4) ||
                            (!addr_quad && bit_cnt == 8'd1)) begin
                            // address done
                            if (cmd_dummy != 4'd0) begin
                                dummy_cnt <= {4'd0, cmd_dummy};
                                io_oe     <= 4'b0000;     // release during dummy
                                state     <= S_DUMMY;
                            end else begin
                                byte_cnt <= cmd_nbytes;
                                bit_cnt  <= 8'd8;
                                rx_total <= data_total_bits;
                                shift_rx <= {DATA_BITS{1'b0}};
                                io_oe    <= cmd_is_read ? 4'b0000 :
                                            (data_quad ? 4'b1111 : 4'b0001);
                                state    <= S_DATA;
                            end
                        end
                    end
                end

                // --------------------------------------------------------
                // DUMMY: absorb `cmd_dummy` SCLK cycles, bus released.  [L3/L6]
                S_DUMMY: begin
                    io_oe <= 4'b0000;
                    if (sclk_fall) begin
                        dummy_cnt <= dummy_cnt - 8'd1;
                        if (dummy_cnt == 8'd1) begin
                            byte_cnt <= cmd_nbytes;
                            bit_cnt  <= 8'd8;
                            rx_total <= data_total_bits;
                            shift_rx <= {DATA_BITS{1'b0}};
                            io_oe    <= cmd_is_read ? 4'b0000 :
                                        (data_quad ? 4'b1111 : 4'b0001);
                            if (!cmd_is_read) begin
                                shift_tx <= wdata_buf;
                                io_out   <= data_quad ?
                                            wdata_buf[DATA_BITS-1:DATA_BITS-4] :
                                            {3'b000, wdata_buf[DATA_BITS-1]};
                            end
                            state    <= S_DATA;
                        end
                    end
                end

                // --------------------------------------------------------
                // DATA: read or write `cmd_nbytes` bytes, MSB-first.
                //   read  : sample IO on the RISING edge (mode-0),
                //           single mode = IO1, quad = IO3..IO0.
                //   write : shift on the FALLING edge like instr/addr.
                S_DATA: begin
                    // ===== READ path: sample on the RISING edge (mode-0). =====
                    //   Build the word MSB-first; completion is tracked by the
                    //   total-read-bit counter `rx_total` so there is exactly
                    //   one capture per data bit (no double-count). When the
                    //   final bit lands, latch the assembled word and finish.
                    if (cmd_is_read && sclk_rise) begin
                        if (data_quad) begin
                            shift_rx <= {shift_rx[DATA_BITS-5:0], io_in};
                            if (rx_total <= 10'd4) begin
                                rdata_buf <= {shift_rx[DATA_BITS-5:0], io_in};
                                sclk_en   <= 1'b0;
                                state     <= S_DONE;
                            end else begin
                                rx_total <= rx_total - 10'd4;
                            end
                        end else begin
                            shift_rx <= {shift_rx[DATA_BITS-2:0], io_in[1]}; // IO1=MISO
                            if (rx_total == 10'd1) begin
                                rdata_buf <= {shift_rx[DATA_BITS-2:0], io_in[1]};
                                sclk_en   <= 1'b0;
                                state     <= S_DONE;
                            end else begin
                                rx_total <= rx_total - 10'd1;
                            end
                        end
                    end
                    // ===== WRITE path: drive next bit(s) on the FALLING edge. =====
                    if (!cmd_is_read && sclk_fall) begin
                        if (data_quad) begin
                            shift_tx <= {shift_tx[DATA_BITS-5:0], 4'b0000};
                            io_out   <= shift_tx[DATA_BITS-5 +: 4];
                            bit_cnt  <= bit_cnt - 8'd4;
                        end else begin
                            shift_tx <= {shift_tx[DATA_BITS-2:0], 1'b0};
                            io_out   <= {3'b000, shift_tx[DATA_BITS-2]};
                            bit_cnt  <= bit_cnt - 8'd1;
                        end
                        if ((data_quad && bit_cnt <= 8'd4) ||
                            (!data_quad && bit_cnt == 8'd1)) begin
                            // one byte complete
                            if (byte_cnt == 8'd1) begin
                                sclk_en <= 1'b0;
                                state   <= S_DONE;
                            end else begin
                                byte_cnt <= byte_cnt - 8'd1;
                                bit_cnt  <= 8'd8;
                            end
                        end
                    end
                end

                // --------------------------------------------------------
                S_DONE: begin
                    cs_n  <= 1'b1;          // deselect (CS# high ends command)
                    io_oe <= 4'b0000;
                    busy  <= 1'b0;
                    done  <= 1'b1;          // 1-clk completion strobe
                    state <= S_IDLE;
                end

                default: begin              // no inferred latch
                    state   <= S_IDLE;
                    sclk_en <= 1'b0;
                    cs_n    <= 1'b1;
                    io_oe   <= 4'b0000;
                end
            endcase
        end
    end

    // -----------------------------------------------------------------
    // CSR write port (synchronous).
    // -----------------------------------------------------------------
    always @(posedge clk) begin
        if (!rst_n) begin
            spicr1        <= 8'h04;             // L8 default (CPOL=1) — but mode-0 used in datapath
            spibr         <= 8'd1;              // default divisor
            cmd_opcode    <= 8'd0;
            cmd_dummy     <= 4'd0;
            cmd_lane_mode <= 2'd0;
            cmd_has_addr  <= 1'b0;
            cmd_is_read   <= 1'b0;
            cmd_nbytes    <= 8'd1;
            cmd_addr      <= {ADDR_BITS{1'b0}};
            wdata_buf     <= {DATA_BITS{1'b0}};
        end else if (csr_we) begin
            case (csr_addr)
                R_SPICR1: spicr1 <= csr_wdata[7:0];
                R_SPIBR:  spibr  <= csr_wdata[7:0];
                R_CMD: begin
                    cmd_opcode    <= csr_wdata[7:0];
                    cmd_dummy     <= csr_wdata[11:8];
                    cmd_lane_mode <= csr_wdata[13:12];
                    cmd_has_addr  <= csr_wdata[14];
                    cmd_is_read   <= csr_wdata[15];
                    cmd_nbytes    <= csr_wdata[23:16];
                end
                R_ADDR:  cmd_addr  <= csr_wdata[ADDR_BITS-1:0];
                R_WDATA: wdata_buf <= csr_wdata[DATA_BITS-1:0];
                default: ; // START handled by start_pulse; others read-only/no-op
            endcase
        end
    end

    // -----------------------------------------------------------------
    // CSR read port (synchronous, registered rdata).
    // -----------------------------------------------------------------
    always @(posedge clk) begin
        if (!rst_n) begin
            csr_rdata <= 32'd0;
        end else if (csr_re) begin
            case (csr_addr)
                R_SPICR1: csr_rdata <= {24'd0, spicr1};
                R_SPIBR:  csr_rdata <= {24'd0, spibr};
                R_CMD:    csr_rdata <= {8'd0, cmd_nbytes, cmd_is_read, cmd_has_addr,
                                        cmd_lane_mode, cmd_dummy, cmd_opcode};
                R_ADDR:   csr_rdata <= {{(32-ADDR_BITS){1'b0}}, cmd_addr};
                R_SPISR:  csr_rdata <= {31'd0, busy};
                R_RDATA:  csr_rdata <= {{(32-DATA_BITS){1'b0}}, rdata_buf};
                default:  csr_rdata <= 32'd0;   // no inferred latch
            endcase
        end
    end

endmodule

`default_nettype wire
