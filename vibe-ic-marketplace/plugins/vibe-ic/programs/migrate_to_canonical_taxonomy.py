#!/usr/bin/env python3
"""
migrate_to_canonical_taxonomy.py — one-shot migration tool that moves
stray top-level entries and stray `reports/` flat artefacts into the
canonical Phase/Stage/Step layout enforced by v1.6.26's
`top_level_outputs_in_canonical_check` and
`reports_subfolder_taxonomy_check`.

Why this exists
---------------
v1.6.26 added two enforcement gates whitelisting the project root
(`input/`, `phase1/`, `phase2/`, `phase3/`, `analog/`, `reports/` +
3 metadata files) and `reports/` subfolders (the 6 phase-aligned
parents `phase1/phase2/phase3/analog/audit/orchestrator`). Existing
benchmarks (v10623, v10619 etc.) were generated by older runners that
wrote to flat top-level paths (`fpga/`, `logs/`, `sim/`, `rtl.pre_gen_backup/`)
plus 4 phase1 metadata files at the project root. v1.6.26's commit
msg claimed the benchmarks were migrated; independent audit shows
they were NOT. This tool actually finishes the job.

Behaviour (chip-AGNOSTIC)
-------------------------
1. Top-level dir migrations (project/<name> → canonical parent):
     fpga              → phase2/stage1/fpga              (merge if exists)
     sim               → phase2/stage1/sim
     formal            → phase2/stage1/formal
     tb                → phase2/stage1/tb
     sim_full_stack    → phase2/stage1/sim_full_stack
     rtl.pre_gen_backup→ phase2/stage1/rtl.pre_gen_backup
     synth             → phase2/stage2/synth
     constraints       → phase2/stage2/constraints
     dft               → phase2/stage2/dft
     pnr               → phase3/stage3/pnr
     cts               → phase3/stage3/cts
     extracted         → phase3/stage3/extracted
     eco               → phase3/stage3/eco
     spice             → phase3/stage3/spice
     sta               → phase3/stage3/sta
     sim_postlayout    → phase3/stage3/sim_postlayout
     gds               → phase3/stage4/gds
     foundry_handoff   → phase3/stage4/foundry_handoff
     mixed_signal      → phase3/mixed_signal
     cosim             → phase3/mixed_signal/cosim
     hardmacro         → analog/hardmacro
     extracted_docs    → phase1/input_doc
     generated_docs    → phase1/generated_docs
     logs / run_logs   → reports/orchestrator/logs

2. Top-level metadata files → phase1/ (per v1.6.26 helpers):
     extraction_patterns.json      / .auto.json
     completeness_check_config.json
     ai_deep_review_patches.json

3. reports/<flat_subdir>/ → reports/<phase_parent>/<flat_subdir>/
   Heuristic (chip-AGNOSTIC, name-based):
     phase2 parent: cdc, coverage, lint, fpga, gates
     phase2 stage2: dft, synth
     phase3 parent:  pnr, cts, sta, mixed_signal, signoff
     audit:          (default for unknown)

4. reports/<file> at top → routed via `_pl.report_path()` auto-router.

Whitelisted (left in place):
     input/, phase1/, phase2/, phase3/, analog/, reports/
     provenance.jsonl, rig_topology.json, waivers.json
     AGENT_REPORT.md (top-level *.md is housekeeping per v1.6.26 spec)

Usage:
    python3 migrate_to_canonical_taxonomy.py <project_dir> [--dry-run]
                                                            [--json <out>]
Exit codes:
    0  PASS (migration completed or VACUOUS — nothing stray)
    1  one or more moves blocked by destination conflict (manual fix)
    2  argument or I/O error
"""
