@dataclass
class Move:
    src: str
    dst: str
    kind: str           # "dir" / "file"
    note: str = ""
    skipped_files: List[str] = field(default_factory=list)
    # For dir merges: relative paths inside src/ that already existed
    # at dst/ and were left in place (caller can audit / resolve).


@dataclass
class MigrationResult:
    moves: List[Move] = field(default_factory=list)
    blocked: List[Move] = field(default_factory=list)


def _safe_move_dir(src: Path, dst: Path, dry_run: bool
                   ) -> Tuple[Optional[str], List[str]]:
    """Merge src/ into dst/. If dst already exists, recursively merge
    file-by-file. Files whose destination already exists are LEFT in
    place inside src/ — they are reported as skipped so the caller can
    flag them. (v1.6.30 change: previously silently dropped them; now
    they remain at src/ so a re-run / manual resolution sees the truth.)
    Returns (error_string_or_None, list_of_skipped_relative_paths).
    """
    if not src.exists():
        return None, []
    if not dst.exists():
        if dry_run:
            return None, []
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(src), str(dst))
        return None, []
    # dst exists — merge
    skipped: List[str] = []
    if dry_run:
        # Preview which files would skip (destination exists at dst).
        for child in src.rglob("*"):
            if child.is_dir():
                continue
            rel = child.relative_to(src)
            if (dst / rel).exists():
                skipped.append(str(rel))
        return None, skipped
    for child in src.rglob("*"):
        if child.is_dir():
            continue
        rel = child.relative_to(src)
        target = dst / rel
        if target.exists():
            skipped.append(str(rel))
            continue  # leave at src/ — caller decides
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(child), str(target))
    # Remove now-empty subdirs and src/ itself if fully drained.
    # If skipped files remain, src/ stays so the user sees them.
    try:
        for empty in sorted(src.rglob("*"), key=lambda p: -len(p.parts)):
            if empty.is_dir() and not any(empty.iterdir()):
                empty.rmdir()
        if src.exists() and not any(src.iterdir()):
            src.rmdir()
    except OSError:
        pass
    return None, skipped


def _safe_move_file(src: Path, dst: Path, dry_run: bool) -> Optional[str]:
    if not src.is_file():
        return None
    if dst.exists():
        # Resume support: if src and dst are byte-identical the move is
        # already "done" — drop the redundant src/ entry and return OK.
        try:
            if src.stat().st_size == dst.stat().st_size and \
               src.read_bytes() == dst.read_bytes():
                if not dry_run:
                    src.unlink()
                return None
        except OSError:
            pass
        return f"destination exists: {dst}"
    if dry_run:
        return None
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(src), str(dst))
    return None


def migrate(project: Path, dry_run: bool) -> MigrationResult:
    result = MigrationResult()

    # 1. Top-level dirs
    for name, dst_rel in _DIR_MIGRATIONS.items():
        src = project / name
        if not src.is_dir():
            continue
        dst = project / dst_rel
        err, skipped = _safe_move_dir(src, dst, dry_run)
        mv = Move(src=name + "/", dst=dst_rel + "/", kind="dir",
                  skipped_files=skipped)
        if err:
            mv.note = err
            result.blocked.append(mv)
        elif skipped:
            mv.note = (f"merged with conflicts; {len(skipped)} file(s) "
                       f"left at src/ (destination exists)")
            result.blocked.append(mv)
        else:
            result.moves.append(mv)

    # 2. Top-level metadata files
    for name, dst_rel in _FILE_MIGRATIONS.items():
        src = project / name
        if not src.is_file():
            continue
        dst = project / dst_rel
        err = _safe_move_file(src, dst, dry_run)
        mv = Move(src=name, dst=dst_rel, kind="file")
        if err:
            mv.note = err
            result.blocked.append(mv)
        else:
            result.moves.append(mv)

    # 3. reports/<flat_subdir>/ → reports/<parent>/<flat_subdir>/
    reports = project / "reports"
    if reports.is_dir():
        for child in sorted(reports.iterdir()):
            if not child.is_dir():
                continue
            if child.name in _pl.REPORTS_VALID_SUBDIRS:
                continue
            parent = _REPORTS_FLAT_TO_PARENT.get(child.name, "audit")
            dst = reports / parent / child.name
            err, skipped = _safe_move_dir(child, dst, dry_run)
            mv = Move(src=f"reports/{child.name}/",
                      dst=f"reports/{parent}/{child.name}/", kind="dir",
                      skipped_files=skipped)
            if err:
                mv.note = err
                result.blocked.append(mv)
            elif skipped:
                mv.note = (f"merged with conflicts; {len(skipped)} file(s) "
                           f"left in src")
                result.blocked.append(mv)
            else:
                result.moves.append(mv)

    # 4. reports/<file> at top → auto-routed via _pl.report_path()
    if reports.is_dir():
        for child in sorted(reports.iterdir()):
            if not child.is_file():
                continue
            dst = _pl.report_path(project, child.name)
            if dst.parent == reports:
                # Already at the right level (auto-router said reports/
                # root); leave it. But this conflicts with the gate's
                # taxonomy (no flat reports/ files allowed). Default
                # such files into reports/audit/.
                dst = reports / "audit" / child.name
            err = _safe_move_file(child, dst, dry_run)
            rel_dst = dst.relative_to(project)
            mv = Move(src=f"reports/{child.name}",
                      dst=str(rel_dst), kind="file")
            if err:
                mv.note = err
                result.blocked.append(mv)
            else:
                result.moves.append(mv)

    return result


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description="Migrate stray entries to v1.6.26 canonical taxonomy.")
    ap.add_argument("project_dir")
    ap.add_argument("--dry-run", action="store_true",
                    help="Preview moves without touching the filesystem.")
    ap.add_argument("--json", help="write JSON migration report to this path")
    args = ap.parse_args(argv)

    project = Path(args.project_dir).resolve()
    if not project.is_dir():
        print(f"error: project dir not found: {project}", file=sys.stderr)
        return 2

    result = migrate(project, args.dry_run)

    report = {
        "tool": "migrate_to_canonical_taxonomy",
        "project": str(project),
        "dry_run": args.dry_run,
        "moves_planned" if args.dry_run else "moves_applied":
            [asdict(m) for m in result.moves],
        "blocked": [asdict(m) for m in result.blocked],
        "summary": {
            "moved": len(result.moves),
            "blocked": len(result.blocked),
        },
    }
    if args.json:
        out = Path(args.json)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(report, indent=2) + "\n")

    label = "PLANNED" if args.dry_run else "APPLIED"
    print(f"{label} {len(result.moves)} move(s); {len(result.blocked)} blocked")
    for m in result.moves[:20]:
        print(f"  [{m.kind}] {m.src} → {m.dst}")
    if len(result.moves) > 20:
        print(f"  … and {len(result.moves) - 20} more")
    if result.blocked:
        print(f"BLOCKED moves (manual review needed):", file=sys.stderr)
        for m in result.blocked:
            print(f"  [{m.kind}] {m.src} → {m.dst}: {m.note}",
                  file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
