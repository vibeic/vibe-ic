# ---------------------------------------------------------------------------
# IC-namespace → board-pin convention.
# Used only when L9.top_module ports use IC-level names (clk/reset_n/id_bus).
# Maps to a *single* board pin; bus ports require either a board wrapper
# (preferred) or explicit per-bit board pins.
# Chip-AGNOSTIC: this rule is "any clock-named port → CLOCK_50, any reset →
# KEY[0], any single-bit inout → GPIO_0[0]".
# ---------------------------------------------------------------------------
def _ic_port_to_board_signal(port_name: str) -> Optional[str]:
    """Return the board signal name (e.g. 'CLOCK_50', 'KEY[0]', 'GPIO_0[0]')
    for an IC-namespace port. None if no convention matches."""
    n = port_name.lower()
    if n in ("clk", "clock", "clk_in", "clk_50", "sysclk"):
        return "CLOCK_50"
    if "clk" in n or "clock" in n:
        return "CLOCK_50"
    if n in ("reset_n", "rst_n", "rstn", "reset", "rst"):
        return "KEY[0]"
    if "reset" in n or "rst" in n:
        return "KEY[0]"
    if n in ("id_bus", "id", "bus", "data", "io"):
        return "GPIO_0[0]"
    # Any other single-bit signal lands on a sequential GPIO_0 — caller
    # must allocate via _allocate_gpio0() instead.
    return None


# ---------------------------------------------------------------------------
# L9 reading
# ---------------------------------------------------------------------------
def _load_l9(project: Path) -> dict:
    p = _pl.generated_docs_dir(project) / "L9_INTEGRATION_SPEC.json"
    if not p.is_file():
        raise FileNotFoundError(f"missing L9: {p}")
    return json.loads(p.read_text(encoding="utf-8"))


def _list_rtl_files(project: Path) -> List[Path]:
    rtl = _pl.rtl_dir(project)
    if not rtl.is_dir():
        return []
    pkgs = sorted(p for p in rtl.glob("*pkg*.sv"))
    sv = sorted(p for p in rtl.glob("*.sv") if "pkg" not in p.name)
    v = sorted(p for p in rtl.glob("*.v"))
    return pkgs + sv + v


def _detect_board_wrapper(rtl_files: List[Path], board: str
                          ) -> Optional[Tuple[str, Path]]:
    """If a board-pin wrapper module exists (e.g. de10lite_top.sv with
    CLOCK_50/KEY/GPIO_0 ports), return (module_name, file_path)."""
    candidates = [f for f in rtl_files
                  if board.replace("-", "").lower() in f.name.lower()]
    for f in candidates:
        try:
            txt = f.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        if "CLOCK_50" in txt or "GPIO_0" in txt:
            # First module declared in the file
            for line in txt.splitlines():
                line = line.strip()
                if line.startswith("module "):
                    name = line.split()[1].split("(")[0].strip()
                    return (name, f)
    return None


