# Pin allocation
# ---------------------------------------------------------------------------
def _expand_port_signals(port: dict) -> List[str]:
    """A single L9 port entry may be vector or scalar. Returns the list of
    board-signal element names this port covers (e.g. KEY[0], KEY[1])."""
    name = port.get("name", "")
    width = port.get("width", 1)
    if isinstance(width, str):
        try:
            width = int(width, 0)
        except Exception:
            width = 1
    width = max(1, int(width or 1))
    if width == 1:
        # Caller decides whether name maps to scalar (CLOCK_50) or [0].
        return [name]
    return [f"{name}[{i}]" for i in range(width)]


def _resolve_board_signal(port_name: str, board: str
                          ) -> Tuple[Optional[str], Optional[str]]:
    """For a given port name, return (board_signal, board_pin).

    Tries direct match first (port already named CLOCK_50/KEY[0]/GPIO_0[0]),
    then IC-namespace heuristic.
    """
    if board != "de10lite":
        return (None, None)
    pin_map = _DE10LITE_PINS
    # 1. direct hit
    if port_name in pin_map:
        return (port_name, pin_map[port_name])
    # 2. IC-namespace convention
    sig = _ic_port_to_board_signal(port_name)
    if sig and sig in pin_map:
        return (sig, pin_map[sig])
    # 3. trailing index hint, e.g. ledr[0] → LEDR[0]
    upper = port_name.upper()
    if upper in pin_map:
        return (upper, pin_map[upper])
    return (None, None)


# ---------------------------------------------------------------------------
# QSF rendering
# ---------------------------------------------------------------------------
def _render_qsf(top: str, board: str, rtl_files: List[Path],
                fpga_dir: Path, port_assignments: List[Tuple[str, str, dict]],
                project_root: Path) -> str:
    """port_assignments = [(board_signal, pin, props), ...]"""
    if board != "de10lite":
        raise ValueError(f"unsupported board: {board}")
    dev = _DE10LITE_DEVICE
    lines: List[str] = []
    lines.append("# =========================================================================")
    lines.append(f"# Auto-generated by qsf_gen.py (Wave 72/73) — board={board}")
    lines.append(f"# Top entity: {top}")
    lines.append(f"# Source: L9_INTEGRATION_SPEC.json + rtl/")
    lines.append("# DO NOT hand-edit; regenerate via:")
    lines.append("#   python3 qsf_gen.py <project_dir>")
    lines.append("# =========================================================================")
    lines.append("")
    lines.append(f'set_global_assignment -name FAMILY                    "{dev["family"]}"')
    lines.append(f'set_global_assignment -name DEVICE                    {dev["device"]}')
    lines.append(f'set_global_assignment -name TOP_LEVEL_ENTITY          {top}')
    lines.append('set_global_assignment -name ORIGINAL_QUARTUS_VERSION  18.1')
    lines.append('set_global_assignment -name PROJECT_OUTPUT_DIRECTORY  output_files')
    lines.append(f'set_global_assignment -name MIN_CORE_JUNCTION_TEMP    {dev["min_core_temp"]}')
    lines.append(f'set_global_assignment -name MAX_CORE_JUNCTION_TEMP    {dev["max_core_temp"]}')
    lines.append('set_global_assignment -name ERROR_CHECK_FREQUENCY_DIVISOR 256')
    lines.append(f'set_global_assignment -name DEVICE_FILTER_PACKAGE     {dev["package"]}')
    lines.append(f'set_global_assignment -name DEVICE_FILTER_PIN_COUNT   {dev["pin_count"]}')
    lines.append(f'set_global_assignment -name DEVICE_FILTER_SPEED_GRADE {dev["speed_grade"]}')
    lines.append("")

    # SDC reference
    lines.append("# SDC constraints (peer file, generated by sdc_gen.py)")
    lines.append(f'set_global_assignment -name SDC_FILE                  {top}.sdc')
    lines.append("")

    # RTL sources — paths relative to fpga/ (project_dir/fpga is the QSF cwd)
    lines.append("# ----- RTL sources (relative to fpga/) ---------------------------------")
    lines.append('set_global_assignment -name SEARCH_PATH               ../rtl')

    # altsyncram / $readmemh init_file lookup: Quartus resolves init_file
    # parameters relative to the QSF cwd (fpga/) or any SEARCH_PATH entry.
    # Add every directory that ships *.mif / *.hex (excluding fpga/output_files/
    # to avoid pointing Quartus at its own outputs). chip-AGNOSTIC: discovered
    # by scan; no chip / vendor / file name hardcoded.
    # All paths in QSF are interpreted relative to the QSF cwd (fpga_dir),
    # not the project_root. Compute paths via os.path.relpath for portability
    # across canonical layout (phase2/stage1/fpga/) and any future layouts.
    import os as _os
    fpga_abs = fpga_dir.resolve()
    proj_abs = project_root.resolve()
    init_dirs: List[str] = []
    fpga_rel_parts = fpga_abs.relative_to(proj_abs).parts  # e.g. ('phase2','stage1','fpga')
    for ext in ("*.mif", "*.hex"):
        for f in project_root.rglob(ext):
            try:
                rel_parent = f.parent.resolve().relative_to(proj_abs)
            except ValueError:
                continue
            parts = rel_parent.parts
            # skip files inside the fpga build dir itself (already on SEARCH_PATH ".")
            if len(parts) >= len(fpga_rel_parts) and parts[:len(fpga_rel_parts)] == fpga_rel_parts:
                continue
            rel = _os.path.relpath(f.parent.resolve(), fpga_abs)
            if rel not in init_dirs:
                init_dirs.append(rel)
    if init_dirs:
        lines.append("# altsyncram/$readmemh init_file lookup (auto-discovered .mif/.hex dirs)")
        for d in init_dirs:
            lines.append(f'set_global_assignment -name SEARCH_PATH               {d}')
    for f in rtl_files:
        rel = _os.path.relpath(f.resolve(), fpga_abs)
        kind = "SYSTEMVERILOG_FILE" if f.suffix.lower() == ".sv" else "VERILOG_FILE"
        lines.append(f'set_global_assignment -name {kind}        {rel}')
    lines.append("")

    # Pin assignments
    lines.append("# ----- Pin assignments (board reference) -------------------------------")
    seen: Dict[str, str] = {}        # signal → pin
    seen_pins: Dict[str, str] = {}   # pin → signal (conflict detect)
    for sig, pin, props in port_assignments:
        if sig in seen:
            lines.append(f"# DUPLICATE skipped: {sig}")
            continue
        if pin in seen_pins:
            lines.append(f"# CONFLICT {sig} would collide with {seen_pins[pin]} on {pin} — skipped")
            continue
        seen[sig] = pin
        seen_pins[pin] = sig
        lines.append(f'set_location_assignment {pin} -to {sig}')
        io_std = props.get("io_standard", dev["default_io_standard"])
        lines.append(f'set_instance_assignment -name IO_STANDARD "{io_std}" -to {sig}')
        if props.get("weak_pull_up"):
            lines.append(f'set_instance_assignment -name WEAK_PULL_UP_RESISTOR ON -to {sig}')
        if props.get("output_open_drain"):
            lines.append(f'set_instance_assignment -name OUTPUT_OPEN_DRAIN ON -to {sig}')
    lines.append("")

    # Top-of-bus IO_STANDARD blanket (matches Wave 71 baseline)
    if any(s.startswith("GPIO_0[") for s, _, _ in port_assignments):
        lines.append('# Blanket IO_STANDARD for GPIO_0 vector')
        lines.append('set_instance_assignment -name IO_STANDARD "3.3-V LVTTL" -to GPIO_0')
        lines.append("")

    # Tail global assignments matching Wave 71 baseline
    lines.append(f'set_global_assignment -name STRATIX_DEVICE_IO_STANDARD "{dev["stratix_default_io_standard"]}"')
    lines.append("")
    lines.append("# MAX10 internal-flash mode that allows ROM init (.mif) inside altsyncram.")
    lines.append("# Default (Single Compressed Image) does not allow init; switch to one that does.")
    lines.append('set_global_assignment -name INTERNAL_FLASH_UPDATE_MODE "SINGLE COMP IMAGE WITH ERAM"')
    lines.append("")
    # Best-effort determinism. Pinning SEED narrows fitter randomness;
    # SMART_RECOMPILE off avoids cache-dependent re-seeding. These cut
    # the bit drift but do NOT make MAX10 Quartus 23.1 fully
    # bit-deterministic in this environment — empirically the .sof
    # hash still differs run-to-run (likely from parallel placement
    # ordering and embedded build-id metadata). The load-bearing fix
    # remains the v1.6.49 final_summary regen between fpga_compile
    # and fpga_burn (so the attestation table reflects the just-built
    # SOF). Keeping these flags anyway: they reduce SOF drift on
    # incremental rebuilds and make seed-pinned regression diffs more
    # tractable.
    lines.append("set_global_assignment -name SEED 1")
    lines.append("set_global_assignment -name SMART_RECOMPILE OFF")
    lines.append("")
    lines.append('set_global_assignment -name LAST_QUARTUS_VERSION "23.1std.0 Lite Edition"')
    lines.append("")
    return "\n".join(lines) + "\n"


