#!/usr/bin/env python3
"""qsf_gen.py — auto-generate Quartus QSF (FPGA pin assignments).

Wave 72 deliverable. Wave 73 (v0.128) renamed from aid_class_qsf_gen.py
to reflect that the generator is class-AGNOSTIC: it works for any chip
whose L9 declares its top-module pins, not just AID-class ICs. A
backwards-compat shim at the old path forwards calls until v0.130.

Closes the last manual-prep gap so a fresh-agent can go from empty
input/ → byte[6] verdict in one phase23_one_shot_runner call.

The QSF is BOARD-specific (default DE10-Lite) but chip-AGNOSTIC: pin names,
device family/part, and IO standards come from the board manual; nothing
about the chip-under-test (<chip-class> / <PDK> / etc.) is hardcoded.

Inputs (read from <project_dir>):
    generated_docs/L9_INTEGRATION_SPEC.json
        - top_module                  → TOP_LEVEL_ENTITY (after wrapper choice)
        - top_module_pins[]           → port-to-board-signal mapping
        - submodules[*].file          → RTL file list (fallback: rtl/*.{sv,v})

Optional:
    rtl/<board>_top.sv (e.g. rtl/de10lite_top.sv)
        If present, that wrapper module is used as TOP_LEVEL_ENTITY and its
        ports drive the pin map directly (CLOCK_50/KEY/GPIO_0 → board pins).
        This matches the Wave 71 hand-written QSF baseline.

    input/docs/DE10-Lite_User_Manual.pdf or input_doc/DE10-Lite_User_Manual.txt
        Future hook for dynamic pin extraction. Currently the DE10-Lite pin
        map is embedded as a literal table (sourced verbatim from Terasic's
        public DE10-Lite User Manual v1.2 §3 pin-out tables).

Output:
    <project_dir>/fpga/<top>.qsf

Logic (chip-AGNOSTIC):
    1. Pick top_module:
        a. If rtl/<board>_top.sv exists → use it (board-pin namespace).
        b. Else use L9.top_module (IC-namespace ports — auto-mapped).
    2. Resolve every top-module port → board pin via _BOARD_PIN_MAP rules:
         CLOCK_50 / clk*       → P11
         reset_n / KEY[0]      → B8
         id_bus / GPIO_0[0]    → V10  (open-drain single-wire, weak-pull-up)
         GPIO_0[N]             → board GPIO_0 header pin
         GPIO_1[N]             → board GPIO_1 header pin
         LEDR[N] / led*[N]     → board LEDR pin
         KEY[N]                → board KEY pin
         SW[N]                 → board SW pin
         HEXn[m]               → board HEX seven-seg pin
       Any port not in the map is reported as a WARN comment in the QSF.
    3. Emit QSF with global assignments + RTL file list (sorted: pkg → sv → v)
       + pin assignments + IO_STANDARD + (open-drain → WEAK_PULL_UP_RESISTOR).
       SDC_FILE points to <top>.sdc (peer file, generated by sdc_gen).

CLI:
    python3 qsf_gen.py <project_dir> [--board de10lite]
                                      [--top-name chip_top]
                                      [--force]

Exit codes:
    0  PASS (QSF generated)
    1  FAIL (missing L9 or RTL)
    2  IO / arg error
"""
