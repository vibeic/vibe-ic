# Driver
# ---------------------------------------------------------------------------
def _build_port_assignments_from_wrapper(rtl_file: Path, board: str
                                         ) -> List[Tuple[str, str, dict]]:
    """Parse a board-pin wrapper file and return board pin assignments
    for each port. Wrapper ports are board-namespace already."""
    txt = rtl_file.read_text(encoding="utf-8", errors="ignore")
    # naive port list extraction between first '(' and ')' after 'module'
    if "module " not in txt:
        return []
    after = txt.split("module ", 1)[1]
    if "(" not in after or ")" not in after:
        return []
    port_block = after.split("(", 1)[1]
    depth = 1
    chars: List[str] = []
    for c in port_block:
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                break
        chars.append(c)
    body = "".join(chars)
    assignments: List[Tuple[str, str, dict]] = []
    for raw in body.split(","):
        line = raw.strip().split("//")[0].strip()
        if not line:
            continue
        # patterns:
        #   input  wire CLOCK_50
        #   input  wire [1:0] KEY
        #   inout  wire [35:0] GPIO_0
        toks = line.replace(",", " ").split()
        # find vector range and identifier
        ident = None
        width = 1
        offset = 0
        for i, t in enumerate(toks):
            if t.startswith("[") and "]" in t:
                # vector spec like [35:0]
                inner = t.strip("[]")
                if ":" in inner:
                    try:
                        hi, lo = inner.split(":")
                        hi = int(hi); lo = int(lo)
                        width = abs(hi - lo) + 1
                        offset = min(hi, lo)
                    except Exception:
                        pass
            elif t in ("input", "output", "inout", "wire", "reg", "logic"):
                continue
            elif t.isidentifier():
                ident = t
        if not ident:
            continue
        # build per-bit signals
        if width == 1:
            sigs = [ident]
        else:
            sigs = [f"{ident}[{offset+i}]" for i in range(width)]
        for s in sigs:
            sig, pin = _resolve_board_signal(s, board)
            if not sig or not pin:
                continue
            props: dict = {"io_standard": _DE10LITE_DEVICE["default_io_standard"]}
            if sig in _DE10LITE_BOARD_OPEN_DRAIN_PORTS or sig in _DE10LITE_WEAK_PULLUP_PORTS:
                props["weak_pull_up"] = True
            assignments.append((sig, pin, props))
    return assignments


def _build_port_assignments_from_l9(l9: dict, board: str
                                    ) -> List[Tuple[str, str, dict]]:
    out: List[Tuple[str, str, dict]] = []
    for port in l9.get("top_module_pins", []):
        if not isinstance(port, dict):
            continue
        name = port.get("name")
        io_kind = str(port.get("io", "")).lower()
        mode = str(port.get("mode", "")).lower()
        # Wave 73 (v0.128) S3 — explicit L9 flag drives OUTPUT_OPEN_DRAIN.
        # An entry like {"name": "scl", "open_drain": true} now produces
        # `set_instance_assignment -name OUTPUT_OPEN_DRAIN ON -to scl`.
        l9_open_drain = bool(port.get("open_drain", False))
        if not name:
            continue
        sig, pin = _resolve_board_signal(name, board)
        if not sig or not pin:
            continue
        props: dict = {"io_standard": _DE10LITE_DEVICE["default_io_standard"]}

        # Open-drain inference: prefer the explicit L9 flag; the
        # io-string heuristic stays as a fallback for legacy fixtures
        # that say io: "open-drain" without an open_drain bool.
        io_string_says_od = (
            "open-drain" in io_kind or "open_drain" in io_kind
        )
        if l9_open_drain or io_string_says_od:
            props["weak_pull_up"] = True
            props["output_open_drain"] = True

        # inout pins (without an explicit open-drain flag) still get a
        # weak pull-up (legacy <chip-class> behaviour) but NOT the
        # OUTPUT_OPEN_DRAIN attribute — that only fires when L9 says so.
        if mode == "inout" and not (l9_open_drain or io_string_says_od):
            props["weak_pull_up"] = True

        if sig in _DE10LITE_WEAK_PULLUP_PORTS:
            props["weak_pull_up"] = True
        out.append((sig, pin, props))
    return out


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("project", type=Path)
    p.add_argument("--board", default="de10lite",
                   choices=["de10lite"])
    p.add_argument("--top-name", default=None,
                   help="Override TOP_LEVEL_ENTITY (default: auto-detect "
                        "board wrapper, else L9.top_module).")
    p.add_argument("--force", action="store_true",
                   help="Overwrite existing QSF.")
    args = p.parse_args()

    project = args.project.resolve()
    if not project.is_dir():
        print(f"ERROR: not a directory: {project}", file=sys.stderr)
        return 2

    try:
        l9 = _load_l9(project)
    except FileNotFoundError as e:
        print(f"FAIL: {e}", file=sys.stderr)
        return 1

    rtl_files = _list_rtl_files(project)
    if not rtl_files:
        print(f"FAIL: rtl/ empty under {project}", file=sys.stderr)
        return 1

    # Decide top entity
    wrapper = _detect_board_wrapper(rtl_files, args.board)
    if args.top_name:
        top = args.top_name
        wrapper_file = next((f for f in rtl_files
                             if f.read_text(encoding="utf-8", errors="ignore")
                             .find(f"module {top}") >= 0), None)
    elif wrapper:
        top, wrapper_file = wrapper
    else:
        top = l9.get("top_module") or "chip_top"
        wrapper_file = None

    # Build pin assignments
    if wrapper_file is not None:
        port_assignments = _build_port_assignments_from_wrapper(wrapper_file, args.board)
        source = f"wrapper {wrapper_file.name}"
    else:
        port_assignments = _build_port_assignments_from_l9(l9, args.board)
        source = "L9.top_module_pins"

    if not port_assignments:
        print(f"FAIL: no port→board-pin mapping resolved (source={source}). "
              f"Top {top!r} ports do not match board {args.board}.",
              file=sys.stderr)
        return 1

    # Render and write
    fpga_dir = _pl.fpga_early_dir(project)
    fpga_dir.mkdir(parents=True, exist_ok=True)
    out = fpga_dir / f"{top}.qsf"
    if out.exists() and not args.force:
        print(f"SKIP: {out} exists (use --force to overwrite)")
        return 0
    text = _render_qsf(top, args.board, rtl_files, fpga_dir,
                       port_assignments, project)
    out.write_text(text, encoding="utf-8")

    # also emit minimal .qpf so quartus_sh --flow compile works on bare project
    qpf = fpga_dir / f"{top}.qpf"
    if not qpf.exists() or args.force:
        qpf.write_text(
            "QUARTUS_VERSION = \"18.1\"\n"
            "DATE = \"Auto-generated by qsf_gen.py\"\n\n"
            f"PROJECT_REVISION = \"{top}\"\n",
            encoding="utf-8")

    print(f"PASS qsf_gen: {out} "
          f"({len(port_assignments)} pins, top={top!r}, source={source})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
