#!/usr/bin/env python3
"""
protocol_gap_check.py — Generate inter-unit gap assertions for any serial protocol.

Every byte-oriented or frame-oriented serial protocol requires a *gap* between
atomic transmission units:
  - UART: stop bit
  - I2C: STOP condition
  - SPI: CS deassert
  - Apple Lightning / AID: Inter-Byte Time (IBT)
  - CAN: intermission field
  - USB: EOP

During <half-duplex-tester> debug (2026-04-16) we found our TX state machine skipped IBT
(jumping straight from S_HIGH → S_IDLE instead of S_IBT), producing byte streams
with 0-cycle gaps that the host couldn't parse.

This tool generates SystemVerilog Assertions that verify:

  (A) atomic_unit_end |-> bus_idle_for_at_least_N_cycles
  (B) gap_min_cycles sampled from spec (user-provided)
  (C) optional: gap_max_cycles (for frame-oriented protocols with timeout)

Usage:
    python3 protocol_gap_check.py \\
        --name lightning_ibt \\
        --end-signal tx_byte_done \\
        --bus-idle "!id_bus_oe && id_bus_rx" \\
        --min-cycles 41 --max-cycles 50 \\
        --out-dir /tmp/gap_check

Generality: works for ANY serial protocol with an atomic-unit-end signal and
an idle condition. Parameterized by (end, idle-expr, min, max). Not tied to
any specific protocol or IC.
"""
from __future__ import annotations
import argparse
import sys
from pathlib import Path


SVA_TEMPLATE = """\
// Generated by protocol_gap_check.py — {name}
// Verifies inter-unit gap on a serial protocol:
//   After {end_signal} pulses, bus must be idle for at least {min_cycles} cycles.
//   (Optional) idle no longer than {max_cycles} cycles before next unit starts.

module {name}_gap_assertions (
    input wire clk,
    input wire rst_n,
    input wire {end_signal},    // pulses at end of atomic unit (byte/frame)
    input wire bus_idle          // user-defined idle expression
);

    // (A) Minimum gap: after unit end, bus_idle holds for min_cycles cycles
    property p_min_gap;
        @(posedge clk) disable iff (!rst_n)
        {end_signal} |=> bus_idle[*{min_cycles}];
    endproperty
    a_min_gap: assert property (p_min_gap);

{max_block}
    // (Cov) Useful to sanity-check the property fires at all in sim/formal
    cov_end_pulse: cover property (
        @(posedge clk) disable iff (!rst_n) {end_signal}
    );

endmodule
"""

MAX_BLOCK_TEMPLATE = """\
    // (B) Maximum gap: if no next unit starts within max_cycles, that's a timeout
    //     (flagged as cover — informational, may be intentional idle)
    property p_max_gap_timeout;
        @(posedge clk) disable iff (!rst_n)
        {end_signal} ##1 bus_idle[*{max_cycles}] ##1 bus_idle;
    endproperty
    cov_max_gap_timeout: cover property (p_max_gap_timeout);

"""

SBY_TEMPLATE = """\
[options]
mode bmc
depth {depth}

[engines]
smtbmc

[script]
read -sv {name}_gap_assertions.sv
prep -top {name}_gap_assertions

[files]
{name}_gap_assertions.sv
"""


def gen_sva(name: str, end_signal: str, min_cycles: int, max_cycles: int) -> str:
    max_block = ""
    if max_cycles > 0:
        max_block = MAX_BLOCK_TEMPLATE.format(
            end_signal=end_signal, max_cycles=max_cycles)
    return SVA_TEMPLATE.format(
        name=name, end_signal=end_signal, min_cycles=min_cycles,
        max_cycles=max_cycles if max_cycles > 0 else 'n/a',
        max_block=max_block)


def gen_sby(name: str, min_cycles: int, max_cycles: int) -> str:
    depth = max(min_cycles, max_cycles, 20) + 10
    return SBY_TEMPLATE.format(name=name, depth=depth)


def gen_readme(name: str, end_signal: str, bus_idle_expr: str,
               min_cycles: int, max_cycles: int) -> str:
    return f"""\
# {name} Protocol Gap Check

Auto-generated assertions verifying inter-unit gap timing.

## Spec

- **End-of-unit signal**: `{end_signal}`
- **Bus idle expression**: `{bus_idle_expr}`
- **Min gap**: {min_cycles} clock cycles
- **Max gap** (cover): {max_cycles if max_cycles > 0 else 'disabled'} clock cycles

## Properties

1. **Min gap** (assert) — after every `{end_signal}` pulse, `bus_idle` must
   hold for at least `{min_cycles}` consecutive cycles before any new drive.
2. **Max gap** (cover) — informational check that gaps can reach the spec
   maximum, useful for finding deadlocks or missed handshakes.

## Run

```bash
sby -f {name}_gap.sby
```

## Integration

Use SystemVerilog `bind` to hook the assertions to the real design:

```systemverilog
bind tx_phy {name}_gap_assertions {name}_check_inst (
    .clk(clk), .rst_n(rst_n),
    .{end_signal}(tx_done),
    .bus_idle({bus_idle_expr})
);
```

## Why this exists

During <half-duplex-tester> debug we found the TX FSM transitioned S_HIGH → S_IDLE
without visiting S_IBT (the inter-byte time state), producing zero-gap byte
streams. A formal assertion of this kind would have caught the bug before
hardware integration.
"""


def main():
    ap = argparse.ArgumentParser(description='Generate serial protocol gap assertions')
    ap.add_argument('--name', required=True, help='property name prefix (e.g. lightning_ibt)')
    ap.add_argument('--end-signal', required=True,
                    help='wire name that pulses at end of atomic unit')
    ap.add_argument('--bus-idle', required=True,
                    help='expression evaluating to 1 when bus is idle')
    ap.add_argument('--min-cycles', type=int, required=True,
                    help='minimum gap in clock cycles')
    ap.add_argument('--max-cycles', type=int, default=0,
                    help='maximum gap in clock cycles (0 = disable max)')
    ap.add_argument('--out-dir', required=True)
    args = ap.parse_args()

    if args.min_cycles <= 0:
        print("ERROR: --min-cycles must be > 0", file=sys.stderr)
        return 2

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    sva_file = out / f"{args.name}_gap_assertions.sv"
    sby_file = out / f"{args.name}_gap.sby"
    readme = out / f"README_{args.name}.md"

    sva_file.write_text(gen_sva(args.name, args.end_signal,
                                args.min_cycles, args.max_cycles))
    sby_file.write_text(gen_sby(args.name, args.min_cycles, args.max_cycles))
    readme.write_text(gen_readme(args.name, args.end_signal, args.bus_idle,
                                 args.min_cycles, args.max_cycles))
    print(f"Generated in {out}:")
    print(f"  {sva_file.name}")
    print(f"  {sby_file.name}")
    print(f"  {readme.name}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
