"""tests/test_analog_a1_a4_flow_declared_layout.py

PR #465 follow-up. #465 taught the A1-A4 gates to resolve a per-block
ARTEFACT under more than one analog root, but left the BLOCK LIST that gates
access to those artefacts readable at exactly one path — so on the only two
layouts a real producer creates, every one of #465's three fixes was
unreachable.

MEASURED on main @ bd2e11520 (v1.7.58), project laid out exactly as
flow/phase1_phase2_phase3.yaml declares (block list at
`phase1/analog/analog_block_list.json` — the path EVERY A-step's
`condition:` pins — A1's spec at `phase1/analog/<blk>/`, A2-A4's artefacts at
`phase2/analog/<blk>/`, a second block declared with nothing):

    analog_a1_spec_extract_check <proj>  -> rc=0 VACUOUS_PASS
      "phase3/analog/analog_block_list.json missing or empty;
       gate inapplicable."
    ... identical for a2 / a3 / a4.

i.e. the flow ACTIVATED A1-A4 (their condition reads the phase1 copy) and
then accepted a rc=0 from four gates that had loaded no block list at all.
#465's newly wired blocking A3 sub-gate was tautological there: it cannot
reach a non-zero exit on the layout the flow declares.

The second real layout is the one `migrate_to_layout_p.py` produces. MEASURED
by running the production migrator on a pre-v2 project: it emits exactly two
moves — `analog/analog_block_list.json -> phase1/analog/...` and
`analog/<block> -> phase2/analog/<block>`. `_classify_analog_block` picks ONE
most-backend destination for the WHOLE block dir, so A1's spec.json lands
under `phase2/analog/`, NOT the `phase1/analog/` the flow declares as A1's
required_output — which #465's {canonical, declared-phase} candidate pair
also missed.

These tests build both layouts with the block list where its OWN producer
puts it (the migrator layout is built by INVOKING the production migrator),
never the phase3-list / phase1-artefact hybrid that no producer creates.

Run: PYTEST_DISABLE_PLUGIN_AUTOLOAD=1 python3 -m pytest tests/<this file>
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

PROGRAMS = Path(__file__).resolve().parent.parent

A1 = PROGRAMS / "analog_a1_spec_extract_check.py"
A2 = PROGRAMS / "analog_a2_topology_select_check.py"
A3 = PROGRAMS / "analog_a3_netlist_gen_check.py"
A4 = PROGRAMS / "analog_a4_corner_sweep_check.py"
MIGRATE = PROGRAMS / "migrate_to_layout_p.py"

# (gate program, artefact filename, root the flow declares for that step)
GATES = [
    pytest.param(A1, "spec.json", "phase1/analog", id="A1"),
    pytest.param(A2, "topology.md", "phase2/analog", id="A2"),
    pytest.param(A3, "{block}.sp", "phase2/analog", id="A3"),
    pytest.param(A4, "corner_results.json", "phase2/analog", id="A4"),
]

_TOPOLOGY = (
    "# Topology\n\n"
    "Two-stage differential amplifier: an NMOS differential pair with a PMOS "
    "current mirror load, a common-source output stage, and Miller feedback "
    "compensation. Tail bias comes from a widlar reference. The dominant pole "
    "sits at the first stage; the right-half-plane zero is cancelled by a "
    "nulling resistor sized against the load capacitor.\n"
)
_NETLIST = (
    "* block netlist\n"
    '.include "design.ngspice"\n'
    ".subckt {block} VDD VSS VOUT VREF EN\n"
    + "M1 net1 VREF VSS VSS nmos w=2u l=0.18u\n" * 6
    + ".ends {block}\n.end\n"
)
# >200 bytes, has `.subckt`, ZERO device cards inside the body: the
# placeholder shape A3_NETLIST_NO_DEVICES exists to reject.
_EMPTY_SHELL = (
    "* {block} — SPICE netlist\n"
    "* Generated by the analog-netlist-gen skill.\n"
    "* PDK model library include:\n"
    '.include "design.ngspice"\n'
    "*\n"
    "* Interface: vdd (supply), vss (ground), vin (input), vout (output)\n"
    "*\n"
    ".subckt {block} vdd vss vin vout\n"
    "* --- device instantiations go here ---\n"
    ".ends {block}\n"
    ".end\n"
)
_CORNERS = {
    "_provenance": "real_ngspice",
    "best_corner": {"name": "tt_27"},
    "corners": [
        {"name": "tt_27", "simulator_run": True, "vout_v": 1.2},
        {"name": "ss_125", "simulator_run": True, "vout_v": 1.21},
        {"name": "ff_m40", "simulator_run": True, "vout_v": 1.19},
    ],
    "spec_results": [
        {"name": "vout", "status": "PASS", "target": 1.2,
         "tolerance_pct": 0.05},
    ],
}


# ── fixture helpers ────────────────────────────────────────────────────────

def _write_block_list(project: Path, blocks: list, root: str) -> None:
    d = project / root
    d.mkdir(parents=True, exist_ok=True)
    (d / "analog_block_list.json").write_text(json.dumps({"blocks": blocks}))


def _write_artefact(project: Path, block: str, filename: str,
                    root: str) -> None:
    name = filename.format(block=block)
    d = project / root / block
    d.mkdir(parents=True, exist_ok=True)
    if name == "spec.json":
        (d / name).write_text(json.dumps(
            {"specs": [{"name": "vout", "typ": 1.2, "min": 1.1, "max": 1.3}]}))
    elif name == "topology.md":
        (d / name).write_text(_TOPOLOGY)
    elif name == "corner_results.json":
        (d / name).write_text(json.dumps(_CORNERS))
    elif name.endswith(".sp"):
        (d / name).write_text(_NETLIST.format(block=block))
    else:                                       # pragma: no cover
        raise AssertionError(f"unhandled artefact {name}")


def _all_artefacts(project: Path, block: str, root: str) -> None:
    """Every A1-A4 artefact for one block under a SINGLE root — the shape a
    pre-v2 `analog/<block>/` dir has, and therefore the shape
    `migrate_to_layout_p.py` relocates as one unit."""
    for _prog, filename, _declared in [(p.values[0], p.values[1], p.values[2])
                                       for p in GATES]:
        _write_artefact(project, block, filename, root)


def _run(prog: Path, project: Path, *args: str,
         report: str = "report.json") -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(prog), str(project),
         "--json", str(project / report), *args],
        capture_output=True, text=True)


def _report(project: Path, report: str = "report.json") -> dict:
    return json.loads((project / report).read_text())


def _flow_declared_project(project: Path) -> None:
    """The layout flow/phase1_phase2_phase3.yaml declares: block list where
    every A-step's `condition:` pins it, A1's spec at phase1/analog, A2-A4's
    artefacts at phase2/analog. `blk_none` is declared and produces nothing."""
    _write_block_list(project, ["blk_ok", "blk_none"], "phase1/analog")
    for param in GATES:
        _prog, filename, declared_root = param.values
        _write_artefact(project, "blk_ok", filename, declared_root)


def _migrated_project(project: Path, blocks: list) -> None:
    """A pre-v2 project put through the PRODUCTION migrator. Only the FIRST
    block gets artefacts; the rest are declared and empty."""
    _write_block_list(project, blocks, "analog")
    _all_artefacts(project, blocks[0], "analog")
    cp = subprocess.run(
        [sys.executable, str(MIGRATE), str(project), "--no-git"],
        capture_output=True, text=True)
    assert cp.returncode == 0, (cp.stdout, cp.stderr)


