# What each gate names as the `rel_path` of an artefact that exists at NO
# candidate. Byte-identical to what the pre-#465 tree reported: A1-A3 name the
# canonical runner path, A4 keeps its own legacy `analog/<block>/...` literal
# (predates #465 — `analog_a4_corner_sweep_check.py:139`). Pinned per gate so
# widening the candidate list cannot silently change what an operator is told
# to go create.
_MISSING_REL_PREFIX = {
    "analog_a1_spec_extract_check.py": "phase3/analog/",
    "analog_a2_topology_select_check.py": "phase3/analog/",
    "analog_a3_netlist_gen_check.py": "phase3/analog/",
    "analog_a4_corner_sweep_check.py": "analog/",
}


@pytest.mark.parametrize("prog,filename,declared_root", GATES)
def test_guard_missing_artefact_rel_path_is_unchanged(
        tmp_path: Path, prog: Path, filename: str, declared_root: str
) -> None:
    """When NO candidate exists the reported `rel_path` is exactly what these
    gates have always named. Widening the candidate list must not change what
    an operator is told to go create."""
    _write_block_list(tmp_path, ["blk_ok", "blk_none"], "phase3/analog")
    _write_artefact(tmp_path, "blk_ok", filename, "phase3/analog")
    r = _run(prog, tmp_path)
    assert r.returncode == 1, (prog.name, r.stdout, r.stderr)
    findings = _report(tmp_path)["findings"]
    miss = [f for f in findings if f.get("block") == "blk_none"]
    assert miss, findings
    want = _MISSING_REL_PREFIX[prog.name]
    assert all(f["rel_path"] == f"{want}blk_none/{filename.format(block='blk_none')}"
               for f in miss), (want, miss)


