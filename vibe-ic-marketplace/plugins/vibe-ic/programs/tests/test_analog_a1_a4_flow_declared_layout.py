def test_vacuous_reason_names_every_location_probed(tmp_path: Path) -> None:
    """The VACUOUS_PASS reason must not claim a single path was the only one
    looked at. On main it reads
    "phase3/analog/analog_block_list.json missing or empty" while the gate's
    own step condition pins the phase1 copy — a message that told the reader
    the gate had checked somewhere it had not."""
    r = _run(A1, tmp_path)
    assert r.returncode == 0, (r.stdout, r.stderr)
    reason = _report(tmp_path)["reason"]
    for rel in ("phase3/analog/analog_block_list.json",
                "phase1/analog/analog_block_list.json",
                "analog/analog_block_list.json"):
        assert rel in reason, (rel, reason)


