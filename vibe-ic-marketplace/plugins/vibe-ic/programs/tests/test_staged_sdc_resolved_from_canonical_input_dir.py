#!/usr/bin/env python3
"""step_pnr must resolve the design's SDC from the tree's SHARED contract.

The defect: `step_pnr` globbed `constraints/*.sdc` (project ROOT) and
`phase2/stage2/constraints/*.sdc` to decide whether the design staged an SDC.
Neither is the ground truth. `sdc_constraints.collect_sdc_files` — the shared
accessor used by every OTHER staged-SDC consumer in the same file — defines it
as `input/constraints/*.sdc` then `input/reference_flow/**/*.sdc`, and
documents `extra_dirs` as appending AFTER that ground truth.

Measured on the authoring host: the project-root probe matched on 0 of 10
projects, while `phase2/stage2/constraints/<top>.sdc` matched because
`step_canonicalize_artefacts` writes the runner's OWN auto-SDC there — so the
miss laundered a fabricated SDC into "design-staged" on every later run, and a
design's real `create_clock -name core_clock` never reached PnR or STA.

BIDIRECTIONAL NEGATIVE CONTROL: the first two tests FAIL against the pre-fix
code (the input-dir SDC is not resolved; the auto-SDC is emitted instead). The
remaining tests pass BOTH ways — they are the guards that pin the blast radius:
the legacy directories still resolve, and honoring a staged SDC must not leave
the I/O boundary untimed.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import sdc_constraints as _sdc  # noqa: E402


def _mkproj(tmp_path: Path, where: str, text: str) -> Path:
    proj = tmp_path / "proj"
    d = proj / where
    d.mkdir(parents=True, exist_ok=True)
    (d / "clock.sdc").write_text(text)
    return proj


DESIGN_SDC = (
    "# design-authored\n"
    "set_units -time ns\n"
    "create_clock [get_ports clk] -name core_clock -period 10.0\n"
)


AUTO_SDC = (
    "# Auto-generated minimal SDC for silicon top "
    "(no constraints/*.sdc supplied; clk_period_ns=10.0 clk_port=clk)\n"
    "create_clock -name clk -period 10.0 [get_ports clk]\n"
)

SDC_GEN_OUTPUT = (
    "# Auto-generated by sdc_gen.py (Wave 72/73)\n"
    "# Top entity: top\n"
    "# Clock: clk period=10 ns\n"
    "create_clock -name clk -period 10 [get_ports clk]\n"
)




# ---------------------------------------------------------------- the defect









# ------------------------------------------------- guards (pass BOTH ways)

@pytest.mark.parametrize("legacy", ["constraints",
                                    "phase2/stage2/constraints"])
def test_legacy_dirs_still_resolve_when_they_are_the_only_source(tmp_path,
                                                                 legacy):
    """Blast radius: a project that resolved an SDC before still resolves it."""
    proj = _mkproj(tmp_path, legacy, DESIGN_SDC)
    found = next(iter(_sdc.collect_sdc_files(
        proj, extra_dirs=[proj / "constraints",
                          proj / "phase2/stage2/constraints"])), None)
    assert found is not None, f"legacy dir {legacy} stopped resolving"
