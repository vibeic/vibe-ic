# DEFECT 1 — discriminators: partial block coverage must not certify a step
# ══════════════════════════════════════════════════════════════════════════

@pytest.mark.parametrize("prog,filename,declared_root", GATES)
def test_partial_block_coverage_is_incomplete(
        tmp_path: Path, prog: Path, filename: str, declared_root: str
) -> None:
    """1 of 2 declared blocks has the artefact → rc=1 INCOMPLETE.

    On the base tree every one of these exits 0 with verdict PASS.
    """
    _block_list(tmp_path, ["blk_ok", "blk_missing"])
    _artefact(tmp_path, "blk_ok", filename)
    r = _run(prog, tmp_path)
    assert r.returncode == 1, (prog.name, r.stdout, r.stderr)
    rpt = _report(tmp_path)
    assert rpt["verdict"] == "INCOMPLETE", rpt
    assert rpt["blocks_pass"] == 1
    assert rpt["blocks_missing"] == 1
    # The uncovered block must be NAMED — a count alone is not actionable.
    assert rpt["incomplete_blocks"] == ["blk_missing"], rpt
    assert "blk_missing" in r.stderr


@pytest.mark.parametrize("prog,filename,declared_root", GATES)
def test_partial_block_coverage_scales_to_many_blocks(
        tmp_path: Path, prog: Path, filename: str, declared_root: str
) -> None:
    """5 declared blocks, 1 covered → INCOMPLETE naming the other 4."""
    blocks = [f"blk{i}" for i in range(5)]
    _block_list(tmp_path, blocks)
    _artefact(tmp_path, "blk0", filename)
    r = _run(prog, tmp_path)
    assert r.returncode == 1, (prog.name, r.stdout, r.stderr)
    rpt = _report(tmp_path)
    assert rpt["verdict"] == "INCOMPLETE"
    assert rpt["blocks_checked"] == 5
    assert rpt["blocks_pass"] == 1
    assert sorted(rpt["incomplete_blocks"]) == blocks[1:]


