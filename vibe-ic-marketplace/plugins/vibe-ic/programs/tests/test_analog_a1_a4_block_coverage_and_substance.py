def test_guard_a3_runner_deterministic_stub_still_passes(
        tmp_path: Path) -> None:
    """The analog runner's OWN deterministic-stub `.sp` must not newly FAIL.

    `analog_one_shot_runner._emit_deterministic_stub` writes a marked
    `.subckt` carrying `r_stub vin vout 1k`. That IS a device card, so the
    PASS_WITH_STUB benchmark tier survives the new rule — this guard pins
    that, so a future stub template that drops the card is caught here
    rather than in the field.
    """
    _block_list(tmp_path, ["ldo"])
    d = tmp_path / "phase3/analog/ldo"
    d.mkdir(parents=True, exist_ok=True)
    (d / "ldo.sp").write_text(
        "* deterministic_stub extraction_strategy=deterministic_stub "
        "block=ldo step=A3_netlist_gen — replace with real analog output\n"
        "* ldo — SPICE netlist (stub)\n"
        ".subckt ldo vdd vss vin vout\n"
        "* replace with extracted netlist when analog-netlist-gen skill runs\n"
        "r_stub vin vout 1k\n"
        ".ends ldo\n")
