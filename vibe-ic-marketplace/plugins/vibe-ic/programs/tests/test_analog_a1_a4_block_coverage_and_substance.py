"""tests/test_analog_a1_a4_block_coverage_and_substance.py

Behavioural discriminators for three defects in the A1-A4 deterministic
gates, plus direction-1 guards for every carve-out that must NOT change.

DEFECT 1 — partial block coverage absorbed into PASS (A1/d5, A2/d5, A4/d2,
           and the same shape in A3).
  The project-mode tail of each gate was:

      if findings:                        -> FAIL
      if missing_seen and blocks_pass==0: -> VACUOUS_PASS
      return emit_pass(...)               # <- mixed PASS + missing

  so a run where the upstream skill produced an artefact for 1 of N
  declared blocks exited 0 with verdict PASS. The flow declaration cannot
  compensate: each A-step declares ONE glob (`phase2/analog/*/topology.md`)
  and `flow_compliance_check` satisfies a glob entry on its FIRST match, so
  per-block coverage is knowable only inside the gate.

DEFECT 2 — A3 certified an empty `.subckt` shell.
  `analog_a3_netlist_gen_check`'s only substance rules were "size >= 200B"
  and "contains .subckt". A placeholder padded with header comments clears
  both. `analog_netlist_pdk_check` (A3's gate of record) cannot catch it
  either: its rules iterate DEVICE cards, so zero devices == zero findings
  == NETLIST_PDK_OK.

DEFECT 3 — the A3 gates never read the flow-declared path.
  `flow/phase1_phase2_phase3.yaml` declares A3's required_output as
  `phase2/analog/*/*.sp` (and A1's as `phase1/analog/*/spec.json`), matching
  `_path_layout.phase2_analog_block_dir` / `phase1_analog_block_dir` and what
  `migrate_to_layout_p.py` produces. Every A1-A4 gate hardcoded
  `phase3/analog/` (where the analog RUNNER writes), so a project laid out
  exactly as its own flow declares self-skipped and measured nothing.

Run: PYTEST_DISABLE_PLUGIN_AUTOLOAD=1 python3 -m pytest tests/<this file>
"""
