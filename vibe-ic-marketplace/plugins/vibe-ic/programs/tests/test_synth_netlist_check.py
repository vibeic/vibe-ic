"""Unit tests for synth_netlist_check.py.

Tests verify correct detection of missing/empty/too-small synthesis netlists,
including valid netlists, comment-only files, and wire-only files.
"""
import json
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).parent.parent / 'synth_netlist_check.py'
assert SCRIPT.exists(), f"Script not found: {SCRIPT}"

sys.path.insert(0, str(SCRIPT.parent))
import synth_netlist_check as snc  # noqa: E402


# ---------------------------------------------------------------------------
# Fixture: netlist templates
# ---------------------------------------------------------------------------
def make_netlist_with_n_cells(n: int) -> str:
    """Generate a netlist with n cell instances."""
    lines = [
        "module synth_design (",
        "    input wire clk,",
        "    input wire rst_n,",
        "    output wire [7:0] data_out",
        ");",
        "",
    ]
    for i in range(n):
        lines.append(f"    sky130_fd_sc_hd__inv_2 _{i:04d}_ (.A(clk), .Y(data_out[{i % 8}]));")
    lines.append("endmodule")
    return "\n".join(lines)


VALID_500_CELLS = make_netlist_with_n_cells(500)
VALID_15_CELLS = make_netlist_with_n_cells(15)
SMALL_5_CELLS = make_netlist_with_n_cells(5)

EMPTY_FILE = ""

COMMENTS_ONLY = """\
// This is a synthesized netlist
// Generated by Yosys
// But it only has comments
// Nothing else
"""

WIRE_ONLY = """\
module wire_only (
    input wire clk,
    output wire out
);
    wire n1;
    wire n2;
    wire [7:0] bus;
    assign out = n1;
endmodule
"""

NO_MODULE = """\
wire a;
wire b;
assign a = b;
"""


# ===========================================================================
# Test 1: Valid netlist with 500 cells — PASS
# ===========================================================================
class TestValid500:
    def test_500_cells_pass(self, tmp_path):
        """Netlist with 500 cells, min=10 → PASS."""
        f = tmp_path / "netlist.v"
        f.write_text(VALID_500_CELLS)
        findings, stats = snc.audit_netlist(f, min_cells=10)
        assert len(findings) == 0
        assert stats["total_cells"] == 500

    def test_cli_pass(self, tmp_path):
        """CLI returns exit 0 for valid netlist."""
        f = tmp_path / "netlist.v"
        f.write_text(VALID_500_CELLS)
        report = tmp_path / "report.json"

        res = subprocess.run(
            [sys.executable, str(SCRIPT),
             '--netlist', str(f),
             '--min-cells', '10',
             '--json', str(report)],
            capture_output=True, text=True)
        assert res.returncode == 0
        data = json.loads(report.read_text())
        assert data["summary"]["pass"] is True
        assert data["summary"]["total_cells"] == 500


