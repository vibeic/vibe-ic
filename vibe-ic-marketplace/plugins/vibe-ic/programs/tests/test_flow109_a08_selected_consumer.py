@pytest.mark.parametrize('mutation', ['point', 'library', 'authority'])
def test_retained_actual_negative_controls_refuse_without_native_replay(retained_case, mutation):
    root, result, point_path, _manifest = retained_case
    before = point_path.read_bytes()
    library = root / 'neutral.lib'
    old_library = library.read_bytes()
    try:
        if mutation == 'point':
            point_path.unlink()
        elif mutation == 'library':
            library.write_bytes(old_library + b'\n* changed library authority\n')
        else:
            (root / 'input/independent-requirement.txt').write_text('changed authority')
        accepted = flow109._selected_step_result(root, context(), result, native)
        assert accepted['default_row_status'] == 'NOT_MEASURED'
        assert accepted['completed'] is False
    finally:
        point_path.write_bytes(before)
        library.write_bytes(old_library)


