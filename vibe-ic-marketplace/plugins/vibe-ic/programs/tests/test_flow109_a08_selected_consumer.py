def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def put(root, relative, value):
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value))
    return path


def authority(root, *, names, floor=14.):
    source = root / 'input/independent-requirement.txt'
    source.parent.mkdir(parents=True, exist_ok=True)
    source.write_text('Software consumer contract authority. No IC qualification or ADC count.')
    approval = {'status': 'APPROVED', 'authority': 'requirements_owner',
                'source_reference': {'path': str(source.relative_to(root)), 'sha256': sha(source)}}
    put(root, 'requirements/base_A7/pvt_load_modes.json', {'schema': metrics.AUTHORITY_SCHEMA,
        'approval': approval, 'required_items': [{'block': name, 'name': corner} for name, corner in names]})
    put(root, 'requirements/base_A7/prelayout_performance.json', {'schema': metrics.AUTHORITY_SCHEMA,
        'approval': approval, 'limits': {name: {'enob': {'min': floor}} for name, _corner in names},
        'units': {name: {'enob': 'bit'} for name, _corner in names}})


def component(root, name, image, row_data=None):
    row = {'step': 'A08', 'block': name, 'status': 'PASS', 'metrics': {}, 'executions': [],
        'input_views': native._input_views(root, name, 'A08'), 'output_views': {}, 'outputs': [],
        'producer_context': {'image': image, 'driver_sha256': sha(native.__file__)}}
    if row_data:
        row.update(row_data)
    report = {'attempt': str(root / 'reports/analog_native/selected-consumer'), 'image': image,
              'source_sha256': sha(native.__file__), 'steps': [row], 'window_verdict': row['status']}
    put(root, 'reports/analog_native/selected-consumer/result.json', report)
    return {'step_id': 'A08', 'component_status': row['status'], 'native_results': report,
            'a08_invocation': native._a08_invocation(root)}


def context():
    profile = next(v for v in flow109.load_registry()['reference_profiles'] if v['name'] == 'Analog model-IP')
    plan = flow109.resolve_plan(profile['features'])
    return flow109.execution_context(plan, 'A08', 'A08')


