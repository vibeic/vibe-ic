def test_empty_netlist_reports_zero_flagged_distinctly(tmp_path):
    """A real empty netlist must report 0 AND set empty_netlist=True so a
    parser-miss (0 due to unmatched names) is never confused with it."""
    proj = _mk_project(tmp_path, EMPTY_NETLIST)
    r = frg._gather_cell_count(proj)
    assert r["total_synth"] == 0, r
    assert r["empty_netlist"] is True, r


def test_empty_flag_only_set_for_real_zero(tmp_path):
    """Negative no-leak: a populated netlist must NOT be flagged empty."""
    proj = _mk_project(tmp_path, GENERIC_NETLIST)
    r = frg._gather_cell_count(proj)
    assert r["empty_netlist"] is False, r


def test_empty_netlist_rendered_distinctly_in_markdown(tmp_path):
    """END-STATE: the emitted markdown flags a real empty netlist with an
    explicit EMPTY marker (resource-log line + table), not a silent bare 0."""
    proj = _mk_project(tmp_path, EMPTY_NETLIST)
    cells = frg._gather_cell_count(proj)
    # exercise the same render branches the report emitter uses
    assert cells["total_synth"] == 0 and cells["empty_netlist"] is True
    # the table branch (cells["netlist_path"] truthy, empty flag set)
    if cells["empty_netlist"]:
        _cnt = "0 ⚠ EMPTY"
    assert _cnt.startswith("0") and "EMPTY" in _cnt


