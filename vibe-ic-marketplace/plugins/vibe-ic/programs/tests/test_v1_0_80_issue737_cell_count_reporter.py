# Yosys generic-mapped gate-level netlist (what `write_verilog` emits BEFORE
# liberty tech-mapping, and what ABC's genlib mapping leaves for `$_*_`
# primitives). Note: the instance master leads with `\$`, and yosys writes an
# inline `/* _N_ */` comment after named registers' instance names.
GENERIC_NETLIST = (
    "/* Generated by Yosys */\n"
    "module foo(a, b, clk, y);\n"
    "  wire _0_;\n"
    "  input a;\n"
    "  wire a;\n"
    "  input b;\n"
    "  input clk;\n"
    "  output y;\n"
    "  \\$_AND_  _1_ (\n"
    "    .A(b),\n"
    "    .B(a),\n"
    "    .Y(_0_)\n"
    "  );\n"
    "  \\$_NOT_  _2_ (\n"
    "    .A(_0_),\n"
    "    .Y(_3_)\n"
    "  );\n"
    "  \\$_DFF_P_  y_reg /* _4_ */ (\n"
    "    .C(clk),\n"
    "    .D(_3_),\n"
    "    .Q(y)\n"
    "  );\n"
    "endmodule\n"
)
GENERIC_EXPECTED = 3  # AND + NOT + DFF

# Lowercase liberty-mapped netlist (sky130-style). Master leads lowercase.
LOWERCASE_NETLIST = (
    "module top(a, b, clk, y);\n"
    "  input a;\n"
    "  input b;\n"
    "  output y;\n"
    "  sky130_fd_sc_hd__nand2_1 _0_ (.A(a), .B(b), .Y(_n));\n"
    "  sky130_fd_sc_hd__inv_1   _1_ (.A(_n), .Y(_m));\n"
    "  sky130_fd_sc_hd__dfxtp_1 _2_ (.CLK(clk), .D(_m), .Q(y));\n"
    "endmodule\n"
)
LOWERCASE_EXPECTED = 3

# Uppercase legacy liberty netlist (the ONLY style the old regex matched) —
# guard that the broadened matcher still parses it.
UPPERCASE_NETLIST = (
    "module m(a, b, clk, y);\n"
    "  input a;\n"
    "  output y;\n"
    "  NAND2X1  g0 (.A(a), .B(b), .Y(_n));\n"
    "  INVX1    g1 (.A(_n), .Y(_m));\n"
    "  DFFPOSX1 g2 (.CLK(clk), .D(_m), .Q(y));\n"
    "endmodule\n"
)
UPPERCASE_EXPECTED = 3

# Genuinely-empty netlist — module + ports + wires, ZERO cells.
EMPTY_NETLIST = (
    "module empty(a, y);\n"
    "  input a;\n"
    "  output y;\n"
    "  wire a;\n"
    "  wire y;\n"
    "  assign y = a;\n"
    "endmodule\n"
)


def _mk_project(tmp_path: Path, netlist_text: str,
                stat_json: str | None = None,
                yosys_log: str | None = None) -> Path:
    sd = tmp_path / "phase2" / "stage2" / "synth"
    sd.mkdir(parents=True)
    (sd / "netlist.v").write_text(netlist_text)
    if stat_json is not None:
        (sd / "stat.json").write_text(stat_json)
    if yosys_log is not None:
        (sd / "yosys.log").write_text(yosys_log)
    return tmp_path


