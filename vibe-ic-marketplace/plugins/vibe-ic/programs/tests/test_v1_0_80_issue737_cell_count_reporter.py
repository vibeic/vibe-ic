# =========================================================================
# #737 REMEDIATION (v1.0.80 adversarial-review LOW) — the stat.json reader
# must PREFER yosys's top-level `design` aggregate over the largest-module
# heuristic. A HIERARCHICAL (non-flattened) netlist under-counts otherwise.
# =========================================================================

# Reviewer's EXACT repro shape: `stat -json -top top` on a 3-level hierarchy
# emits per-module blocks leaf{num_cells:1}/mid{2}/top{2} PLUS a sibling
# top-level `design` block whose num_cells (3) is the whole-design leaf total.
# The old largest-module heuristic picked mid or top (2) and disagreed with
# both the yosys.log `Number of cells:` line and the phase2 parser (both 3).
HIER_STAT_JSON = (
    '{"creator":"Yosys 0.33","invocation":"stat -json -top top ",'
    '"modules":{'
    '"\\\\leaf":{"num_cells":1,"num_cells_by_type":{"$and":1}},'
    '"\\\\mid":{"num_cells":2,"num_cells_by_type":{"leaf":2}},'
    '"\\\\top":{"num_cells":2,"num_cells_by_type":{"leaf":1,"mid":1}}'
    '},'
    '"design":{"num_cells":3,"num_cells_by_type":{"$and":3}}}'
)

# A flattened single-module design: largest module == design total. The
# `design` block (if emitted) and the module agree; result stays correct.
FLAT_STAT_JSON = (
    '{"creator":"Yosys 0.33","invocation":"stat -json -top top ",'
    '"modules":{'
    '"\\\\top":{"num_cells":3,"num_cells_by_type":{"$_AND_":1,"$_NOT_":1,'
    '"$_DFF_P_":1}}'
    '},'
    '"design":{"num_cells":3,"num_cells_by_type":{"$_AND_":1,"$_NOT_":1,'
    '"$_DFF_P_":1}}}'
)

# A plain `stat -json` (no -top) omits the design block — the largest-module
# fallback must still apply so this style keeps working unchanged.
NO_DESIGN_STAT_JSON = (
    '{"creator":"Yosys 0.33","invocation":"stat -json ",'
    '"modules":{'
    '"\\\\leaf":{"num_cells":1,"num_cells_by_type":{"$and":1}},'
    '"\\\\top":{"num_cells":2,"num_cells_by_type":{"leaf":2}}'
    '}}'
)


def test_hierarchical_stat_prefers_design_aggregate(tmp_path):
    """Reviewer's EXACT failing input: leaf{1}/mid{2}/top{2} + design{3}.
    Pre-remediation the largest-module heuristic reported 2 (UNDER-count);
    the corrected end-state reports the design aggregate 3."""
    proj = _mk_project(tmp_path, GENERIC_NETLIST, stat_json=HIER_STAT_JSON)
    r = frg._gather_cell_count(proj)
    assert r["total_synth"] == 3, r          # NOT 2 (the buggy largest-module)
    assert r["synth_count_source"] == "stat.json", r
    # histogram comes from the design-level by-type table, not a per-module one
    assert ("$and", 3) in r["top"], r["top"]
    assert r["empty_netlist"] is False, r




def test_flattened_stat_still_correct(tmp_path):
    """Guard the flattened single-module case: largest module == design total,
    both 3 — result is unchanged by the remediation."""
    proj = _mk_project(tmp_path, GENERIC_NETLIST, stat_json=FLAT_STAT_JSON)
    r = frg._gather_cell_count(proj)
    assert r["total_synth"] == 3, r
    assert r["synth_count_source"] == "stat.json", r


def test_plain_stat_no_design_falls_back_to_largest_module(tmp_path):
    """No `design` block (plain `stat -json`, no -top) → fall back to the
    largest-module heuristic, preserving the original #737 behaviour."""
    proj = _mk_project(tmp_path, GENERIC_NETLIST, stat_json=NO_DESIGN_STAT_JSON)
    r = frg._gather_cell_count(proj)
    assert r["total_synth"] == 2, r          # largest module (top, 2 cells)
    assert r["synth_count_source"] == "stat.json", r


def test_design_aggregate_by_type_only_is_summed(tmp_path):
    """Fail-safe: a `design` block with ONLY a by-type table (no num_cells
    scalar) is summed rather than ignored."""
    stat = (
        '{"modules":{"\\\\top":{"num_cells":2,'
        '"num_cells_by_type":{"leaf":2}}},'
        '"design":{"num_cells_by_type":{"$and":1,"$or":1,"$xor":1}}}'
    )
    proj = _mk_project(tmp_path, GENERIC_NETLIST, stat_json=stat)
    r = frg._gather_cell_count(proj)
    assert r["total_synth"] == 3, r          # 1+1+1 summed from by-type
    assert r["synth_count_source"] == "stat.json", r


