#!/usr/bin/env python3
"""ISSUE #737 — post-synth cell-count reporters misreported generic-mapped +
lowercase-liberty netlists as 0/? cells (reporting-integrity, can MASK a real
empty netlist).

Two reporters shared one naming convention and BOTH missed real cells:

(1) final_report_generate._gather_cell_count anchored its instance regex on an
    UPPERCASE-leading token `^\\s*([A-Z][A-Z0-9_]+)\\s+…` → matched ZERO of
    Yosys's generic-mapped gates (`\\$_NAND_`, `\\$_DFF_P_`, …, which lead with
    backslash-dollar) and ZERO lowercase liberty cells (`sky130_fd_sc_hd__*`).
    A fully-populated post-synth netlist of either style reported 0 cells.

(2) design_one_shot_runner keyed its synth-cells parser on the substring
    `'Number of cells'` and read stdout ONLY. Some yosys builds print only a
    bare `'NNNNN cells'` stat line, and any count that lands on stderr was
    dropped → yosys_synth reported cells=? for a real netlist.

FIX (chip-AGNOSTIC, Bucket A):
  (1) _gather_cell_count PREFERS the authoritative yosys `stat` count
      (stat.json → yosys.log `Number of cells:` / `NNNNN cells`); the netlist
      scan is the fallback and its matcher is broadened to backslash-dollar
      generic gates + lowercase liberty cells. A genuinely-empty netlist still
      reports 0 but is FLAGGED DISTINCTLY (`empty_netlist=True`) so a
      parser-miss is never confused with a real empty netlist.
  (2) design_one_shot_runner matches BOTH stat forms over stdout+stderr via the
      shared `_parse_yosys_stat_cells` helper.

This module pins the actual yosys `stat` line FORMAT so the emitter↔checker
can't drift again. guard_class=False (reporting fix).
"""
from __future__ import annotations

from pathlib import Path

import pytest

import final_report_generate as frg

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))


# --- fixtures: the EXACT yosys stat / netlist shapes -----------------------

# Yosys generic-mapped gate-level netlist (what `write_verilog` emits BEFORE
# liberty tech-mapping, and what ABC's genlib mapping leaves for `$_*_`
# primitives). Note: the instance master leads with `\$`, and yosys writes an
# inline `/* _N_ */` comment after named registers' instance names.
GENERIC_NETLIST = (
    "/* Generated by Yosys */\n"
    "module foo(a, b, clk, y);\n"
    "  wire _0_;\n"
    "  input a;\n"
    "  wire a;\n"
    "  input b;\n"
    "  input clk;\n"
    "  output y;\n"
    "  \\$_AND_  _1_ (\n"
    "    .A(b),\n"
    "    .B(a),\n"
    "    .Y(_0_)\n"
    "  );\n"
    "  \\$_NOT_  _2_ (\n"
    "    .A(_0_),\n"
    "    .Y(_3_)\n"
    "  );\n"
    "  \\$_DFF_P_  y_reg /* _4_ */ (\n"
    "    .C(clk),\n"
    "    .D(_3_),\n"
    "    .Q(y)\n"
    "  );\n"
    "endmodule\n"
)
GENERIC_EXPECTED = 3  # AND + NOT + DFF

# Lowercase liberty-mapped netlist (sky130-style). Master leads lowercase.
LOWERCASE_NETLIST = (
    "module top(a, b, clk, y);\n"
    "  input a;\n"
    "  input b;\n"
    "  output y;\n"
    "  sky130_fd_sc_hd__nand2_1 _0_ (.A(a), .B(b), .Y(_n));\n"
    "  sky130_fd_sc_hd__inv_1   _1_ (.A(_n), .Y(_m));\n"
    "  sky130_fd_sc_hd__dfxtp_1 _2_ (.CLK(clk), .D(_m), .Q(y));\n"
    "endmodule\n"
)
LOWERCASE_EXPECTED = 3

# Uppercase legacy liberty netlist (the ONLY style the old regex matched) —
# guard that the broadened matcher still parses it.
UPPERCASE_NETLIST = (
    "module m(a, b, clk, y);\n"
    "  input a;\n"
    "  output y;\n"
    "  NAND2X1  g0 (.A(a), .B(b), .Y(_n));\n"
    "  INVX1    g1 (.A(_n), .Y(_m));\n"
    "  DFFPOSX1 g2 (.CLK(clk), .D(_m), .Q(y));\n"
    "endmodule\n"
)
UPPERCASE_EXPECTED = 3

# Genuinely-empty netlist — module + ports + wires, ZERO cells.
EMPTY_NETLIST = (
    "module empty(a, y);\n"
    "  input a;\n"
    "  output y;\n"
    "  wire a;\n"
    "  wire y;\n"
    "  assign y = a;\n"
    "endmodule\n"
)


def _mk_project(tmp_path: Path, netlist_text: str,
                stat_json: str | None = None,
                yosys_log: str | None = None) -> Path:
    sd = tmp_path / "phase2" / "stage2" / "synth"
    sd.mkdir(parents=True)
    (sd / "netlist.v").write_text(netlist_text)
    if stat_json is not None:
        (sd / "stat.json").write_text(stat_json)
    if yosys_log is not None:
        (sd / "yosys.log").write_text(yosys_log)
    return tmp_path


# =========================================================================
# (a) generic-mapped netlist → real count (the PRIMARY reported defect)
# =========================================================================

def test_generic_mapped_netlist_scan_reports_real_count(tmp_path):
    """Reproduce-現象: a generic-mapped netlist (`\\$_AND_` etc.) with NO stat
    must scan to the REAL count, not 0. Pre-fix the uppercase-anchored regex
    matched zero of these and reported 0."""
    proj = _mk_project(tmp_path, GENERIC_NETLIST)
    r = frg._gather_cell_count(proj)
    assert r["total_synth"] == GENERIC_EXPECTED, r
    assert r["synth_count_source"] == "netlist_scan", r
    assert r["empty_netlist"] is False


def test_generic_mapped_prefers_stat_json(tmp_path):
    """Reproduce-現象: feed a generic-mapped netlist PLUS a yosys stat block
    reporting 94243 cells (the issue's named number) — the reporter must use
    the authoritative stat count, not the netlist scan."""
    stat = (
        '{"creator":"Yosys","modules":{'
        '"\\\\foo":{"num_cells":94243,'
        '"num_cells_by_type":{"$_AND_":50000,"$_DFF_P_":44243}}}}'
    )
    proj = _mk_project(tmp_path, GENERIC_NETLIST, stat_json=stat)
    r = frg._gather_cell_count(proj)
    assert r["total_synth"] == 94243, r
    assert r["synth_count_source"] == "stat.json", r
    # histogram comes from stat by-type table
    assert ("$_AND_", 50000) in r["top"], r["top"]


