# ── The netlist rule: zero cells is CORRECT, no module is not ───────────────
def test_a_design_that_legitimately_synthesises_to_zero_cells_is_not_flagged(tmp_path):
    """THE CONTROL. `assign zero = 1'b0` has no cells and is a real netlist.

    Requiring cells would be the adjacent-measurement trap, and it would red a
    correct design. This is the test that proves D3 is not a detector that fires
    on everything.
    """
    p = tmp_path / "netlist.v"
    p.write_text(ZERO_CELL_NETLIST)
    assert "0 cells" not in p.read_text()          # the count is not in the file
    v = S.classify_artefact(p)
    assert v["state"] == S.SUBSTANTIVE, v


