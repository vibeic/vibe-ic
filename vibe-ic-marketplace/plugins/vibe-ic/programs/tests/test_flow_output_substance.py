"""Guards for `flow_output_substance` — the D3 decider.

EVERY TEST HERE HAS TWO POLES. A predicate that only ever demonstrates its
refusal is indistinguishable from one that refuses everything, and a detector
that fires on every target it is pointed at is as broken as the silence it
replaced. So each rule is shown refusing the vacuous artefact AND accepting the
healthy one that most resembles it.

The fixtures are the REAL bytes, not paraphrases: the vacuous STA transcript is
what OpenROAD wrote on
ghcr.io/vibeic/vibeic-eda@sha256:4ece6c01cddc99903af4f027326f7624b069311f2073a5a0b565d5a9cf649a16
when `eda_sta` handed it a netlist with no technology, and the zero-cell netlist
is what yosys wrote for `assign zero = 1'b0` on the same image.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

PROGRAMS = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROGRAMS))

import flow_output_substance as S  # noqa: E402


