# ── NOT_DECIDABLE is neither a pass nor a fail ──────────────────────────────
def test_an_opaque_bitstream_is_not_decidable_and_never_a_verdict(tmp_path):
    p = tmp_path / "top.sof"
    p.write_bytes(b"\x00\x01\x02\x03" * 64)
    v = S.classify_artefact(p)
    assert v["state"] == S.NOT_DECIDABLE, v
    assert v["state"] not in S.FAILING
    assert v["state"] != S.SUBSTANTIVE
    assert v["state"] in S.NO_VERDICT


# ── The whole-flow contract ─────────────────────────────────────────────────
def _steps():
    import yaml
    doc = yaml.safe_load((PROGRAMS.parent / "flow" /
                          "phase1_phase2_phase3.yaml").read_text())
    out = []

    def walk(o):
        if isinstance(o, dict):
            if "id" in o and "name" in o:
                out.append(o)
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(doc)
    return [s for s in out if not str(s.get("id", "")).startswith("stage")]


def test_with_no_run_every_cell_is_NOT_MEASURED_and_none_is_a_pass():
    """The whole lesson: an absent measurement must not be renderable as a good
    one — and must not be rendered as a bad one either.
    """
    rec = S.classify_flow(None, _steps())
    assert rec["state"] == S.NOT_MEASURED
    assert rec["cells"], "an empty cell list would make the assertion vacuous"
    for c in rec["cells"]:
        assert c["state"] == S.NOT_MEASURED, c
        assert c["state"] != S.SUBSTANTIVE
        assert c["state"] not in S.FAILING


def test_a_step_the_run_never_reached_is_NOT_MEASURED_not_a_failure(tmp_path):
    """A phase-1 project has no phase-3 outputs, and that is not a defect.

    Without this, D3 reds every unreached step of every partial run — measured
    at 64 of 68 on a two-step run tree while this was being built. A dimension
    that reds everything gets ignored, which costs exactly what silence costs.
    """
    steps = {str(s["id"]): s for s in _steps()}
    r = S.classify_step(tmp_path, steps["10"])
    assert r["state"] == S.NOT_MEASURED, r
    assert r["code"] == "STEP_NOT_EVIDENCED", r
    assert r["state"] not in S.FAILING


def test_but_a_HALF_written_step_is_still_a_finding(tmp_path):
    """The exemption above is not a blanket amnesty for absence.

    The moment ANY declared output resolves, the step demonstrably ran, and a
    missing SIBLING output becomes a real finding again.
    """
    steps = {str(s["id"]): s for s in _steps()}
    (tmp_path / "phase3" / "stage3" / "sta").mkdir(parents=True)
    (tmp_path / "phase3" / "stage3" / "sta" / "pre_pnr_timing.rpt").write_text(GOOD_STA)
    # step 10's OTHER declared output, reports/phase3/sta/pre_pnr_summary.json,
    # is deliberately not written.
    r = S.classify_step(tmp_path, steps["10"])
    assert r["state"] == S.ABSENT, r
    assert r["state"] in S.FAILING


def test_the_real_case_end_to_end_on_the_flows_own_sta_step(tmp_path):
    """Step 10, both poles, through the same code path the grid uses."""
    steps = {str(s["id"]): s for s in _steps()}
    sta = tmp_path / "phase3" / "stage3" / "sta"
    sta.mkdir(parents=True)
    summ = tmp_path / "reports" / "phase3" / "sta"
    summ.mkdir(parents=True)
    (summ / "pre_pnr_summary.json").write_text('{"wns_ns": 1.27}')

    (sta / "pre_pnr_timing.rpt").write_text(VACUOUS_STA)
    bad = S.classify_step(tmp_path, steps["10"])
    assert bad["state"] == S.VACUOUS and bad["code"] == "TOOL_REPORTED_ERROR", bad

    (sta / "pre_pnr_timing.rpt").write_text(GOOD_STA)
    good = S.classify_step(tmp_path, steps["10"])
    assert good["state"] == S.SUBSTANTIVE, good


# ── The anti-D8 guard ───────────────────────────────────────────────────────
def test_this_module_never_reads_a_steps_gate(tmp_path):
    """D3 must not be D8 wearing a new name.

    Mechanical, not a promise: give a step a gate that would satisfy any
    declaration-based predicate and NO substantive output, and the verdict must
    still come from the bytes. The gate is also removed entirely in the second
    half — if any verdict moved, something read it.
    """
    steps = {str(s["id"]): s for s in _steps()}
    sta = tmp_path / "phase3" / "stage3" / "sta"
    sta.mkdir(parents=True)
    (sta / "pre_pnr_timing.rpt").write_text(VACUOUS_STA)
    summ = tmp_path / "reports" / "phase3" / "sta"
    summ.mkdir(parents=True)
    (summ / "pre_pnr_summary.json").write_text('{"wns_ns": 1.27}')

    import copy
    with_gate = copy.deepcopy(steps["10"])
    with_gate["gate"] = {"all_of": [{"files_exist": ["phase3/stage3/sta/pre_pnr_timing.rpt"]}]}
    without_gate = copy.deepcopy(steps["10"])
    without_gate.pop("gate", None)

    a = S.classify_step(tmp_path, with_gate)
    b = S.classify_step(tmp_path, without_gate)
    assert a["state"] == b["state"] == S.VACUOUS, (a["state"], b["state"])


def test_the_module_source_names_no_gate_key():
    """The same guard at the source level, so a future edit that starts reading
    the declaration turns this red instead of quietly changing what D3 means.
    """
    src = (PROGRAMS / "flow_output_substance.py").read_text()
    body = src.split('"""', 2)[2]        # strip the module docstring
    for forbidden in ('"gate"', "'gate'", '.get("gate"', "step['gate']"):
        assert forbidden not in body, (
            f"{forbidden} appears in the executable body; D3 must reach every "
            f"verdict from bytes a run wrote, never from what the flow declares")


# ── Every vacuity code the module can emit is enumerated ────────────────────
def test_every_emitted_code_is_in_the_declared_vocabulary():
    """A code invented at a return site and absent from the table is prose with
    a capital letter. Both directions: the table must also not rot.
    """
    src = (PROGRAMS / "flow_output_substance.py").read_text()
    import re
    emitted = set(re.findall(r'code="([A-Z_]+)"', src))
    emitted.discard("")
    known = set(S.VACUITY_CODES) | set(S.NO_VERDICT_CODES) | {"ABSENT"}
    assert emitted <= known, sorted(emitted - known)
    assert emitted, "no codes found — the regex has drifted from the source"


# ── The CLI contract ────────────────────────────────────────────────────────
def _cli(*args):
    p = subprocess.run([sys.executable, str(PROGRAMS / "flow_output_substance.py"), *args],
                       capture_output=True, text=True, timeout=600)
    return p.returncode, p.stdout + p.stderr


def test_the_cli_with_no_run_says_NOT_MEASURED_in_those_words():
    rc, out = _cli()
    assert rc == 0, out
    assert "NOT MEASURED" in out, out
    assert "neither a pass nor a fail" in out, out
