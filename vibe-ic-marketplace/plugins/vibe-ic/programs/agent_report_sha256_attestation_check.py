#!/usr/bin/env python3
"""
agent_report_sha256_attestation_check.py — verify the project's
final report attests every canonical chip / FPGA artefact with a
SHA256 hash.

Per the v1.6.30 anti-fabrication doctrine (rule #5):

    Final report carries a SHA256 attestation table of every
    canonical artefact (SOF / GDS / synth-netlist / LEF / Liberty /
    sign-off reports). Without that table, "PASS" is unverifiable
    and counts as incomplete.

`agent_report_presence_check` (v1.6.24) already enforces that the
report exists and carries the 5 mandatory sections; this gate adds
the next layer — that the **content** of the report carries
verifiable SHA256 attestations of the deliverables.

Report-file lookup (v1.6.34)
---------------------------
The gate inspects up to TWO canonical report files (whichever
exists; both are accepted, and hashes from either count):

  1. `<project>/reports/final_summary.md` — auto-generated by
     `final_report_generate.py`, wired into all 5 one-shot runners
     since v1.6.32. Contains the SHA-256 Attestation table since
     v1.6.34.
  2. `<project>/AGENT_REPORT.md` — hand-authored by an agent that
     does not run the canonical generator. Allowed for
     back-compatibility and ad-hoc workflows.

If both exist, declared hashes from either file count toward
attestation. If neither exists, the gate emits VACUOUS_PASS — the
presence requirement is owned by `agent_report_presence_check`.

Failure modes (chip-AGNOSTIC):

1. NO_ATTESTATION_TABLE — AGENT_REPORT.md exists but contains zero
   `sha256:<64-hex>` tokens. The report is unverifiable.

2. MISSING_ATTESTATION — a canonical artefact exists on disk but
   its on-disk-computed SHA256 does NOT appear anywhere in
   AGENT_REPORT.md. The report omits attestation for an artefact
   the project actually produced.

   Canonical artefact globs (chip-AGNOSTIC, no chip-specific names):
     phase2/stage1/fpga/output_files/*.sof          (FPGA bitstream)
     phase3/stage4/gds/*.gds                         (chip GDS)
     phase3/stage4/foundry_handoff/**/*.gds          (mask GDS)
     phase2/stage2/synth/*.v                        (synth netlist)
     phase3/stage3/pnr/*.v                           (PnR netlist)
     phase3/stage4/foundry_handoff/**/*.lef          (LEF)
     phase3/stage4/foundry_handoff/**/*.lib          (Liberty)
     phase3/analog/hardmacro/**/*.lef                (analog LEF)
     phase3/analog/hardmacro/**/*.lib                (analog Liberty)

   EXCLUDED from the two *.v globs: front-end pre-pass files the
   flow itself writes into the netlist directory (`*_sv2v.v`).
   Those are synthesis INPUTS. See
   `_FRONTEND_INTERMEDIATE_SUFFIXES` for why this is a name rule
   over the flow's own generated names and not content sniffing.

VACUOUS_PASS conditions:
* AGENT_REPORT.md missing — `agent_report_presence_check` handles
  that as FAIL; this gate stays out of the way and emits VACUOUS.
* No canonical artefacts exist on disk — pre-output project,
  attestation gate inapplicable.

WHY VACUOUS_PASS EXITS 2 AND NOT 0 (#834)
-----------------------------------------
The umbrella that consumes this gate reads its EXIT CODE and nothing
else. `flow_compliance_check._run_structural_rtl_gates` — the driver
for the `_STRUCTURAL_RTL_GATES` tuple this gate is registered in
(line ~1409) — maps rc 0 -> a `PASS` gate record, rc 1 -> `FAIL`,
rc 2 -> a `SKIP` record carrying `skip_kind: input-missing`. It never
opens the JSON report and never scans stdout, so the
`VACUOUS_PASS:` line printed below reaches NO automated consumer on
that path: it is read by a human or by nobody.

This gate computed `VACUOUS_PASS` and then returned 0 anyway, so
"there was nothing to look at" was credited in the executed-PASS
numerator, indistinguishable from "every canonical artefact on disk
is attested and the hashes match". The two halves of one contract
disagreed; this side is the one that was wrong, because the umbrella's
convention (rc 2 = examined nothing) is the shared one and is what
`_vacuous_exit` exists to route.

The `VACUOUS_PASS:` stdout line is KEPT. It is the second, weaker
channel (`flow_compliance_check._stdout_signals_vacuous`), it is what
`_check_program_exit_zero` reads on the per-step path, and dropping it
would trade one disclosure for another instead of adding one.

Usage:
    python3 agent_report_sha256_attestation_check.py <project_dir>
                                                      [--json <out>]

Exit codes:
    0  PASS — every canonical artefact on disk is attested
    1  no attestation table OR canonical artefact lacks attestation
    2  VACUOUS_PASS (examined nothing: no report file, or no canonical
       artefact on disk) — the repo-wide `_vacuous_exit.RC_VACUOUS`
       convention. Also the rc for an unusable project argument, which
       is the same overload every gate routed through `_vacuous_exit`
       carries (see `reports_subfolder_taxonomy_check`): the umbrella
       never invokes a gate on a path it did not just walk, and
       `_gate_invocation` separates a genuine argparse rejection from a
       verdict by reading the callee's own error protocol.

chip-AGNOSTIC. No vendor / IC / specific filename hardcoded.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from dataclasses import dataclass, field, asdict
from pathlib import Path
from typing import List, Optional, Set, Tuple

import _vacuous_exit as _vx
from _atomic_artefact import write_text as atomic_write_text  # vibe-ic#1082 (helper from PR #1094)


_RE_SHA256_TOKEN = re.compile(r"sha256:([0-9a-fA-F]{64})", re.IGNORECASE)


# Canonical artefact glob set. Order is presentation-stable; gate
# walks each pattern and aggregates findings. Each pattern is
# rooted at the project tree.
_CANONICAL_ARTEFACT_GLOBS: Tuple[Tuple[str, str], ...] = (
    ("FPGA SOF",       "phase2/stage1/fpga/output_files/*.sof"),
    ("chip GDS",       "phase3/stage4/gds/*.gds"),
    ("foundry GDS",    "phase3/stage4/foundry_handoff/**/*.gds"),
    ("synth netlist",  "phase2/stage2/synth/*.v"),
    ("PnR netlist",    "phase3/stage3/pnr/*.v"),
    ("foundry LEF",    "phase3/stage4/foundry_handoff/**/*.lef"),
    ("foundry Liberty","phase3/stage4/foundry_handoff/**/*.lib"),
    # Canonical analog hardmacro location is phase3/analog/hardmacro/
    # per _path_layout.phase3_hardmacro_dir; the entries below glob that
    # canonical path for the attestation chain.
    ("analog LEF",     "phase3/analog/hardmacro/**/*.lef"),
    ("analog Liberty", "phase3/analog/hardmacro/**/*.lib"),
)


#: Filenames the FLOW ITSELF deposits in a netlist directory that are
#: synthesis INPUTS, not synthesis OUTPUTS.
#:
#: WHY THIS EXISTS — the two `*.v` globs above ask "is there a .v file in
#: the netlist directory" and the gate reads the answer as "has this
#: project produced a netlist". Those are not the same question, and the
#: flow's own front-end fallback is what separates them: when the SV
#: front-end is unavailable, the runner writes an sv2v pre-pass file
#: INTO the very directory the glob watches, then feeds it to yosys.
#:
#:   design_one_shot_runner.py   `_host_conv = synth_dir / f"{synth_top}_sv2v.v"`
#:   phase3_one_shot_runner.py   `sv2v_out_host = out_dir / f"{top}_sv2v.v"`
#:
#: So a project that has NOT completed synthesis can still present a
#: `.v` file here, and the gate then demands the final report attest a
#: pre-synthesis intermediate as a chip artefact. The cheapest way to
#: clear that is to publish a SHA256 of an intermediate under a "chip
#: artefact" heading — a rule meant to make reports verifiable rewarding
#: a report that is falsely verifiable. Same shape as #802.
#:
#: A gate-level netlist is trivially distinguishable by CONTENT (no
#: `parameter`, no `always`, only cell instantiations), but content
#: sniffing fails OPEN in the dangerous direction: an unparsed real
#: netlist would stop being demanded. This is a NAME rule over the
#: flow's OWN generated names instead, which fails SAFE — anything the
#: flow did not generate stays a canonical artefact and is still
#: demanded. Reading the emitter's documented naming contract, not
#: guessing at file content (same principle as `_gate_invocation`).
#:
#: SCOPE — deliberately narrow. It suppresses NOTHING but the front-end
#: intermediate. A real netlist under any other name, including one that
#: merely CONTAINS "sv2v", is still a canonical artefact: the rule is an
#: exact suffix match on the emitters' f-string, not a substring search.
_FRONTEND_INTERMEDIATE_SUFFIXES: Tuple[str, ...] = (
    "_sv2v.v",
)


def _is_frontend_intermediate(path: Path) -> bool:
    """True if `path` is a front-end pre-pass file the flow itself wrote.

    Exact-suffix match on the runners' own f-string so a hand-authored
    netlist named e.g. `sv2v_top.v` or `top_sv2v_golden.v` is NOT
    suppressed — it is not a name the flow generates, so it keeps
    requiring attestation."""
    return any(path.name.endswith(sfx)
               for sfx in _FRONTEND_INTERMEDIATE_SUFFIXES)


@dataclass
class AttestationFinding:
    rule: str
    artefact_kind: str
    rel_path: str
    expected_sha256: str
    detail: str = ""


def _sha256_of_file(path: Path) -> Optional[str]:
    """Compute lowercase hex SHA256 of `path`. Returns None on read
    failure (broken symlink, permission denied)."""
    h = hashlib.sha256()
    try:
        with path.open("rb") as f:
            while True:
                buf = f.read(1 << 20)  # 1 MiB chunks
                if not buf:
                    break
                h.update(buf)
    except OSError:
        return None
    return h.hexdigest()


def _extracted_hashes(text: str) -> Set[str]:
    """Lower-case hex SHA256 tokens declared anywhere in `text`."""
    return {m.group(1).lower() for m in _RE_SHA256_TOKEN.finditer(text)}


def _collect_canonical_artefacts(project: Path
                                 ) -> List[Tuple[str, Path]]:
    """Return (kind, path) for every canonical artefact present on
    disk. Symlinks are resolved before SHA256 (matches the
    provenance gate's behaviour)."""
    out: List[Tuple[str, Path]] = []
    for kind, pattern in _CANONICAL_ARTEFACT_GLOBS:
        for p in sorted(project.glob(pattern)):
            if not p.is_file():
                continue
            # A front-end pre-pass file is an INPUT to synthesis. It is
            # not a chip artefact and must not be attested as one.
            if _is_frontend_intermediate(p):
                continue
            out.append((kind, p))
    return out


_REPORT_CANDIDATE_REL_PATHS: Tuple[str, ...] = (
    "reports/final_summary.md",   # v1.6.32 canonical (auto-generated)
    "AGENT_REPORT.md",            # back-compat hand-authored alternative
)


def _resolve_report_files(project: Path) -> List[Path]:
    """Return every canonical report file that exists on disk, in
    declaration order. v1.6.34 widened the lookup from 1→2 candidates
    so the v1.6.32 auto-generator and the legacy hand-authored
    convention are both accepted."""
    out: List[Path] = []
    for rel in _REPORT_CANDIDATE_REL_PATHS:
        p = project / rel
        if p.is_file():
            out.append(p)
    return out


def audit(project: Path) -> Tuple[str, List[AttestationFinding]]:
    report_files = _resolve_report_files(project)
    if not report_files:
        # No report file at any canonical location. Presence gate owns
        # this failure mode; we stay out of the way and emit VACUOUS.
        return "VACUOUS_PASS", []

    artefacts = _collect_canonical_artefacts(project)
    if not artefacts:
        # Pre-output project; nothing to attest.
        return "VACUOUS_PASS", []

    declared: Set[str] = set()
    for rp in report_files:
        text = rp.read_text(encoding="utf-8", errors="replace")
        declared |= _extracted_hashes(text)

    findings: List[AttestationFinding] = []

    if not declared:
        # NO attestation hashes at all across either report file.
        report_paths_str = " / ".join(
            str(rp.relative_to(project)) for rp in report_files)
        findings.append(AttestationFinding(
            rule="NO_ATTESTATION_TABLE",
            artefact_kind="-",
            rel_path=report_paths_str,
            expected_sha256="-",
            detail=(f"{report_paths_str} contains zero sha256:<64hex> "
                    "tokens but project ships "
                    f"{len(artefacts)} canonical artefact(s) — final "
                    "report is unverifiable.")))
        return "FAIL", findings

    for kind, path in artefacts:
        actual = _sha256_of_file(path)
        if actual is None:
            findings.append(AttestationFinding(
                rule="ARTEFACT_UNREADABLE",
                artefact_kind=kind,
                rel_path=str(path.relative_to(project)),
                expected_sha256="-",
                detail="artefact file present but unreadable "
                       "(broken symlink / permission denied)"))
            continue
        if actual not in declared:
            findings.append(AttestationFinding(
                rule="MISSING_ATTESTATION",
                artefact_kind=kind,
                rel_path=str(path.relative_to(project)),
                expected_sha256=f"sha256:{actual}",
                detail=("artefact present on disk but its sha256 is "
                        "not declared in any of the canonical report "
                        "files (reports/final_summary.md / "
                        "AGENT_REPORT.md)")))

    return ("FAIL" if findings else "PASS"), findings


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description="Verify AGENT_REPORT.md attests canonical "
                    "artefacts with SHA256.")
    ap.add_argument("project_dir")
    ap.add_argument("--json", help="write JSON report to this path")
    args = ap.parse_args(argv)

    project = Path(args.project_dir).resolve()
    if not project.is_dir():
        print(f"error: project dir not found: {project}", file=sys.stderr)
        return 2

    verdict, findings = audit(project)

    artefacts = _collect_canonical_artefacts(project)
    report = {
        "gate": "agent_report_sha256_attestation_check",
        "verdict": verdict,
        "project": str(project),
        "canonical_artefacts_found": len(artefacts),
        "findings_count": len(findings),
        "findings": [asdict(f) for f in findings],
    }
    if verdict == "VACUOUS_PASS":
        if not _resolve_report_files(project):
            report["reason"] = ("no canonical report file at "
                                + " / ".join(_REPORT_CANDIDATE_REL_PATHS)
                                + "; agent_report_presence_check owns "
                                "that failure mode.")
        else:
            report["reason"] = ("no canonical artefacts on disk; "
                                "pre-output project.")

    if args.json:
        out = Path(args.json)
        out.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_text(out, json.dumps(report, indent=2) + "\n")

    if verdict == "VACUOUS_PASS":
        # Both channels, from the same conclusion (#834). The stdout line
        # is the pre-existing human/`_stdout_signals_vacuous` disclosure;
        # `exit_code(passed=True, skipped=True)` is rc 2, the ONLY channel
        # the P0 structural umbrella reads. Before this, the gate said
        # "examined nothing" in the one place the umbrella cannot hear.
        print(f"VACUOUS_PASS: {report['reason']}")
        return _vx.exit_code(passed=True, skipped=True)
    if verdict == "PASS":
        rep = _resolve_report_files(project)
        rep_str = " / ".join(str(p.relative_to(project)) for p in rep)
        print(f"PASS: {len(artefacts)} canonical artefact(s) all "
              f"attested in {rep_str}")
        return 0
    print(f"FAIL: {len(findings)} attestation gap(s):", file=sys.stderr)
    for f in findings[:10]:
        print(f"  [{f.rule}] {f.artefact_kind} ({f.rel_path}): "
              f"{f.detail}", file=sys.stderr)
    if len(findings) > 10:
        print(f"  … and {len(findings) - 10} more", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
