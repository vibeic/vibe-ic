# Rule 12: Reset-boundary residual level-enable write (ORGANIC #723)
#
# A clocked register that a reset CLEARS to 0, and is then UPDATED under a
# purely LEVEL-sensitive enable that traces to a TOP-LEVEL INPUT, with NO
# registered "armed"/"settle"/"valid-after-reset" qualifier in the module, has
# the stale-enable-post-reset-write hole:
#
#     always @(posedge clk or negedge rst_n)
#         if (!rst_n)   cnt <= 0;        // (a) reset clears the register
#         else if (dw)  cnt <= cnt + 1;  // (b) level enable `dw` (== an input)
#
# If the environment leaves `dw`'s source input HIGH across reset (common when a
# reset test runs after a random-stimulus test that did not clear enables), the
# very FIRST post-reset clock edge already performs the update, so the post-reset
# "empty / zero" invariant breaks before any deliberate transaction. The
# motivating real case: a `ping_pong_buffer` async-reset test failed because a
# held-high `write_enable` performed a transfer immediately after reset release;
# the fix was a registered 2-cycle "armed" guard that blocks updates until reset
# has been de-asserted for >= 1 full cycle.
#
# CORPUS-CLEAN narrowing — fire ONLY when ALL of:
#   (a) the register is RESET-CLEARED to zero inside the block's reset branch, AND
#   (b) the SAME register is updated in an `else if(<COND>) <reg> <= ...` whose
#       <COND> gates on a PURELY-COMBINATIONAL enable that TRACES TO A TOP-LEVEL
#       INPUT (the input port directly, or via `assign`/`wire = ...` chains of
#       combinational signals) — an environment-controllable enable that can be
#       held HIGH across reset, AND
#   (c) the module contains NO registered armed/settle/valid-after-reset
#       qualifier (a reg whose name signals a post-reset settle guard).
#
# This is deliberately conservative: the ubiquitous legitimate shape
# `if(!rst_n) x<=0; else x<=d;` (unconditional else) does NOT fire (no level
# enable in the else branch); a counter gated by an INTERNAL (clocked / derived)
# enable does NOT fire (the enable is not environment-held-across-reset); and a
# design that already carries an armed/settle qualifier does NOT fire. Advisory
# WARN only. chip-AGNOSTIC: pure SV structure, no chip/vendor/SKU literal.
# ---------------------------------------------------------------------------
_ARMED_QUALIFIER_RE = re.compile(
    r'\b\w*(?:armed|settl|reset_done|rst_done|reset_rel|rst_rel|por_done|'
    r'init_done|valid_after_reset|ready_after_reset|warmup|warm_up|'
    r'startup_done|boot_done|came_out_of_reset)\w*\b', re.I)


def _collect_input_ports(src: str) -> Set[str]:
    """Top-level input port names (chip-AGNOSTIC structural scan)."""
    ports: Set[str] = set()
    for m in re.finditer(
            r'\binput\b(?:\s+wire|\s+reg|\s+logic)?(?:\s+signed)?\s*'
            r'(?:\[[^\]]+\]\s*)?([A-Za-z_]\w*)\s*(?=[,;)=])', src):
        nm = m.group(1)
        if nm and nm not in VERILOG_KEYWORDS:
            ports.add(nm)
    # ANSI port lists pack several names per `input` keyword:
    #   `module m(input clk, rst_n, we, output ...)` — `rst_n` and `we` follow a
    #   comma, not their own `input`. Walk the port-list header and attribute
    #   every bare name after an `input` (until the next direction keyword) as an
    #   input. Pure structural, no literals.
    # Walk EVERY module header (multi-module files: a non-first module's inputs
    # are otherwise missed because comma-separated names lack their own `input`).
    for hm in re.finditer(r'\bmodule\b\s+\w+\s*(#\s*\([^)]*\)\s*)?\(', src):
        depth = 0
        end = hm.end() - 1
        while end < len(src):
            if src[end] == '(':
                depth += 1
            elif src[end] == ')':
                depth -= 1
                if depth == 0:
                    break
            end += 1
        header = src[hm.end():end]
        cur_dir = None
        for tok in re.finditer(r'\b(input|output|inout)\b|([A-Za-z_]\w*)', header):
            if tok.group(1):
                cur_dir = tok.group(1)
            elif tok.group(2):
                nm = tok.group(2)
                if nm in VERILOG_KEYWORDS or nm in ('wire', 'reg', 'logic',
                                                    'signed', 'unsigned'):
                    continue
                if cur_dir == 'input':
                    ports.add(nm)
    return ports


def _traces_to_input(sig: str, input_ports: Set[str], combinational: Dict[str, str],
                     clocked: Set[str], _seen: Set[str] | None = None) -> bool:
    """True if `sig` is a top-level input, or a purely-combinational signal
    (`assign`/`wire = ...`) whose RHS chain reaches a top-level input WITHOUT
    passing through a clocked/registered signal. Conservative: a signal driven
    by a clocked reg short-circuits to False (it is not environment-held).
    """
    if _seen is None:
        _seen = set()
    if sig in input_ports:
        return True
    if sig in clocked:
        return False
    if sig in _seen:
        return False
    _seen.add(sig)
    rhs = combinational.get(sig)
    if rhs is None:
        return False
    for tok in re.findall(r'[A-Za-z_]\w*', rhs):
        if tok in VERILOG_KEYWORDS:
            continue
        if _traces_to_input(tok, input_ports, combinational, clocked, _seen):
            return True
    return False


def _enable_fanin_text(expr: str, combinational: Dict[str, str],
                       _seen: Set[str] | None = None) -> str:
    """Concatenate `expr` with the RHS text of every combinational signal it
    transitively reads. Used to detect reset-self-gating ANYWHERE in the enable's
    fan-in (e.g. `wire dw = we & rst_n; ... else if(dw) ...` — `dw` is already
    held low while reset is asserted, so it is NOT a residual-enable hole)."""
    if _seen is None:
        _seen = set()
    parts = [expr]
    for tok in re.findall(r'[A-Za-z_]\w*', expr):
        if tok in VERILOG_KEYWORDS or tok in _seen:
            continue
        _seen.add(tok)
        rhs = combinational.get(tok)
        if rhs is not None:
            parts.append(_enable_fanin_text(rhs, combinational, _seen))
    return ' '.join(parts)


def rule_reset_boundary_residual_enable(src: str, path: str) -> List[Finding]:
    """Rule 12 (ORGANIC #723) — flag a reset-cleared register updated under a
    level-sensitive, top-level-input-traced enable with no armed/settle guard."""
    findings: List[Finding] = []
    input_ports = _collect_input_ports(src)
    if not input_ports:
        return findings

    # (c) module-wide: if any registered armed/settle qualifier exists, the
    # design already guards the reset boundary — never fire.
    # `clocked_lhs`: every `<=` (NBA) target in the file. Used both as the
    # armed/settle disqualifier set and as the "not environment-held" short
    # circuit in `_traces_to_input` (a registered signal is never an external
    # held-high enable). Over-approximating membership is the safe direction.
    clocked_lhs: Set[str] = set()
    for mm in re.finditer(r'(?<![<>!=])\b(\w+)(?:\[[^\]]+\])?\s*<=(?!=)', src):
        clocked_lhs.add(mm.group(1))
    if any(_ARMED_QUALIFIER_RE.search(nm) for nm in clocked_lhs):
        return findings

    # Combinational fan-in map: `assign X = expr;` and `wire X = expr;`.
    combinational: Dict[str, str] = {}
    for m in re.finditer(r'\bassign\s+([A-Za-z_]\w*)\s*=\s*([^;]+);', src):
        combinational.setdefault(m.group(1), m.group(2))
    for m in re.finditer(
            r'\bwire\b(?:\s+signed)?\s*(?:\[[^\]]+\]\s*)?'
            r'([A-Za-z_]\w*)\s*=\s*([^;]+);', src):
        if m.group(1) not in VERILOG_KEYWORDS:
            combinational.setdefault(m.group(1), m.group(2))

    # Scan each posedge/negedge always block for the reset-clear + level-enable
    # update on the SAME register.
    block_re = re.compile(r'\balways\s*@\s*\(\s*(?:pos|neg)edge\b[^)]*\)',
                          re.M | re.S)
    for bm in block_re.finditer(src):
        body_start = bm.end()
        # Extract the block body (begin..end or up to the next top-level always /
        # end-of-module). We only need the if/else-if chain text.
        tail = src[body_start:]
        # Bound the body: stop at the next `always`/`endmodule` at any depth — the
        # if-chain we care about is always at the head of the block.
        nxt = re.search(r'\balways\b|\bendmodule\b', tail)
        body = tail[:nxt.start()] if nxt else tail

        # (a) reset-clear: `if (<reset-cond>) <reg> <= 0;` (or '0 / {N{1'b0}}).
        # The reset condition references a reset-name signal.
        for rm in re.finditer(
                r'\bif\s*\(\s*([^()]*)\)\s*'
                r'([A-Za-z_]\w*)\s*<=\s*'
                r"(?:\d+'[bhdo]?0+|'0|0|\{[^{}]*1'b0[^{}]*\})\s*;",
                body):
            cond, reg = rm.group(1), rm.group(2)
            if not _RESET_NAME_RE.search(cond):
                continue
            # (b) same register updated under an `else if(<enable>) reg <= ...`.
            after = body[rm.end():]
            em = re.match(
                r'\s*else\s+if\s*\(\s*([^()]*(?:\([^()]*\)[^()]*)*)\)\s*'
                r'(?:begin\b)?\s*' + re.escape(reg) + r'\s*<=',
                after)
            if not em:
                continue
            enable_expr = em.group(1)
            enable_ids = [t for t in re.findall(r'[A-Za-z_]\w*', enable_expr)
                          if t not in VERILOG_KEYWORDS]
            if not enable_ids:
                continue
            # the enable must NOT reference reset anywhere in its combinational
            # fan-in (an enable like `(en & rst_n)`, directly or via a `wire dw =
            # we & rst_n;` chain, already self-gates on reset release and is not
            # a residual-enable hole).
            if _RESET_NAME_RE.search(_enable_fanin_text(enable_expr, combinational)):
                continue
            # at least one enable identifier must trace to a top-level input via
            # a purely-combinational chain (not through a clocked reg).
            traced = next(
                (t for t in enable_ids
                 if _traces_to_input(t, input_ports, combinational, clocked_lhs)),
                None)
            if traced is None:
                continue
            lineno = src[:body_start + rm.start()].count('\n') + 1
            f = Finding(
                path, lineno, 'WARN', 'reset-boundary-residual-enable', reg,
                f"register `{reg}` is reset-cleared to 0 then updated under the "
                f"level-sensitive enable `{enable_expr.strip()}` (traces to "
                f"top-level input `{traced}`) with no registered armed/settle "
                f"qualifier. A held-high enable can perform a transfer on the "
                f"FIRST post-reset clock edge, breaking the post-reset invariant. "
                f"Fix: add a registered armed/settle guard that blocks the update "
                f"until reset has been de-asserted for >= 1 full cycle (e.g. "
                f"`else if (armed && {enable_expr.strip()}) {reg} <= ...`).")
            # ORGANIC #770 round-2 — this rule is a LEVEL-ENABLE HEURISTIC: it
            # GUESSES, from a held-high enable tracing to a top-level input, that
            # a post-reset transfer is a bug. But a held-high enable on the first
            # post-reset edge is the CORRECT behaviour for the overwhelming
            # majority of valid/ready / capture registers (e.g. AXI `awvalid_q`,
            # `wvalid_q`, `timeout_flag_q`) — there is NO structural corroboration
            # that the post-reset transfer violates this design's intent. The
            # finding is PROSE_HEURISTIC with NO structural corroboration → it is
            # advisory ONLY, never a hard veto. (Non-strict callers already only
            # WARNed; this routes it out of the rc=1 / sole-emit BLOCK set.)
            f = _advisory(f, _prov.PROSE_HEURISTIC, _prov.NO_CORROBORATION)
            findings.append(f)
            break  # one finding per block is enough
    return findings


# ---------------------------------------------------------------------------
# Rule 13: Multidriven register — same reg written from >1 always block in
# genuinely different / racing clocking domains (ORGANIC #740, G4)
#
# A register written from MORE THAN ONE always block is the classic
# `verilator -Wall MULTIDRIVEN` warning: the two procedural drivers can both
# execute and the last-scheduled write wins non-deterministically. Today this
# is caught ONLY by an external `verilator -Wall`; this rule makes it a
# plugin-native, structural, advisory WARN that needs no external tool.
#
# FIRE (WARN) when the SAME reg LHS is assigned (`<=`/`=`) in >=2 distinct
# `always` blocks AND those writers can RACE:
#   * DIFFERENT clock/edge domains — block A is `@(posedge clk_a)` and block B
#     is `@(posedge clk_b)` (or `posedge`/`negedge` of the same clock): the
#     writes are unsynchronised → always a real multidriven hazard (this is
#     exactly what Verilator flags); OR
#   * SAME clock but the per-block writes to the reg are NOT mutually-exclusively
#     guarded — e.g. one block clears the reg under `if(<rst>)` while the other
#     writes it UNCONDITIONALLY (the acceptance shape: `if(rst) mem0<=0;` in one
#     block and `mem0<=mem0+1;` in another). Both fire on a reset edge → race.
#
# DO NOT FIRE (chip-AGNOSTIC, fail-SAFE — never false-WARN a legal shape):
#   * the reg is written in only ONE always block (incl. the in-block
#     `if(rst) x<=0; else x<=d;` reset+datapath idiom — one block, never racing);
#   * SAME clock AND the writer blocks are reset-COMPLEMENTARY-guarded — one
#     writes the reg only inside `if(<rst>)` and the other only inside
#     `if(!<rst>)` / `else` (they never both fire on one edge → legal split);
#   * the writers target DISJOINT bit-slices of the reg (`q[1:0]<=..` in one
#     block, `q[3:2]<=..` in another) — distinct drivers of distinct bits. This
#     exemption is PAIRWISE over ANY writer count: a reg legally split across
#     3+ always blocks (each driving its own slice) is silent too.
# Advisory WARN only; structural SV parse; no chip/vendor/SKU literal.
# ---------------------------------------------------------------------------
def _blank_string_literals(src: str) -> str:
    """Replace the INTERIOR of every Verilog double-quoted string literal with
    spaces (preserving the surrounding quotes, the TOTAL length, and every
    newline) so a keyword-shaped token inside a `$display`/`$error`/parameter
    string — e.g. the word `endmodule` or `module` — is never parsed as a
    structural boundary. Because length + newline positions are preserved, a
    caller can scan the blanked copy and index back into the ORIGINAL `src` at
    the same offsets. chip-AGNOSTIC: pure Verilog string grammar.

    ORGANIC #782 r2 (Step-2.7 §4.05): an `endmodule` token inside a string
    literal truncated `_module_regions` BEFORE a genuine same-module multidriven
    / continuous-procedural defect, so the region-scoped scan missed it (the
    masked register/illegal-l-value race verilator/iverilog flag as a real
    error). Blanking the string interior closes that leak without shifting any
    offset."""
    def _blank(m: "re.Match") -> str:
        body = m.group(0)[1:-1]
        inner = ''.join('\n' if c == '\n' else ' ' for c in body)
        return '"' + inner + '"'
    return re.sub(r'"(?:\\.|[^"\\])*"', _blank, src)


def _module_regions(src: str) -> List[Tuple[str, int, int]]:
    """ORGANIC R8C3 (#782) — partition a (comment-stripped) source file into its
    top-level module regions: a list of (module_name, start_off, end_off) where
    [start_off, end_off) spans from the `module NAME` keyword through its
    matching `endmodule`. A register name is only a multi-driven candidate when
    its driving always blocks live in the SAME module region; without this, two
    DISTINCT registers that merely SHARE A NAME across sibling modules (e.g. a
    `bit_count`/`data_reg` in both a `tx_block` and an `rx_block`) collide in the
    whole-file flat scan and false-fire as a bogus cross-domain multidriven race
    even though verilator -Wall reports ZERO MULTIDRIVEN. Verilog forbids nested
    module definitions, so a simple keyword walk (no brace nesting) is exact and
    chip-AGNOSTIC. A region before the first `module` (none, in legal SV) or an
    unterminated final module both degrade safely to the file tail.

    ORGANIC #782 r2 (Step-2.7 §4.05) — the `module`/`endmodule` walk runs over a
    STRING-BLANKED copy so a keyword token buried in a `$display`/`$error`
    string never mis-truncates a region (length-preserving, so the offsets still
    index the real `src`)."""
    regions: List[Tuple[str, int, int]] = []
    scan = _blank_string_literals(src)
    # `module NAME` … `endmodule`, scanned left-to-right. Verilog disallows a
    # module declaration inside another, so the next `endmodule` after a
    # `module NAME` always closes THAT module.
    for mm in re.finditer(r'\bmodule\b\s+([A-Za-z_]\w*)', scan):
        name = mm.group(1)
        start = mm.start()
        em = re.search(r'\bendmodule\b', scan[mm.end():])
        end = (mm.end() + em.end()) if em else len(src)
        regions.append((name, start, end))
    if not regions:
        regions.append(('', 0, len(src)))
    return regions


def _iter_always_blocks(src: str, region: Optional[Tuple[int, int]] = None):
    """Yield (sens_list_text, body_text, abs_start_offset) for every
    `always`/`always_ff`/`always_comb`/`always_latch` block. The body is bounded
    at the next top-level `always`/`endmodule` (the same head-of-block bounding
    the other rules use).

    ORGANIC R8C3 (#782) — when `region`=(lo,hi) is given, only blocks whose
    header starts inside [lo,hi) are yielded (used by rule_multidriven_register
    to confine multi-driven candidacy to a SINGLE module scope). The returned
    `abs_start_offset` is always relative to the FULL `src` so line numbers stay
    correct, and the bounded body still stops at the next always/endmodule —
    which, for the last block of a region, is that region's own `endmodule`."""
    for bm in re.finditer(r'\balways(?:_ff|_comb|_latch)?\s*@\s*\(([^)]*)\)', src):
        if region is not None and not (region[0] <= bm.start() < region[1]):
            continue
        sens = bm.group(1)
        body = _block_body_after(src, bm.end())
        yield sens, body, bm.start()


def _reg_write_guard_in_block(body: str, reg: str):
    """Classify how `reg` is written inside one always-block `body`.

    Returns a tuple (writes, slices, reset_pos, reset_neg, unconditional):
      * writes        — True if `reg` is a `<=`/`=` LHS anywhere in the block.
      * slices        — set of bit-slice strings written (`'[1:0]'`); the empty
                        string '' means a WHOLE-reg (un-sliced) write.
      * reset_pos     — True if EVERY write of `reg` is dominated by an
                        `if (<reset>)` (asserted-reset) condition.
      * reset_neg     — True if EVERY write of `reg` is dominated by an
                        `if (!<reset>)` / `else`-of-reset (deasserted) condition.
      * unconditional — True if at least one write of `reg` is NOT under any
                        reset-referencing `if`.
    Conservative & structural: a write is "reset-dominated" only when the
    nearest enclosing `if` condition (on the same source line region) references
    a reset-name signal. Deliberately simple — it just needs to separate the
    racing acceptance shape from the complementary legal split.
    """
    writes = False
    slices: Set[str] = set()
    reset_branch_only = True
    notreset_branch_only = True
    any_unconditional = False
    for am in re.finditer(
            r'(?<![<>!=])\b' + re.escape(reg) + r'\s*(\[[^\]]+\])?\s*(?:<=|=)(?!=)',
            body):
        writes = True
        slices.add((am.group(1) or '').replace(' ', ''))
        # The text from the block start up to this write tells us the nearest
        # governing condition. Find the LAST `if (...)` / `else` before it.
        prefix = body[:am.start()]
        ifs = list(re.finditer(r'\b(if)\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)|\b(else)\b',
                               prefix))
        gov = ifs[-1] if ifs else None
        if gov is None:
            any_unconditional = True
            reset_branch_only = False
            notreset_branch_only = False
            continue
        if gov.group(1) == 'if':
            cond = gov.group(2) or ''
            if _RESET_NAME_RE.search(cond):
                # determine polarity: a `!`/`~` / `==0` → deassert (complement)
                if '!' in cond or '~' in cond or re.search(r'==\s*0', cond):
                    notreset_branch_only = notreset_branch_only and True
                    reset_branch_only = False
                else:
                    reset_branch_only = reset_branch_only and True
                    notreset_branch_only = False
            else:
                any_unconditional = True
                reset_branch_only = False
                notreset_branch_only = False
        else:  # else-branch — the complement of the preceding reset `if`
            notreset_branch_only = notreset_branch_only and True
            reset_branch_only = False
    return (writes, slices,
            reset_branch_only and writes,
            notreset_branch_only and writes,
            any_unconditional)


def _slices_disjoint(slices_a: Set[str], slices_b: Set[str]) -> bool:
    """True if every write in A targets a bit-slice and every write in B
    targets a bit-slice and the two slice SETS share no slice and neither writes
    the WHOLE reg (the '' marker). Conservative: any whole-reg write ('') in
    either set means they are NOT disjoint."""
    if '' in slices_a or '' in slices_b:
        return False
    if not slices_a or not slices_b:
        return False
    return slices_a.isdisjoint(slices_b)


def _all_slices_pairwise_disjoint(slice_sets: List[Set[str]]) -> bool:
    """True when N (>=2) writer blocks each drive a DISTINCT bit-slice of a reg
    and NO two writers touch overlapping bits — i.e. every PAIR of writer
    slice-sets is `_slices_disjoint`. This generalises the disjoint-slice
    exemption from exactly-two writers to any writer count (2, 3, …): a register
    legally split across 3+ always blocks, each driving its own slice, is NOT a
    multidriven hazard (matches `verilator -Wall` reporting 0 MULTIDRIVEN).

    Conservative / fail-SAFE: reuses `_slices_disjoint`, so a whole-reg ('')
    write in ANY block, an empty slice-set, or ANY shared slice string between
    two blocks makes the group NOT-disjoint (so the genuine multidriven WARN can
    still fire). Requires >=2 sets; fewer is not a multidriven situation."""
    if len(slice_sets) < 2:
        return False
    for i in range(len(slice_sets)):
        for j in range(i + 1, len(slice_sets)):
            if not _slices_disjoint(slice_sets[i], slice_sets[j]):
                return False
    return True


def _edge_domain(sens: str) -> frozenset:
    """The (edge, signal) clocking domain of an always sensitivity list, e.g.
    {('posedge','clk')}. A level-sensitive / `*` list yields the empty set."""
    return frozenset(
        (m.group(1), m.group(2))
        for m in re.finditer(r'\b(pos|neg)edge\s+([A-Za-z_]\w*)', sens))


def _names_written_nba_in_edge_block(src: str) -> Set[str]:
    """ORGANIC #770 r2 Step-2.7 — names that receive a NON-BLOCKING (`<=`) write
    inside an EDGE-sensitive (`@(posedge/negedge …)`) always block: i.e. real
    sequential STATE / accumulators. Such a name is NEVER a mere loop index even
    if declared `integer`. chip-AGNOSTIC: pure edge-block + NBA grammar."""
    names: Set[str] = set()
    for bm in re.finditer(
            r'always(?:_ff)?\s*@\s*\(\s*(?:posedge|negedge)\b[^)]*\)',
            src, re.I):
        tail = src[bm.end():]
        nxt = re.search(r'\balways(?:_ff|_comb|_latch)?\b|\bendmodule\b', tail)
        body = tail[:nxt.start()] if nxt else tail
        for am in re.finditer(r'([A-Za-z_]\w*)(?:\s*\[[^\]]*\])?\s*<=', body):
            names.add(am.group(1))
    return names


def _loop_index_and_genvar_names(src: str) -> Set[str]:
    """Names that are LOOP-CONTROL / elaboration variables, NOT state/data
    registers: a `genvar NAME;`, or a `for (NAME = ...)` control variable /
    `integer NAME;` THAT HAS NO clocked (NBA-in-edge-block) write. ORGANIC #770
    round-2 (+ Step-2.7 tightening).

    A loop-index `i` reused across several `for` loops in different always
    blocks is NOT a multi-driven STATE register. BUT `integer` is also the
    canonical idiom for a wide counter/accumulator: a true cross-domain
    accumulator (`integer acc; always @(posedge clkX) acc <= ...`) IS legitimate
    multi-driven state and must KEEP its WARN — so a name written by a
    non-blocking assignment inside an edge-sensitive block is EXCLUDED from this
    loop-index set even if declared `integer`. chip-AGNOSTIC."""
    clocked = _names_written_nba_in_edge_block(src)
    names: Set[str] = set()
    # `genvar NAME;` is ALWAYS elaboration-only (never a data reg).
    for m in re.finditer(r'\bgenvar\b\s+([^;]+);', src):
        for nm in m.group(1).split(','):
            nm = re.sub(r'=.*', '', nm).strip()
            nm = re.sub(r'\[.*', '', nm).strip()
            if re.fullmatch(r'[A-Za-z_]\w*', nm or '') and nm not in VERILOG_KEYWORDS:
                names.add(nm)
    # `integer NAME;` — a loop/elaboration counter ONLY if it has no clocked write.
    for m in re.finditer(r'\binteger\b\s+([^;]+);', src):
        for nm in m.group(1).split(','):
            nm = re.sub(r'=.*', '', nm).strip()
            nm = re.sub(r'\[.*', '', nm).strip()
            if (re.fullmatch(r'[A-Za-z_]\w*', nm or '')
                    and nm not in VERILOG_KEYWORDS and nm not in clocked):
                names.add(nm)
    # `for (NAME = ...)` control variable — excludable only when not clocked-written.
    for m in re.finditer(r'\bfor\s*\(\s*([A-Za-z_]\w*)\s*=', src):
        nm = m.group(1)
        if nm not in VERILOG_KEYWORDS and nm not in clocked:
            names.add(nm)
    return names


def rule_multidriven_register(src: str, path: str) -> List[Finding]:
    """Rule 13 (ORGANIC #740 G4) — WARN when a reg is driven from >1 always
    block in a racing/different clocking domain."""
    findings: List[Finding] = []
    # ORGANIC #770 round-2 — loop-index integers / genvars are NOT state
    # registers; exclude them so a `for`-loop control var `i` reused across two
    # always blocks does not false-fire as a multi-driven STATE race. No-leak: a
    # genuine DATA/STATE reg (declared `reg`/`logic`, written as an FSM/datapath
    # value) is never in this set, so a real multi-driven register still WARNs.
    loop_ctrl = _loop_index_and_genvar_names(src)
    # ORGANIC R8C3 (#782) — PARTITION always-block discovery by MODULE scope
    # before building reg_block_idx. A register name is only a multi-driven
    # candidate when its >1 driving always blocks live in the SAME module. Two
    # DISTINCT registers that merely share a name across sibling modules (a
    # `bit_count` / `data_reg` in both a `tx_block` and an `rx_block`) were
    # colliding in the whole-file flat scan and false-firing a bogus
    # DIFFERENT-clocking multidriven race even though verilator -Wall reports
    # ZERO MULTIDRIVEN. No-leak: a genuine SAME-module two-block race still
    # collides within one region and still WARNs (verified). chip-AGNOSTIC: pure
    # module-scope parse.
    for _mname, _mlo, _mhi in _module_regions(src):
        findings += _multidriven_in_region(src, path, _mlo, _mhi, loop_ctrl)
    return findings


def _multidriven_in_region(src: str, path: str, mlo: int, mhi: int,
                           loop_ctrl: Set[str]) -> List[Finding]:
    """ORGANIC R8C3 (#782) — the original whole-file multidriven body, now
    confined to a SINGLE module region [mlo,mhi). Block indices/domains/guards
    are all computed only from blocks inside this region, so same-named regs in
    sibling modules never collide."""
    findings: List[Finding] = []
    blocks = [(sens, body, pos)
              for sens, body, pos in _iter_always_blocks(src, (mlo, mhi))]
    if len(blocks) < 2:
        return findings
    # collect every reg-like LHS per block (NBA or blocking) with its slice info
    # so we can see which regs are written by >1 block.
    reg_block_idx: Dict[str, List[int]] = {}
    for idx, (sens, body, pos) in enumerate(blocks):
        for am in re.finditer(
                r'(?<![<>!=])\b([A-Za-z_]\w*)\s*(?:\[[^\]]+\])?\s*(?:<=|=)(?!=)',
                body):
            nm = am.group(1)
            if nm in VERILOG_KEYWORDS:
                continue
            reg_block_idx.setdefault(nm, [])
            if idx not in reg_block_idx[nm]:
                reg_block_idx[nm].append(idx)
    for reg, idxs in sorted(reg_block_idx.items()):
        if len(idxs) < 2:
            continue
        # ORGANIC #770 round-2 — a loop-index integer / genvar is a transient
        # iteration counter, not a multi-driven STATE/data register; skip it.
        if reg in loop_ctrl:
            continue
        # gather per-block clocking domain + guard classification for THIS reg
        domains = [_edge_domain(blocks[i][0]) for i in idxs]
        guards = [_reg_write_guard_in_block(blocks[i][1], reg) for i in idxs]
        # (1) disjoint bit-slice writers → distinct drivers, not a race. This
        # holds for ANY writer count (2, 3, …): if every PAIR of writer blocks
        # drives non-overlapping bit-slices of `reg`, each block owns its own
        # bits and there is no multidriven hazard (verilator -Wall reports 0
        # MULTIDRIVEN). A single whole-reg / overlapping write breaks disjointness
        # and falls through to the genuine-race checks below.
        slice_sets = [g[1] for g in guards]   # g = (writes, slices, ...)
        if _all_slices_pairwise_disjoint(slice_sets):
            continue
        # (2) different clocking domains among the writers → ALWAYS a race
        # (this is exactly verilator's MULTIDRIVEN: "different clocking").
        distinct_domains = {d for d in domains if d}
        different_clocking = len(distinct_domains) > 1
        if different_clocking:
            lineno = src[:blocks[idxs[0]][2]].count('\n') + 1
            doms = sorted(
                "/".join(f"{e} {s}" for e, s in sorted(d)) or "comb"
                for d in distinct_domains)
            findings.append(Finding(
                path, lineno, 'WARN', 'multidriven-register', reg,
                f"register `{reg}` is driven from {len(idxs)} always blocks "
                f"with DIFFERENT clocking domains ({', '.join(doms)}) — the "
                f"writes are unsynchronised and the last-scheduled one wins "
                f"non-deterministically (`verilator -Wall` MULTIDRIVEN). Drive "
                f"`{reg}` from a SINGLE always block."))
            continue
        # (3) SAME clocking domain — fire ONLY when the writers can RACE on a
        # shared edge: i.e. they are NOT reset-complementary-guarded. The legal
        # split (`if(rst) x<=0;` in one block, `if(!rst) x<=..;` in another)
        # never both-fires on one edge → no WARN. The acceptance shape (one
        # reset-clear block + one UNCONDITIONAL datapath block) races → WARN.
        any_unconditional = any(g[4] for g in guards)
        has_reset_clear = any(g[2] for g in guards)
        all_reset_complementary = (
            all(g[2] or g[3] for g in guards)        # every block reset-guarded
            and any(g[2] for g in guards)            # at least one assert-side
            and any(g[3] for g in guards))           # at least one deassert-side
        if all_reset_complementary and not any_unconditional:
            continue                                 # legal reset/datapath split
        if any_unconditional and has_reset_clear:
            lineno = src[:blocks[idxs[0]][2]].count('\n') + 1
            findings.append(Finding(
                path, lineno, 'WARN', 'multidriven-register', reg,
                f"register `{reg}` is driven from {len(idxs)} always blocks "
                f"(multidriven): one block reset-clears it while another writes "
                f"it UNCONDITIONALLY under the same clock, so both fire on a "
                f"reset edge and the last-scheduled write wins "
                f"non-deterministically (`verilator -Wall` MULTIDRIVEN). Merge "
                f"the writes into ONE always block (gate the datapath update "
                f"with the same reset/else the clear uses)."))
    return findings


# ---------------------------------------------------------------------------
# Rule 13b (ORGANIC R8C3, #782) — CONTINUOUS-vs-PROCEDURAL driver on SAME net.
# ---------------------------------------------------------------------------
# A net driven by a continuous `assign` AND ALSO written from a procedural
# `always` block is illegal: iverilog -g2012 rejects it ("not a valid l-value
# for a procedural assignment / declared here as a wire") and verilator -Wall
# emits %Error-PROCASSWIRE. rule_multidriven_register only models always-vs-
# always races and SHORT-CIRCUITS on <2 always blocks, so a single procedural
# block fighting a continuous assign (the canonical `binary_to_gray` defect)
# was missed entirely. This is a hard, two-tool-corroborated structural defect
# — chip-AGNOSTIC, pure SV parse.
def _match_begin_end(src: str, begin_kw_off: int) -> int:
    """Given the offset of a `begin` keyword, return the offset just past its
    matching `end`. begin/end nest; the scanner also tracks the structural
    keyword pairs that introduce their OWN begin-less arms
    (case/casez/casex…endcase, function…endfunction, task…endtask,
    fork…join[_any|_none]) by counting them on the SAME depth stack so an inner
    `case` arm's `end`-less statements never desync the begin/end balance.
    chip-AGNOSTIC: pure SystemVerilog block grammar."""
    depth = 0
    for m in re.finditer(
            r'\b(begin|end|case|casez|casex|endcase|function|endfunction|'
            r'task|endtask|fork|join|join_any|join_none)\b',
            src[begin_kw_off:]):
        kw = m.group(1)
        if kw in ('begin', 'case', 'casez', 'casex', 'function', 'task', 'fork'):
            depth += 1
        else:  # end / endcase / endfunction / endtask / join*
            depth -= 1
            if depth == 0:
                return begin_kw_off + m.end()
    return len(src)


def _norm_cond(text: str) -> str:
    """Collapse a generate-if condition to a whitespace-insensitive canonical
    form (drop ALL whitespace). chip-AGNOSTIC: pure text normalisation (#799)."""
    return re.sub(r'\s+', '', text)


def _conditions_complementary(a: str, b: str) -> bool:
    """ORGANIC #799 (cross-ref #788) — True when two SEPARATE single-arm
    generate-if conditions are STRUCTURALLY complementary, i.e. exactly one of
    them can ever hold, so a driver in each can never co-elaborate:

      * logical negation        COND vs !COND   (either order)
      * equality vs inequality  X==K  vs X!=K   (same LHS, same RHS, either order)

    Both forms are decidable at elaboration time from the source text alone, so
    pairing them is sound WITHOUT a parameter solver. Anything not provably
    complementary (`if(A)` vs `if(B)`, `if(X==1)` vs `if(X==2)`) returns False so
    a genuine potential multidriver STAYS flagged.

    DELIBERATELY excludes bitwise `~COND`: `!X` is the boolean complement for ANY
    width (`!1==0`, `!0==1`), but `~X` is the bit-complement, so for a >1-bit
    operand `~EN` is still truthy when `EN` is truthy (EN=1 → ~EN=…1110 ≠ 0) and
    BOTH `if(EN)` / `if(~EN)` arms elaborate — a GENUINE multidriver
    (iverilog -g2012 rc=1). Pairing `~` would suppress that real race, so only
    `!` is a complement. chip-AGNOSTIC: pure SV expression grammar."""
    na, nb = _norm_cond(a), _norm_cond(b)
    if not na or not nb:
        return False
    # logical negation: one side is `!X` and the other is bare `X`
    for hi, lo in ((na, nb), (nb, na)):
        if hi[:1] == '!' and hi[1:2] != '=' and hi[1:] == lo:
            return True
        # tolerate a redundant outer paren on the negated side: `!(X)` vs `X`
        if hi[:2] == '!(' and hi[-1:] == ')' and hi[2:-1] == lo:
            return True
    # equality vs inequality over the SAME operands: `LHS==RHS` vs `LHS!=RHS`
    for x, y in ((na, nb), (nb, na)):
        me = re.fullmatch(r'(.+?)==(.+)', x)
        mn = re.fullmatch(r'(.+?)!=(.+)', y)
        if me and mn and me.group(1) == mn.group(1) and me.group(2) == mn.group(2):
            return True
    return False


def _generate_if_arms(src: str, mlo: int, mhi: int) -> List[List[Tuple[int, int]]]:
    """ORGANIC GAP-A — return the mutually-exclusive arm spans of every
    conditional-generate `if … begin:lbl … end else [if …] begin:lbl … end`
    chain inside module region [mlo,mhi). Each returned group is a list of
    (arm_start_off, arm_end_off) byte spans; AT MOST ONE arm of a group ever
    elaborates, so two drivers landing in DIFFERENT arms of the SAME group are
    mutually exclusive and can never co-drive a net.

    Only NAMED begin-block arms (`begin : label`) are tracked — a named begin
    immediately after `if(...)`/`else` is the canonical conditional-generate
    marker (`if (USE_FF) begin : gen_ff … end else begin : gen_comb …`). A bare
    procedural `if` inside an always block uses an UN-named begin (or no begin),
    so it is never picked up here; this keeps the suppression structurally
    confined to elaboration-time generate selection and never relaxes a genuine
    procedural same-scope race. chip-AGNOSTIC: pure SV generate-if grammar.

    ORGANIC #799 (cross-ref #788) — ALSO pairs two SEPARATE single-arm
    generate-if blocks whose conditions are structurally complementary
    (`if(COND) begin:gen_a … end` and `if(!COND) begin:gen_b … end`, NOT an
    if/else chain). #788 only walked the if/ELSE chain, so a net split across two
    complementary stand-alone ifs falsely tripped
    multidriven-continuous-procedural even though iverilog -g2012 elaborates
    exactly one arm (rc=0). Each complementary pair is emitted as its own 2-arm
    group so the two drivers read as mutually exclusive."""
    groups: List[List[Tuple[int, int]]] = []
    # #799 — stand-alone single-arm generate-ifs collected for complementary
    # pairing: (normalised-condition-text, begin_off, end_off).
    singles: List[Tuple[str, int, int]] = []
    consumed_until = mlo
    for ifm in re.finditer(r'\bif\b\s*\(', src[mlo:mhi]):
        if_abs = mlo + ifm.start()
        if if_abs < consumed_until:
            continue  # already swallowed as the `else if` of an earlier chain
        # balance the if-condition parens
        popen = mlo + ifm.end() - 1
        depth = 0
        cclose = -1
        j = popen
        while j < mhi:
            c = src[j]
            if c == '(':
                depth += 1
            elif c == ')':
                depth -= 1
                if depth == 0:
                    cclose = j
                    break
            j += 1
        if cclose < 0:
            continue
        cond_text = src[popen + 1:cclose]  # #799 — for complementary pairing
        # require a NAMED begin block immediately after the condition
        bm = re.match(r'\s*begin\b\s*:\s*[A-Za-z_]\w*', src[cclose + 1:mhi])
        if not bm:
            continue
        begin_kw = src.index('begin', cclose + 1)
        arm_end = _match_begin_end(src, begin_kw)
        arms = [(begin_kw, arm_end)]
        # walk the `else` / `else if` chain — all arms are mutually exclusive
        cur = arm_end
        while True:
            em = re.match(r'\s*else\b', src[cur:mhi])
            if not em:
                break
            after_else = cur + em.end()
            ifm2 = re.match(r'\s*if\b\s*\(', src[after_else:mhi])
            if ifm2:  # else if (...) begin : lbl
                po = after_else + ifm2.end() - 1
                d = 0
                k = po
                cc = -1
                while k < mhi:
                    if src[k] == '(':
                        d += 1
                    elif src[k] == ')':
                        d -= 1
                        if d == 0:
                            cc = k
                            break
                    k += 1
                if cc < 0:
                    break
                bm2 = re.match(r'\s*begin\b\s*:\s*[A-Za-z_]\w*', src[cc + 1:mhi])
                if not bm2:
                    break
                bkw = src.index('begin', cc + 1)
                aend = _match_begin_end(src, bkw)
                arms.append((bkw, aend))
                cur = aend
            else:  # else begin : lbl  (terminal arm)
                bm2 = re.match(r'\s*begin\b\s*:\s*[A-Za-z_]\w*', src[after_else:mhi])
                if not bm2:
                    break
                bkw = src.index('begin', after_else)
                aend = _match_begin_end(src, bkw)
                arms.append((bkw, aend))
                cur = aend
                break
        if len(arms) >= 2:
            groups.append(arms)
            consumed_until = arms[-1][1]
        else:
            # #799 — a stand-alone single-arm generate-if (no else chain).
            # Held back for complementary pairing with another stand-alone if.
            singles.append((cond_text, begin_kw, arm_end))
            consumed_until = arm_end
    # #799 — pair stand-alone single-arm ifs whose conditions are structurally
    # complementary (`if(COND)` + `if(!COND)` / `X==K` + `X!=K`). Each such pair
    # is its own mutually-exclusive 2-arm group. Greedy: each single is consumed
    # by at most one pairing so a non-complementary single is never absorbed.
    used = [False] * len(singles)
    for i in range(len(singles)):
        if used[i]:
            continue
        for k in range(i + 1, len(singles)):
            if used[k]:
                continue
            if _conditions_complementary(singles[i][0], singles[k][0]):
                groups.append([(singles[i][1], singles[i][2]),
                               (singles[k][1], singles[k][2])])
                used[i] = used[k] = True
                break
    return groups


def _drivers_mutually_exclusive(groups: List[List[Tuple[int, int]]],
                                off_a: int, off_b: int) -> bool:
    """True when off_a and off_b fall into DIFFERENT arms of the SAME
    conditional-generate group — i.e. only one of the two drivers ever
    elaborates, so they can never co-drive the net. Returns False when either
    offset is outside every tracked group, or when both land in the SAME arm (a
    genuine same-scope race that MUST stay flagged)."""
    for arms in groups:
        a_idx = next((i for i, (s, e) in enumerate(arms) if s <= off_a < e), None)
        b_idx = next((i for i, (s, e) in enumerate(arms) if s <= off_b < e), None)
        if a_idx is not None and b_idx is not None and a_idx != b_idx:
            return True
    return False


def rule_continuous_vs_procedural_driver(src: str, path: str) -> List[Finding]:
    findings: List[Finding] = []
    for _mname, mlo, mhi in _module_regions(src):
        region = src[mlo:mhi]
        # ORGANIC GAP-A — mutually-exclusive conditional-generate arms in THIS
        # module. A net whose continuous `assign` driver lives in one arm and
        # whose procedural `always` write lives in a DIFFERENT arm of the same
        # generate-if is LEGITIMATE RTL (only one arm ever elaborates), so it
        # must NOT be reported as continuous+procedural multidriven (iverilog
        # -g2012 rc=0 on such a design — confirmed). Track the absolute driver
        # offsets so the two arms can be compared structurally below.
        gen_groups = _generate_if_arms(src, mlo, mhi)
        # Continuous-assign LHS bases in THIS module (`assign NAME ... = ...`),
        # allowing an optional bit/part-select on the target.
        cont_lhs: Set[str] = set()
        cont_line: Dict[str, int] = {}
        cont_off: Dict[str, int] = {}
        for m in re.finditer(r'\bassign\b\s+(?:#\s*\S+\s+)?'
                             r'([A-Za-z_]\w*)(?:\s*\[[^\]]+\])?\s*=(?!=)', region):
            nm = m.group(1)
            if nm in VERILOG_KEYWORDS:
                continue
            cont_lhs.add(nm)
            cont_line.setdefault(nm, src[:mlo + m.start()].count('\n') + 1)
            cont_off.setdefault(nm, mlo + m.start())
        if not cont_lhs:
            continue
        # Procedural-block LHS bases in THIS module (any `<=`/`=` inside an
        # always block body), reusing the module-scoped block iterator.
        # IMPORTANT (no-leak) — `_block_body_after` bounds a body at the next
        # `always`/`endmodule`, so the LAST always block of a module OVERRUNS to
        # `endmodule` and textually swallows any CONTINUOUS `assign` statements
        # that follow it. Those swallowed `assign LHS = …;` are NOT procedural
        # writes — counting them would falsely pair a perfectly legal
        # `always @(*)`-then-`assign data_out=…` design as continuous+procedural.
        # Excise every `assign …;` statement from the body before scanning so
        # only genuine procedural `<=`/`=` writes register as proc_lhs. (iverilog
        # rc=0 / verilator no-PROCASSWIRE on those designs — confirmed.)
        proc_lhs: Set[str] = set()
        proc_line: Dict[str, int] = {}
        proc_off: Dict[str, int] = {}
        for sens, body, pos in _iter_always_blocks(src, (mlo, mhi)):
            # blank out continuous-assign statements (keep length/newlines so the
            # per-write line numbers stay correct)
            body_noassign = re.sub(
                r'\bassign\b[^;]*;',
                lambda m: ''.join('\n' if c == '\n' else ' ' for c in m.group(0)),
                body)
            for am in re.finditer(
                    r'(?<![<>!=])\b([A-Za-z_]\w*)\s*(?:\[[^\]]+\])?\s*(?:<=|=)(?!=)',
                    body_noassign):
                nm = am.group(1)
                if nm in VERILOG_KEYWORDS:
                    continue
                proc_lhs.add(nm)
                # report at the procedural-assignment site (where iverilog points)
                proc_line.setdefault(nm, src[:pos + am.start()].count('\n') + 1)
                proc_off.setdefault(nm, pos + am.start())
        for nm in sorted(cont_lhs & proc_lhs):
            # ORGANIC GAP-A — suppress when the continuous driver and the
            # procedural driver live in MUTUALLY-EXCLUSIVE conditional-generate
            # arms (only one arm elaborates → never a real multidriver). A
            # genuine SAME-scope (or SAME-arm) continuous+procedural race lands
            # both offsets outside any group / in the same arm and STILL fires.
            if _drivers_mutually_exclusive(
                    gen_groups, cont_off.get(nm, -1), proc_off.get(nm, -1)):
                continue
            ln = proc_line.get(nm, cont_line.get(nm, 1))
            findings.append(Finding(
                path, ln, 'ERROR', 'multidriven-continuous-procedural', nm,
                f"net `{nm}` is driven by BOTH a continuous `assign` (line "
                f"{cont_line.get(nm, '?')}) and a procedural `always` block — a "
                f"continuous + procedural driver on the same net is illegal "
                f"(iverilog: '`{nm}` is not a valid l-value for a procedural "
                f"assignment'; `verilator -Wall` PROCASSWIRE). Drive `{nm}` from "
                f"ONE kind of driver only."))
    return findings


# ---------------------------------------------------------------------------
# Rule 14 (ORGANIC #744 R3-1) — divide / modulo by a COMPILE-TIME-ZERO divisor
# ---------------------------------------------------------------------------
# A `localparam [W-1:0] DW = W'(2**W)` truncates to 0 (e.g. 8'(256) == 0), so
# `x % DW` / `x / DW` is modulo/divide-by-ZERO → x at runtime (a functionally
# dead pointer). This passes iverilog -g2012, verilator -Wall, AND every other
# rtl_hygiene rule — only the hidden behavioral scorer catches it. Flag a `%`/`/`
# whose divisor is a constant proven to evaluate to 0 (a width-truncated
# power-of-2-fill literal, or a bare `0` constant). chip-AGNOSTIC: pure constant
# evaluation, no chip/design literal.
_LOCALPARAM_DECL_RE = re.compile(
    r"\b(?:localparam|parameter)\b\s*"
    r"(?:integer\s+|signed\s+|unsigned\s+|logic\s+|bit\s+|reg\s+)*"
    r"(?:\[[^\]]*\]\s*)?"                            # optional packed range [W-1:0] / [7:0]
    r"(?:integer\s+|signed\s+|unsigned\s+)*"
    r"([A-Za-z_]\w*)\s*=\s*([^;]+);")


def _eval_const_int(expr: str, params: Dict[str, int]) -> Optional[int]:
    """Best-effort evaluation of a constant integer expression using only
    already-known localparam/parameter values + ** / + - * // and a SystemVerilog
    width-cast `W'(value)` (which truncates to the low W bits). Returns None when
    not a pure constant (e.g. references a signal / unknown name)."""
    e = expr.strip()
    # SV width cast: <width>'(<inner>)  → inner truncated to `width` low bits.
    m = re.fullmatch(r"\s*([A-Za-z_]\w*|\d+)\s*'\s*\(\s*(.+?)\s*\)\s*", e)
    if m:
        w = _eval_const_int(m.group(1), params)
        inner = _eval_const_int(m.group(2), params)
        if w is None or inner is None or w <= 0 or w > 4096:
            return None
        return inner & ((1 << w) - 1)        # truncate to W low bits
    # sized literal W'dN / W'hN etc. — value modulo 2**W.
    m = re.fullmatch(r"\s*(\d+)\s*'\s*[sS]?[dDhHbBoO]\s*([0-9A-Fa-f_]+)\s*", e)
    if m:
        width = int(m.group(1))
        digits = m.group(2).replace("_", "")
        try:
            val = int(digits, {"d": 10, "h": 16, "b": 2, "o": 8}[
                e[e.index("'") + 1].lower().replace("s", "d")])
        except (ValueError, KeyError):
            return None
        return val & ((1 << width) - 1) if 0 < width <= 4096 else None
    # plain decimal
    if re.fullmatch(r"\d+", e):
        return int(e)
    # known param name
    if re.fullmatch(r"[A-Za-z_]\w*", e) and e in params:
        return params[e]
    # simple binary arithmetic on two constant sub-exprs (no parens beyond cast).
    for op in ("**", "//", "*", "+", "-"):
        # split on the LAST top-level operator (avoid touching '**' as two '*').
        idx = e.rfind(op)
        if idx <= 0 or idx + len(op) >= len(e):
            continue
        if op == "*" and (e[idx - 1] == "*" or e[idx + 1] == "*"):
            continue   # part of '**'
        left = _eval_const_int(e[:idx], params)
        right = _eval_const_int(e[idx + len(op):], params)
        if left is None or right is None:
            continue
        try:
            if op == "**":
                return left ** right if right < 256 else None
            if op == "//":
                return left // right if right != 0 else None
            if op == "*":
                return left * right
            if op == "+":
                return left + right
            if op == "-":
                return left - right
        except (ValueError, ZeroDivisionError):
            return None
    return None


def _blank_string_literals(src: str) -> str:
    """Replace the CONTENTS of double-quoted string literals with spaces (keep
    the quotes + length + newlines) so a `$display("...%0d...")` format
    specifier is never mistaken for a `% 0` modulo operator. chip-AGNOSTIC."""
    out = []
    i = 0
    n = len(src)
    while i < n:
        c = src[i]
        if c == '"':
            out.append('"')
            i += 1
            while i < n and src[i] != '"':
                out.append('\n' if src[i] == '\n' else ' ')
                if src[i] == '\\' and i + 1 < n:   # skip escaped char
                    out.append(' ')
                    i += 1
                i += 1
            if i < n:
                out.append('"')
                i += 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def _harvest_header_params(src: str, consts: Dict[str, int],
                           zero_consts: Dict[str, int],
                           line_of: Dict[str, int]) -> None:
    """#750 / ORGANIC #744 R4 — seed the constant environment with module-HEADER
    parameters `module NAME #( parameter A=.., B=.. ) (...)`. The shipped Rule-14
    harvested only `;`-terminated decls (via `_LOCALPARAM_DECL_RE`), so a
    width-truncated divisor whose WIDTH source is a module-header parameter
    (`localparam [W-1:0] DW = W'(2**W)` with `#(parameter W=8)`) was missed.
    A header param with a NON-CONSTANT default resolves to None and is skipped
    (§4.05 — no false-positive risk). chip-AGNOSTIC: pure constant evaluation."""
    n = len(src)
    i = 0
    while True:
        h = src.find("#", i)
        if h < 0:
            break
        j = h + 1
        while j < n and src[j] in " \t\r\n":
            j += 1
        if j >= n or src[j] != "(":
            i = h + 1
            continue
        depth = 0
        k = j
        while k < n:
            if src[k] == "(":
                depth += 1
            elif src[k] == ")":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        body = src[j + 1:k]
        base_ln = src.count("\n", 0, h) + 1
        # split on TOP-LEVEL commas
        entries, d2, last = [], 0, 0
        for idx, ch in enumerate(body):
            if ch in "([{":
                d2 += 1
            elif ch in ")]}":
                d2 -= 1
            elif ch == "," and d2 == 0:
                entries.append(body[last:idx])
                last = idx + 1
        entries.append(body[last:])
        for ent in entries:
            m = re.search(
                r"(?:parameter|localparam)?\s*"
                r"(?:integer\s+|signed\s+|unsigned\s+|logic\s+|bit\s+|reg\s+)*"
                r"(?:\[[^\]]*\]\s*)?"
                r"(?:integer\s+|signed\s+|unsigned\s+)*"
                r"([A-Za-z_]\w*)\s*=\s*(.+)$", ent.strip(), re.S)
            if not m:
                continue
            name, rhs = m.group(1), m.group(2).strip()
            if name in VERILOG_KEYWORDS or name in consts:
                continue
            val = _eval_const_int(rhs, consts)
            if val is None:
                continue
            # §4.05 — a module-header parameter whose default is a BARE INTEGER
            # LITERAL is an OVERRIDABLE PLACEHOLDER (the instantiator supplies
            # the real value, e.g. SERV's `#(parameter width=0)`): it is NOT a
            # compile-time-provable constant divisor, so it must never enter
            # `zero_consts` (a `… / width` with a default-0 placeholder is not a
            # divide-by-zero defect — the design is parameterised). A non-zero
            # bare literal is still seeded into `consts` so it can resolve a
            # derived width (`[W-1:0]`), but a bare 0 is dropped entirely so a
            # derived divisor never reads it as a hard zero. By contrast a value
            # arising from a DERIVED/TRUNCATING expression (`W'(2**W)`, the #750
            # idiom) IS provably 0 regardless of override and remains flagged.
            is_bare_literal = bool(re.fullmatch(r"\d+", rhs))
            if is_bare_literal:
                if val != 0:
                    consts[name] = val
                    line_of[name] = base_ln
                continue
            consts[name] = val
            line_of[name] = base_ln
            if val == 0:
                zero_consts[name] = base_ln
        i = k + 1


def rule_divmod_by_zero_const(src: str, path: str) -> List[Finding]:
    """Rule 14 (ORGANIC #744) — WARN on a `%` or `/` whose divisor is a
    compile-time constant that evaluates to 0 (e.g. a width-truncated
    `localparam [7:0] DW = 8'(256)` == 0). chip-AGNOSTIC."""
    findings: List[Finding] = []
    # 0. blank string-literal contents so $display("...%0d...") format specs are
    #    never read as a `% 0` divisor (printf-format blast-radius).
    src = _blank_string_literals(src)
    # 1. build the constant-localparam environment.
    consts: Dict[str, int] = {}
    zero_consts: Dict[str, int] = {}   # name -> line of a const proven == 0
    line_of: Dict[str, int] = {}
    # #750 / ORGANIC #744 R4 — seed module-HEADER parameters FIRST so a derived
    # body localparam whose WIDTH comes from a header param is provable.
    _harvest_header_params(src, consts, zero_consts, line_of)
    for m in _LOCALPARAM_DECL_RE.finditer(src):
        name, rhs = m.group(1), m.group(2)
        if name in VERILOG_KEYWORDS or name in consts:
            continue
        val = _eval_const_int(rhs, consts)
        ln = src.count("\n", 0, m.start()) + 1
        if val is not None:
            consts[name] = val
            line_of[name] = ln
            if val == 0:
                zero_consts[name] = ln
    if not zero_consts:
        # still check a bare literal-0 divisor below; otherwise nothing to do.
        pass
    # 2. scan `%`/`/` divisors. The divisor is the operand to the RIGHT of the op
    #    up to the next operator/paren/semicolon.
    for dm in re.finditer(r"(%|/)(?!/|\*)\s*([A-Za-z_]\w*|\d+\s*'\s*\w*\s*\([^)]*\)|\d+)", src):
        op = dm.group(1)
        divisor = dm.group(2).strip()
        # A real binary %/÷ has a LEFT OPERAND on the same line. A line-leading
        # `%`-coverage annotation (Verilator/covered emit `%000000  input ...`)
        # has no operand before it → skip (else `%000000` reads as `% 0`).
        line_start = src.rfind("\n", 0, dm.start()) + 1
        left = src[line_start:dm.start()].rstrip()
        if not left or left[-1] not in (
                "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_)]"):
            continue
        ln = src.count("\n", 0, dm.start()) + 1
        zero = False
        detail = ""
        if re.fullmatch(r"[A-Za-z_]\w*", divisor) and divisor in zero_consts:
            zero = True
            detail = (f"`{divisor}` is a compile-time constant that evaluates to "
                      f"0 (declared at line {zero_consts[divisor]}; a width-"
                      f"truncated literal such as W'(2**W) truncates to 0)")
        else:
            v = _eval_const_int(divisor, consts)
            if v == 0:
                zero = True
                detail = f"the divisor `{divisor}` evaluates to a constant 0"
        if zero:
            opname = "modulo" if op == "%" else "divide"
            findings.append(Finding(
                path, ln, 'WARN', 'divmod-by-zero-const', divisor,
                f"{opname}-by-zero: {detail}, so `x {op} {divisor}` is "
                f"{opname}-by-zero → x at runtime (functionally dead). Use a "
                f"non-truncated width for the divisor, or guard the divisor != 0."))
    return findings


