#!/usr/bin/env python3
"""
rtl_hygiene_lint.py — General-purpose RTL hygiene checker.

Deterministic Python-based lint that catches 7 general bug classes found
across IC designs (learned from <half-duplex-tester> debug 2026-04-16; rule 5
added from the VerilogEval-v2 v0.1.10 tuning loop 2026-05-27; rules 6-7 from the
v0.1.24/v0.1.25 fail-case loops 2026-05-27/28):

  1. Declared-but-undriven wire
     (e.g., `wire ch_wake_event;` but never on LHS of `assign` or instance output)
  2. Declared-but-unread reg
     (e.g., `reg [7:0] resp_crc;` but never appears on RHS)
  3. Case/if enumeration coverage
     (e.g., `case (x) 8'h70: ... 8'h72: ... endcase` with no `default`, missing
      values that are actually generated by producer)
  4. Pulse-to-state without latch
     (e.g., `start <= 1'b1;` in one always block, consumed by another FSM that
      only looks at `start` during a specific state → pulse may be swallowed)
  5. Reset-less registered output with no power-up initializer
     (e.g., `output reg q;` clocked by `<= d` with no reset and no `= 0` →
      powers up as X; deterministic references expect 0 at t=0)
     v0.1.24: `--fix` REPAIRS this deterministically in-place (inserts
     `initial <reg>=0;`), and now also covers an internal reg that drives an
     output via a continuous assign (Prob053-class). The lesson is enforced by
     the tool, not by a caller/prompt that can forget or be told to ignore it.
  6. Incomplete sensitivity list
     (e.g., `always @(a) if (clock) p<=a;` misses clock-edge updates → use `@(*)`)
  7. Vector self-shift fold
     (e.g., `in | {in[98:0],1'b0}` — the unshifted operand re-folds the boundary
      bit so the padded edge bit is NOT 0; shift BOTH operands inside the concat)
  8. SV reserved-word identifier (v0.1.38, from the close-loop sweep)
     iverilog 12 treats `packed`, `unique`, `priority`, `final`, `chandle`,
     `null`, `unique0` as reserved even outside their reserved contexts. Using
     any of these as a user identifier (variable, port, label) raises a
     useless `syntax error near …` with no line. Detect at lint time and
     suggest a `_val` / `_result` suffix. Chip-AGNOSTIC.
  9. Wire-driven-by-input read inside a clocked block (v0.1.38)
     `wire X = f(input_port);` followed by `always @(posedge clk) ... X ...`
     reads X at the same simulation instant as the clock edge — TB sees X
     evaluated with PRE-edge input values (one-cycle skew). The fix is to
     inline the expression inside the always block (NBA RHS pre-fetch
     semantics) OR pre-register the input. Chip-AGNOSTIC sequential hazard.
  10. Power-up determinism for INTERNAL regs in reset-less modules (v0.1.38)
     The existing rule 5 covers registered OUTPUT ports and an internal reg
     that directly drives an output via `assign out = q`. v0.1.38 extends
     `--fix` to ALSO cover ALL internal `reg` declarations in reset-less
     modules — the X-propagation through internal pipeline regs at t=0
     corrupts the output even when the output itself is initialized. Same
     conservative gate (no reset port). Chip-AGNOSTIC.
     v0.1.39 honesty correction (audit Finding 3): the v0.1.38 release
     note claimed "3 samples picked up additional initial blocks". The
     actual broader corpus sweep (362 reference samples) shows the case-c
     extension fires on ~42 samples (~11.6%). The behavior is unchanged:
     `initial X = 0;` insertion only, which preserves all functional
     behavior (steady-state semantics are independent of t=0 power-up
     value); idempotent re-runs add nothing. Zero functional regressions
     across the 42 — the safety claim holds; only the count was wrong.
  11. Unguarded simulation-only immediate assertion (v0.1.61, from the CVDP
     v0.1.59 Shape-D run). An immediate `assert (cond) else $error(...);` is
     simulation-only; yosys/DC reject it (yosys: `syntax error near else`).
     CVDP's assertion-injection task (`priority_encoder_8x3`) — and the
     benchmark's OWN provided module — shipped it unguarded, FAILing the
     synth gate. `--fix` fences it with `// synthesis translate_off …
     translate_on` (yosys/DC skip it; iverilog/cocotb keep it live). Safe,
     whole-line-only, idempotent, chip-AGNOSTIC.

Usage:
    python3 rtl_hygiene_lint.py <files.v|.sv ...>
    python3 rtl_hygiene_lint.py --json <out.json> <files.v|.sv ...>

Exit codes:
    0 = no findings
    1 = findings issued (see stdout / JSON)
    2 = parse error

Works with plain regex + optional pyslang (more accurate) if installed.
No external tool dependencies required for the regex path.

Generality: applies to ANY Verilog/SystemVerilog design. Finds bugs #1, #2,
#7, #10 from the <half-duplex-tester> debug session using only syntax patterns.
"""
