# Rule 5: Reset-less registered output with no power-up initializer
# ---------------------------------------------------------------------------
# #530 — also accept PREFIXED reset spellings (w_rst / r_rst / io_rst /
# sys_reset …, common in cross-domain designs): the old anchor required the
# token to START with rst/reset, so a dual-clock module with w_rst+r_rst was
# falsely classified reset-less and fed to the power-up autofix.
# #754 / ORGANIC-20260616 (C4) — the alternation already carried the ASYNC
# prefix `a?` (areset/arst) and the alphabetic clear spellings sclr/aclr, but
# had NO SYNC prefix: the canonical synchronous-reset spelling `srst` (= s+rst,
# no underscore separator) and `sreset` were therefore NOT matched, so a
# spec-faithful `if (srst) out <= 0;` output was mis-classified reset-less and
# falsely tripped rule_uninit_registered_output. `(?:\w+_)?` cannot consume the
# bare `s` (it requires a trailing underscore). Fix: widen the async-only
# prefix `a?` to `[as]?` on BOTH the reset and rst alternatives so
# srst/sreset/arst/areset all match — matching the richer reset-name recognition
# used by the rest of the plugin. Pure recognition widening of canonical
# sync-reset spellings — chip-AGNOSTIC, deterministic.
_RESET_NAME_RE = re.compile(
    r'\b(?:\w+_)?([as]?reset[a-z_]*|[as]?rst[a-z_]*|resetn|nreset|por|sclr|aclr)\b',
    re.I)


def _block_body_after(src: str, body_start: int) -> str:
    """Return the body text of an always block that starts at `body_start`,
    bounded at the next top-level `always` / `endmodule`. Mirrors the bounding
    used by rule_reset_boundary_residual_enable so both rules agree on scope.

    ORGANIC #765 (R6C8) — the boundary MUST match the SAME flavors of `always`
    that the block discovery does (`_iter_always_blocks` finds
    `always(?:_ff|_comb|_latch)?`). The old `\\balways\\b` could NOT match
    `always_ff`/`always_comb`/`always_latch` (the trailing `_` is a word char,
    so there is no `\\b` between `always` and `_ff`). On any modern-SV design
    written purely with `always_ff`/`always_comb` (every CDC FIFO/FILO, every
    APB block), the FIRST block's body then overran to `endmodule`, swallowing
    EVERY later block — so each register looked written by many blocks across
    many clock domains and rule_multidriven_register false-WARNed. Widening the
    boundary to the same flavors keeps every block body scoped to its own block.
    chip-AGNOSTIC, purely structural."""
    tail = src[body_start:]
    nxt = re.search(r'\balways(?:_ff|_comb|_latch)?\b|\bendmodule\b', tail)
    return tail[:nxt.start()] if nxt else tail


def _reset_covered_signals(src: str) -> Set[str]:
    """ORGANIC #727 — structurally collect every signal that has an assignment
    DOMINATED by the reset condition of its enclosing reset-bearing `always`
    process, INCLUDING a single mixed process where the reset branch and the
    datapath share one block.

    A reset-bearing process is `always @(... posedge/negedge <rst> ...)` whose
    sensitivity list names a reset-like signal (so `negedge presetn`,
    `negedge rst_n`, async OR sync resets all qualify — the reset-name detector
    here is signal-structural, not a whole-module port-name early-return).

    Inside such a process, the reset branch is the `if (<cond>)` whose condition
    references that block's reset signal (e.g. `if (!presetn)`); every `<=`/`=`
    LHS in that branch (a single statement OR a `begin ... end` group) is
    credited as reset-covered. This is purely structural and chip-AGNOSTIC.
    """
    covered: Set[str] = set()
    # Match an always block and capture its sensitivity list so we can identify
    # the per-block reset signal(s) — only edges count (a level-sensitive list
    # is not a clocked reset process).
    for bm in re.finditer(r'\balways(?:_ff)?\s*@\s*\(([^)]*)\)', src):
        sens = bm.group(1)
        # Edge-triggered signals of THIS block, in list order.
        edge_sigs = re.findall(r'\b(?:pos|neg)edge\s+([A-Za-z_]\w*)', sens)
        # Reset signal(s) of THIS block, by TWO structural signals (chip-
        # AGNOSTIC — does not depend on the reset port being spelled in a known
        # way like rst/reset; catches `presetn`, `aresetn`, custom names):
        #   (1) NAME — an edge signal whose name matches the reset-name detector.
        #   (2) STRUCTURE — in an async-reset idiom `always @(posedge clk or
        #       <edge> rst)`, the reset is the edge signal that the block's
        #       leading `if` condition tests. We seed this from the head `if`
        #       below; here we keep all edge signals as candidates so the head
        #       `if` can pick the one it tests.
        edge_rst = {t for t in edge_sigs if _RESET_NAME_RE.search(t)}
        body = _block_body_after(src, bm.end())
        # The async-reset branch of a multi-edge block is the FIRST `if` whose
        # condition tests one of the block's edge signals — structurally this IS
        # the reset, regardless of its name (clk is never tested in an `if`).
        first_if = re.search(r'\bif\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)', body)
        if first_if and len(edge_sigs) >= 2:
            head_cond = first_if.group(1)
            for t in edge_sigs:
                if re.search(r'\b' + re.escape(t) + r'\b', head_cond):
                    edge_rst.add(t)
        # Walk every `if ( <cond> )` whose condition references a reset signal
        # (either a reset edge signal of this block — name- OR structure-derived
        # — or any reset-name token, which also covers the synchronous `if(rst)`
        # form in a clk-only block).
        for im in re.finditer(r'\bif\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)', body):
            cond = im.group(1)
            cond_refs_block_rst = any(re.search(r'\b' + re.escape(r) + r'\b', cond)
                                      for r in edge_rst)
            if not (cond_refs_block_rst or _RESET_NAME_RE.search(cond)):
                continue
            # The reset branch: the statement (single or begin..end) that the
            # `if` dominates. Capture up to the matching `end` for a begin-group,
            # else the single `<lhs> <= / = ...;` statement.
            after = body[im.end():]
            mblk = re.match(r'\s*begin\b', after)
            if mblk:
                # Balance begin/end to find the branch end.
                depth = 0
                idx = 0
                # Re-scan token by token for begin/end keywords.
                for km in re.finditer(r'\b(begin|end)\b', after):
                    if km.group(1) == 'begin':
                        depth += 1
                    else:
                        depth -= 1
                        if depth == 0:
                            idx = km.end()
                            break
                branch = after[:idx] if idx else after
            else:
                semi = after.find(';')
                branch = after[:semi + 1] if semi != -1 else after
            for am in re.finditer(r'(?<![<>!=])\b([A-Za-z_]\w*)(?:\[[^\]]+\])?\s*(?:<=|=)(?!=)',
                                  branch):
                lhs = am.group(1)
                if lhs not in VERILOG_KEYWORDS:
                    covered.add(lhs)
    return covered


def _case_spans(src: str) -> List[Tuple[str, int, int]]:
    """[(selector_text, case_start_off, endcase_start_off)] for every `case`,
    depth-matched (a nested case closes against the nearest unmatched endcase).
    chip-AGNOSTIC pure Verilog grammar. (ORGANIC #783 r2.)"""
    spans: List[Tuple[str, int, int]] = []
    stack: List[Tuple[int, str]] = []
    for m in re.finditer(r'\bcase[szx]?\s*\(([^)]*)\)|\bendcase\b', src):
        if m.group(0).startswith('endcase'):
            if stack:
                start, sel = stack.pop()
                spans.append((sel, start, m.start()))
        else:
            stack.append((m.start(), m.group(1) or ''))
    return spans


def _enclosing_begin_end(src: str, pos: int) -> Optional[Tuple[int, int]]:
    """The INNERMOST [after-`begin`, start-of-matching-`end`) char span that
    encloses `pos`, or None. Depth-matched; the innermost is the enclosing pair
    with the largest `begin` offset. (ORGANIC #783 r2 — used to require a
    done/valid companion in the SAME arm as a terminal output write.)"""
    best: Optional[Tuple[int, int]] = None
    stack: List[int] = []
    for m in re.finditer(r'\b(begin|end)\b', src):
        if m.group(1) == 'begin':
            stack.append(m.end())
        elif stack:
            bstart = stack.pop()
            if bstart <= pos < m.start() and (best is None or bstart > best[0]):
                best = (bstart, m.start())
    return best


def _is_valid_gated_fsm_terminal_output(src: str, name: str,
                                        reset_covered: Set[str]) -> bool:
    """ORGANIC #783 (R8C4) — structurally recognise the legitimate
    *valid-gated FSM-terminal output* pattern, which the prose heuristic
    "a registered output powers up X but the reference expects 0 at t=0"
    CONTRADICTS.

    The canonical insertion-sort / compute-then-emit FSM writes its WIDE
    result register ONLY in a terminal/computed FSM state (e.g. `DONE:
    out_data <= array[..]`), deliberately OUTSIDE the reset branch, and
    qualifies it with a companion 1-bit `done`/`valid` output that IS
    reset-covered. The consumer samples the result only when that valid
    flag asserts, so the pre-clock X is never observed and forcing
    `initial <name> = 0;` would DIVERGE the power-up value from a
    spec-faithful / golden reference (X vs 0) on equivalence/area-opt tasks.

    Downgrade to ADVISORY only when ALL of the following hold (no-leak biased
    — every clause must be structurally TRUE, else the finding keeps its
    historical hard-block power):

      (1) the module has a WORKING reset (it reset-covers >= 1 register).
          A genuinely reset-less module is UNTOUCHED — it still hard-blocks
          (the original reset-less DFF case the rule was built for).
      (2) a companion 1-bit reset-covered OUTPUT exists (a `done`/`valid`
          qualifier with a deterministic power-up value). Without such a
          handshake, the X power-up could be consumed — keep the block.
      (3) every `<=` write of `name` is dominated by a `case` whose selector
          is a reset-covered FSM state register (i.e. the output is a
          terminal/computed result, not a free-running register that merely
          FORGOT its reset). A free-running unreset output is NOT state-gated
          and stays a hard block.

    chip-AGNOSTIC, purely structural — no chip/vendor/SKU literal.
    """
    # (1) module has a working reset.
    if not reset_covered:
        return False
    # (2) >= 1 companion 1-bit reset-covered output exists (a done/valid
    #     qualifier with a deterministic power-up value).
    one_bit_outs = set(re.findall(
        r'\boutput\b\s+(?:reg|logic|wire)?\s*([A-Za-z_]\w*)\s*(?=[,;)=])', src))
    companions = {o for o in one_bit_outs if o in reset_covered and o != name}
    if not companions:
        return False
    # state-case spans: a `case(<sel>) … endcase` whose selector is a
    # reset-covered FSM state register. (ORGANIC #783 r2 Step-2.7 — the earlier
    # form computed these selectors but NEVER used them; it only checked that
    # SOME `case` keyword textually preceded the write, so a write inside a case
    # keyed on an INPUT, or in a different block entirely, was wrongly credited.)
    state_cases = [(s, e) for sel, s, e in _case_spans(src)
                   if set(re.findall(r'[A-Za-z_]\w*', sel)) & reset_covered]
    if not state_cases:
        return False
    writes = list(re.finditer(
        r'(?<![<>!=])\b' + re.escape(name) + r'(?:\[[^\]]+\])?\s*<=\s*([^;]*);', src))
    if not writes:
        return False
    for w in writes:
        rhs = w.group(1)
        # (A) reject a FREE-RUNNING / SELF-ACCUMULATING output (the X poisons
        #     every cycle and is sampled): `name` appears in its OWN RHS.
        if re.search(r'(?<![\w.])' + re.escape(name) + r'(?![\w])', rhs):
            return False
        # (B) the write must sit textually INSIDE a reset-covered state-case
        #     (terminal/computed result, not a free-running register that merely
        #     forgot its reset, nor a case keyed on an input/non-state signal).
        if not any(s < w.start() < e for s, e in state_cases):
            return False
        # (C) a companion 1-bit reset-covered output is assigned in the SAME
        #     innermost begin/end arm as the write — the done/valid-WITH-result
        #     idiom that proves the X is qualified out. A coincidental reset-
        #     covered 1-bit output elsewhere does NOT qualify (§4.05 no-leak).
        be = _enclosing_begin_end(src, w.start())
        if be is None:
            return False
        arm = src[be[0]:be[1]]
        if not any(re.search(r'(?<![\w])' + re.escape(c) + r'\s*<=', arm)
                   for c in companions):
            return False
    return True


def rule_uninit_registered_output(src: str, path: str) -> List[Finding]:
    """
    Detect a REGISTERED output port (assigned via `<=` in a clocked block) in a
    module that has NO reset-like input AND gives the output NO power-up value
    (no declaration-time initializer, no `initial` block).

    Such an output powers up as X. Deterministic reference models (and the
    VerilogEval-v2 testbenches) sample the output at t=0 before the first clock
    edge and expect a deterministic 0 there, so the design mismatches on exactly
    that one pre-clock sample. Learned from VerilogEval-v2 Prob034/053/104, where
    each lost a single vector purely to an uninitialised `output reg`.

    Conservative — only fires when the module has NO reset port at all (so the
    output genuinely cannot be reset), which is precisely the reset-less DFF
    case. Reports WARN with the exact fix. chip-AGNOSTIC.
    """
    findings: List[Finding] = []

    # Output ports (ANSI or non-ANSI), capturing optional reg/logic/wire kind.
    out_ports: Dict[str, int] = {}
    for m in re.finditer(
            r'\boutput\b\s+(?:(?:reg|logic|wire)\s+)?(?:signed\s+)?'
            r'(?:\[[^\]]+\]\s*)?([A-Za-z_]\w*)\s*(?=[,;)=])', src):
        name = m.group(1)
        if name and name not in VERILOG_KEYWORDS:
            out_ports.setdefault(name, src[:m.start()].count('\n') + 1)
    if not out_ports:
        return findings

    # ORGANIC #727 — per-OUTPUT reset coverage (replaces the old whole-module
    # "if any reset port exists, suppress every finding" early-return). The old
    # guard had two defects: (1) it MISSED resets whose port name the detector
    # did not match (e.g. `presetn`), false-flagging a reset-covered output; and
    # (2) when a reset port WAS recognized, it suppressed findings for ALL
    # outputs, hiding a genuinely-unreset output in a reset-having module. We now
    # CREDIT an output only when it is structurally assigned under the reset
    # condition of its enclosing reset-bearing process (single mixed reset+
    # datapath block included), and STILL flag any output never so assigned.
    reset_covered = _reset_covered_signals(src)

    # Registered = appears on LHS of a non-blocking assignment.
    registered = {mm.group(1)
                  for mm in re.finditer(r'(?<![<>!=])\b(\w+)(?:\[[^\]]+\])?\s*<=', src)}
    has_initial = bool(re.search(r'\binitial\b', src))

    for name, lineno in out_ports.items():
        if name not in registered:
            continue
        # Reset-covered: assigned under the reset condition of its clocked
        # process → has a deterministic power-up value, do NOT flag.
        if name in reset_covered:
            continue
        # Declaration-time initializer: a decl line for `name` containing `=`.
        decl_init = re.search(
            r'\b(?:output|reg|logic)\b[^;\n]*\b' + re.escape(name) + r'\s*=', src)
        if decl_init or (has_initial and re.search(
                r'\binitial\b[\s\S]{0,200}?\b' + re.escape(name) + r'\s*(<=|=)', src)):
            continue
        f = Finding(
            path, lineno, 'WARN', 'uninit-registered-output', name,
            f"registered output '{name}' has no reset and no power-up initializer "
            f"-> powers up as X. A deterministic reference (and VerilogEval-style "
            f"testbenches that sample at t=0) expects 0 there. Fix (preferred, "
            f"Verilator-clean): add a separate `initial {name} = 0;` block. A "
            f"declaration initializer `output reg ... {name} = 0;` also clears the "
            f"power-up X but trips Verilator PROCASSINIT when '{name}' is ALSO "
            f"procedurally assigned (`{name} <= ...`), so prefer the `initial` block.")
        # ORGANIC #783 — the *valid-gated FSM-terminal output* pattern (a wide
        # result register written only in a terminal/computed FSM state of a
        # reset-bearing module, qualified by a reset-covered `done`/`valid`
        # companion output) CONTRADICTS the prose heuristic "the reference
        # expects 0 at t=0": the consumer reads the result only when the valid
        # flag asserts, so the pre-clock X is never observed, and forcing
        # `initial 0` here would DIVERGE the power-up value from a spec-faithful /
        # golden reference (X vs 0) on equivalence/area-opt tasks. Downgrade to
        # ADVISORY (reported, never a hard block). A truly reset-less module, a
        # free-running output that merely forgot its reset, or a state-gated
        # output with NO done/valid companion stays STRUCTURAL → hard block
        # (§4.05 no-leak — see _is_valid_gated_fsm_terminal_output).
        if _is_valid_gated_fsm_terminal_output(src, name, reset_covered):
            f = _advisory(f, _prov.PROSE_HEURISTIC, _prov.CONTRADICTED)
            f.advisory_note = (
                "valid-gated FSM-terminal output — written only in a terminal/"
                "computed FSM state of a reset-bearing module and qualified by a "
                "reset-covered done/valid companion output, so the pre-clock X is "
                "never sampled; forcing `initial 0` would diverge the power-up "
                "value from a spec-faithful / golden reference (X vs 0). "
                "Advisory, not a hard block (ORGANIC #783)")
        findings.append(f)
    return findings


# ---------------------------------------------------------------------------
# Rule 6: Incomplete sensitivity list (latch / wrong-update hazard)
# ---------------------------------------------------------------------------
def rule_incomplete_sensitivity(src: str, path: str) -> List[Finding]:
    """Flag a LEVEL-sensitive `always @(<explicit list>)` whose body reads a signal that is
    NOT in the sensitivity list — the classic incomplete-sensitivity-list bug.

    A combinational / level-sensitive block must react to every signal it reads; if it
    lists only some, it behaves like a latch that misses updates on the omitted signals.
    The fix is `always @(*)`. Edge blocks (`@(posedge/negedge ...)`) and `@(*)` / `always_comb`
    are exempt. Learned from VerilogEval-Machine Prob145: `always @(a) if (clock) p<=a;`
    misses clock-edge updates — the reference uses `always @(*) if (clock) p=a;`. chip-AGNOSTIC.
    """
    findings: List[Finding] = []
    for m in re.finditer(r'\balways\b\s*@\s*\(([^)]*)\)', src):
        sens = m.group(1)
        if '*' in sens or re.search(r'\b(pos|neg)edge\b', sens):
            continue                                   # @(*) or clocked — exempt
        listed = set(re.findall(r'[A-Za-z_]\w*', sens))
        if not listed:
            continue
        # Extract the block body: begin..end (depth-matched) or a single statement.
        rest = src[m.end():]
        bm = re.match(r'\s*begin\b', rest)
        if bm:
            depth, i, n = 0, 0, len(rest)
            tok = re.compile(r'\b(begin|end)\b')
            start = None
            for t in tok.finditer(rest):
                if t.group(1) == 'begin':
                    if depth == 0:
                        start = t.end()
                    depth += 1
                else:
                    depth -= 1
                    if depth == 0:
                        body = rest[start:t.start()]
                        break
            else:
                continue
        else:
            semi = rest.find(';')
            if semi == -1:
                continue
            body = rest[:semi + 1]
        # ORGANIC #802 — strip BASED NUMERIC LITERALS before the identifier scan.
        # A sized/unsized based literal (4'b0000, 8'hFF, 20'd0, 'h0) has a
        # base-letter-prefixed VALUE tail (b0000 / hFF / d0) that the
        # `[A-Za-z_]\w*` read scan below treats as an identifier; the sole literal
        # guard `not re.match(r"^\d", t)` only rejects DIGIT-prefixed tokens, so
        # the value tail survives and is falsely reported as a missing-sensitivity
        # read on correct combinational RTL. A based numeric literal can never be
        # a sensitivity signal, so removing it is always safe. The regex is
        # ANCHORED on the apostrophe, so a signal merely NAMED `d0` (read as
        # `q = d0;`, no apostrophe) is never over-stripped. chip-AGNOSTIC.
        body = re.sub(r"\b\d*'[sS]?[bBoOdDhH][0-9a-fA-FxXzZ_]+", " ", body)
        # LHS targets (assigned) are not "reads"; everything else read must be in the list.
        lhs = set(re.findall(r'(\w+)(?:\s*\[[^\]]*\])?\s*(?:<=|=)(?!=)', body))
        reads = {t for t in re.findall(r'[A-Za-z_]\w*', body)
                 if t not in VERILOG_KEYWORDS and t not in lhs
                 and not re.match(r"^\d", t)}
        missing = sorted(reads - listed)
        if missing:
            lineno = src[:m.start()].count('\n') + 1
            findings.append(Finding(
                path, lineno, 'WARN', 'incomplete-sensitivity-list', ','.join(missing),
                f"level-sensitive `always @({sens.strip()})` reads {missing} not in its "
                f"sensitivity list — it behaves like a latch that misses updates on those "
                f"signals. Use `always @(*)` (or add them)."))
    return findings


# ---------------------------------------------------------------------------
# Rule 7: vector self-shift fold (boundary bit re-introduced by an unshifted op)
# ---------------------------------------------------------------------------
# `v` is the based-zero literal regex for the boundary pad (1'b0 / 2'b00 / 'h0 …),
# deliberately NOT plain `0` so it never matches an index like `v[0]`.
_BASED_ZERO_RE = re.compile(r"\d*'[bdh]0+\b")


def rule_vector_self_shift_fold(src: str, path: str) -> List[Finding]:
    """Flag `v OP {… v[..] …, 1'b0}` (OP in | & ^): a vector OR/AND/XOR-ed with a
    SHIFTED CONCAT of ITSELF that pads a boundary `1'b0`.

    SEVERITY IS SPLIT BY THE COMPOSING OPERATOR
    (ORGANIC-20260605-boundary-fold-or-form-escalation — two consecutive
    clean-room campaigns produced the OR-form bug while the corpus sweep's
    false positives were exclusively AND-form):
      * `|` / `^` composition → ERROR. The unshifted operand DOMINATES the
        padded zero (x|0 = x, x^0 = x), so the boundary bit LEAKS through and
        the padded edge bit is NOT the intended 0 (e.g. `in | {in[98:0],1'b0}`
        gives out[0]=in[0] instead of 0). Virtually always the bug. The correct
        form shifts BOTH operands inside the concat:
        `{(in[98:0] OP in[99:1]), 1'b0}`.
      * `&` composition → WARN (informational). The padded zero DOMINATES
        (x&0 = 0), so the boundary bit is correctly MASKED — `in & {1'b0,
        in[W-1:1]}` is the legitimate, correct-by-construction neighbour-AND
        idiom (proven by the v0.2.40 corpus sweep over 305 passing samples).
    Not auto-repaired — the right slices depend on the intended neighbour
    relation. chip-AGNOSTIC. Learned from VerilogEval-v2 Prob092 (gatesv100) —
    the recurring "boundary bit by placement, not by an op" miss.
    """
    findings: List[Finding] = []
    # The composing operators are COMMUTATIVE, so the same bug can be written
    # with EITHER operand order (ORGANIC-20260605-boundary-fold-commutative-
    # match: the third consecutive clean-room recurrence wrote the zero-padded
    # shifted self-copy as the LEFT operand and escaped the vector-first-only
    # match with zero findings). Match BOTH:
    #   form A: `<ident> <|&^> { ...concat... }`   (vector first)
    #   form B: `{ ...concat... } <|&^> <ident>`   (mirrored)
    # In both forms the ident must be the UNSHIFTED whole vector (not sliced —
    # form A enforces this by `\s*` adjacency; form B adds a `(?!\s*\[)`
    # lookahead), and the concat must slice the SAME ident + carry a zero pad.
    matches = [(m.group(1), m.group(2), m.group(3), m.start())
               for m in re.finditer(
                   r'\b([A-Za-z_]\w*)\s*([|&^])\s*\{([^{}]*)\}', src)]
    matches += [(m.group(3), m.group(2), m.group(1), m.start())
                for m in re.finditer(
                    r'\{([^{}]*)\}\s*([|&^])\s*([A-Za-z_]\w*)(?!\s*\[)', src)]
    seen_keys = set()
    for lhs, op, concat, mstart in matches:
        if lhs in VERILOG_KEYWORDS:
            continue
        has_self_slice = re.search(r'\b' + re.escape(lhs) + r'\s*\[[^\]]*\]', concat)
        has_zero_pad = _BASED_ZERO_RE.search(concat)
        if has_self_slice and has_zero_pad:
            lineno = src[:mstart].count('\n') + 1
            key = (lineno, lhs, op)
            if key in seen_keys:      # same expression matched by both forms
                continue
            seen_keys.add(key)
            if op == '&':
                findings.append(Finding(
                    path, lineno, 'WARN', 'vector-self-shift-fold', lhs,
                    f"`{lhs} & {{… {lhs}[..], 1'b0}}` — AND-composition with a "
                    f"zero-padded shifted self-copy: the padded zero MASKS the "
                    f"edge bit (x&0=0), so this is the legitimate neighbour-AND "
                    f"idiom; verify the edge bit against the spec's stated "
                    f"boundary value (informational)."))
            else:
                findings.append(Finding(
                    path, lineno, 'ERROR', 'vector-self-shift-fold', lhs,
                    f"`{lhs} {op} {{… {lhs}[..], 1'b0}}` — {op}-composition with "
                    f"a zero-padded shifted self-copy: the UNSHIFTED operand "
                    f"DOMINATES the padded zero (x{op}0=x), so '{lhs}'s edge bit "
                    f"LEAKS through and the padded edge bit is NOT 0. Shift BOTH "
                    f"operands inside the concat "
                    f"(e.g. `{{({lhs}[hi:lo] {op} {lhs}[hi2:lo2]), 1'b0}}`) and "
                    f"verify the edge bit against the spec's stated boundary "
                    f"value."))
    return findings


# ---------------------------------------------------------------------------
# Rule 8: SV reserved-word identifier (v0.1.38, from close-loop sweep)
# ---------------------------------------------------------------------------
# iverilog 12 ALWAYS treats these as reserved, even outside their reserved
# context. Using one as a variable / port / label name produces a
# "syntax error near …" with no useful location. The list is the conservative
# intersection of (SV-2012 reserved words used in nowhere-near-anything-else
# contexts) ∩ (iverilog 12 actually rejects). Adding `parameter` / `wire` /
# `input` etc. would be redundant — Verilog-1995 already rejects those.
_RESERVED_IDENT_BLACKLIST = frozenset({
    "packed", "unique", "unique0", "priority", "final",
    "chandle", "null", "interconnect",
})


def rule_reserved_word_identifier(src: str, path: str) -> List[Finding]:
    """Flag user identifiers that match the iverilog-rejects blacklist.

    Detects in three contexts:
      (a) variable / port DECLARATION (`reg packed`, `wire [N:0] packed`,
          `input final`)
      (b) named-block / generate / instance label (`begin : final`)
      (c) module port-list position (`module m (input final, ...)`)

    Skips occurrences in the legitimate reserved context (`logic packed [3:0]`
    SystemVerilog struct, `unique case`, `priority case`, `final begin`, etc.)
    by requiring the reserved word to appear AFTER a type keyword that's
    expecting an identifier.

    chip-AGNOSTIC; iverilog-substitution-specific (per open-benchmark-methodology
    skill § 3).
    """
    findings: List[Finding] = []
    for w in _RESERVED_IDENT_BLACKLIST:
        # (a) immediately follows a type/direction keyword
        decl = re.compile(
            r'\b(reg|wire|logic|input|output|inout|integer|real|byte|shortint|int|longint)\b'
            r'(?:\s+signed)?\s*(?:\[[^\]]+\]\s*)?'
            r'\b(' + re.escape(w) + r')\b\s*(?=[,;)=]|\[)')
        for m in decl.finditer(src):
            lineno = src[:m.start()].count('\n') + 1
            findings.append(Finding(
                path, lineno, 'WARN', 'reserved-word-identifier', w,
                f"identifier '{w}' is reserved by iverilog 12 (Vibe-IC's VCS "
                f"substitute) even outside its reserved context. Using it as a "
                f"user identifier triggers 'syntax error near {w}' with no line. "
                f"Rename to '{w}_val' / '{w}_result' / similar."))
        # (b) named-block label
        label = re.compile(r'\b(?:begin|fork|module|generate)\s*:\s*(' + re.escape(w) + r')\b')
        for m in label.finditer(src):
            lineno = src[:m.start()].count('\n') + 1
            findings.append(Finding(
                path, lineno, 'WARN', 'reserved-word-identifier', w,
                f"block label '{w}' is reserved by iverilog 12. Rename."))
    return findings


# ---------------------------------------------------------------------------
# Rule 9: wire-driven-by-input read inside a clocked block (v0.1.38)
# ---------------------------------------------------------------------------
def rule_wire_input_read_in_clocked_block(src: str, path: str) -> List[Finding]:
    """Flag `wire X = f(input_port);` then `always @(posedge clk) ... X ...`.

    The wire evaluates at the same simulation instant as the clock edge —
    iverilog evaluates the continuous-assign expression in the active region;
    the NBA in the always block samples its RHS in the same active region, so
    the wire's value is computed from the PRE-edge input. Result: a one-cycle
    skew that looks like an algorithm bug.

    The fix is either (a) inline the expression inside the always block (uses
    NBA RHS pre-fetch semantics directly), or (b) pre-register the input first.

    Conservative WARN: fires only when ALL of these are true:
      • a `wire X = expr;` declaration exists where `expr` reads an input port
      • `X` appears on the RHS of `<=` inside an `always @(posedge ...)` block
      • the same `X` is NOT also assigned in any always block (else it's not a
        pure combinational helper — could be a clocked alias)
    chip-AGNOSTIC.
    """
    findings: List[Finding] = []
    # collect input port names
    input_ports: Set[str] = set()
    for m in re.finditer(
            r'\binput\b(?:\s+wire)?(?:\s+signed)?\s*(?:\[[^\]]+\]\s*)?'
            r'([A-Za-z_]\w*)\s*(?=[,;)=])', src):
        nm = m.group(1)
        if nm and nm not in VERILOG_KEYWORDS:
            input_ports.add(nm)
    if not input_ports:
        return findings
    # collect `wire X = expr;` with RHS reading at least one input port
    wire_helpers: Dict[str, Tuple[int, str]] = {}
    for m in re.finditer(
            r'\bwire\b(?:\s+signed)?\s*(?:\[[^\]]+\]\s*)?'
            r'([A-Za-z_]\w*)\s*=\s*([^;]+);', src):
        nm, rhs = m.group(1), m.group(2)
        if nm in VERILOG_KEYWORDS:
            continue
        rhs_ids = set(re.findall(r'[A-Za-z_]\w*', rhs))
        if rhs_ids & input_ports:
            wire_helpers[nm] = (src[:m.start()].count('\n') + 1, rhs.strip())
    if not wire_helpers:
        return findings
    # A wire is never the LHS of a procedural assignment (Verilog forbids
    # it), so the only thing that would disqualify a wire helper is being
    # also written via `<=` (which itself would be a syntax error, but be
    # conservative). We do NOT collect blocking `=` here — the wire's own
    # `wire X = expr;` declaration uses `=` and would self-exclude.
    proc_lhs = {mm.group(1) for mm in
                re.finditer(r'(?<![<>!=])\b(\w+)(?:\[[^\]]+\])?\s*<=', src)}
    candidates = {k: v for k, v in wire_helpers.items() if k not in proc_lhs}
    # scan posedge-clk always blocks for RHS use of a candidate
    block_re = re.compile(r'\balways\s*@\s*\(\s*(?:pos|neg)edge\b[^)]*\)\s*(begin|[^;]+;)',
                          re.M | re.S)
    for m in block_re.finditer(src):
        head_end = m.end()
        tail = src[head_end:]
        # extract body (begin..end or single statement)
        if m.group(1).strip().startswith('begin'):
            depth, body = 0, None
            for tm in re.finditer(r'\b(begin|end)\b', src[m.start():]):
                if tm.group(1) == 'begin':
                    depth += 1
                else:
                    depth -= 1
                    if depth == 0:
                        body = src[m.end():m.start() + tm.start()]
                        break
            if body is None:
                continue
        else:
            body = m.group(1)
        rhs_ids = set(re.findall(r'[A-Za-z_]\w*', body))
        # collect block-local LHS so we don't false-positive on a local var
        block_lhs = {mm.group(1) for mm in
                     re.finditer(r'(?<![<>!=])\b(\w+)(?:\[[^\]]+\])?\s*<=', body)}
        for cand, (lineno, rhs_expr) in candidates.items():
            if cand in rhs_ids and cand not in block_lhs:
                findings.append(Finding(
                    path, lineno, 'WARN',
                    'wire-input-read-in-clocked-block', cand,
                    f"`wire {cand} = {rhs_expr};` reads an input port and is "
                    f"then read inside an `always @(posedge ...)` block at the "
                    f"same simulation instant — the wire evaluates with PRE-edge "
                    f"input values (one-cycle skew). Fix: inline the expression "
                    f"inside the always block (uses NBA RHS pre-fetch semantics), "
                    f"or pre-register the input."))
                break
    return findings


