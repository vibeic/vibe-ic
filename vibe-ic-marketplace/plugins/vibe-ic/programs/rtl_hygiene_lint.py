def _advisory(f: Finding, provenance: str, corroboration: str) -> Finding:
    """ORGANIC #770 — route ONE finding through the shared provenance layer.

    Returns the SAME Finding with block_eligible / advisory_note set per the
    single block-decision rule in _provenance.is_block_eligible. A finding that
    is downgraded is also demoted to INFO severity so it never trips the
    `warn > 0` exit condition — it stays in the report as an advisory line.
    chip-AGNOSTIC: no design/vendor literal, pure decision plumbing."""
    f.block_eligible = _prov.is_block_eligible(provenance, corroboration)
    if not f.block_eligible:
        f.advisory_note = _prov.advisory_reason(provenance, corroboration)
        f.severity = 'INFO'
    return f


# ---------------------------------------------------------------------------
# Tokenization (comment stripper + simple lexer good enough for our patterns)
# ---------------------------------------------------------------------------
def strip_comments(src: str) -> str:
    """Remove // line comments and /* block */ comments, preserving newlines."""
    # Block comments — preserve newlines for line tracking
    out = []
    i = 0
    while i < len(src):
        if src[i:i+2] == '/*':
            end = src.find('*/', i+2)
            if end == -1:
                break
            # Keep newlines so line numbers stay correct
            out.append(''.join('\n' if c == '\n' else ' ' for c in src[i:end+2]))
            i = end + 2
        elif src[i:i+2] == '//':
            end = src.find('\n', i)
            if end == -1:
                break
            out.append(' ' * (end - i))
            i = end
        else:
            out.append(src[i])
            i += 1
    return ''.join(out)


# Reserved words that look like identifiers but aren't signals
VERILOG_KEYWORDS = {
    'module', 'endmodule', 'input', 'output', 'inout', 'wire', 'reg', 'logic',
    'assign', 'always', 'always_ff', 'always_comb', 'always_latch',
    'begin', 'end', 'if', 'else', 'case', 'endcase', 'default', 'for',
    'while', 'repeat', 'posedge', 'negedge', 'or', 'and', 'not',
    'function', 'endfunction', 'task', 'endtask', 'parameter', 'localparam',
    'generate', 'endgenerate', 'genvar', 'integer', 'real', 'time',
    'return', 'break', 'continue', 'typedef', 'struct', 'union', 'enum',
    'packed', 'unpacked', 'signed', 'unsigned', 'initial', 'forever',
    'wait', 'fork', 'join', 'disable', '1b0', '1b1', 'x', 'z',
}


# ---------------------------------------------------------------------------
# Rule 1 + Rule 2: Undriven-wire / Unread-reg (general)
# ---------------------------------------------------------------------------
def find_declarations(src: str) -> List[Tuple[str, str, int]]:
    """
    Return list of (kind, name, lineno) for all wire/reg/logic declarations
    except module ports (which are driven/read externally).
    """
    decls = []
    lines = src.split('\n')
    # Track whether we are inside a module port list to skip port decls
    in_port_list = False
    paren_depth = 0
    for lineno, line in enumerate(lines, start=1):
        # Track entry/exit of port list
        if re.search(r'\bmodule\b\s+\w+', line):
            in_port_list = True
        if in_port_list:
            paren_depth += line.count('(') - line.count(')')
            if paren_depth <= 0 and ';' in line:
                in_port_list = False
            continue
        # Match: wire [MSB:LSB] name1, name2;  or reg [..] name;
        m = re.match(
            r'\s*(wire|reg|logic)\s+(?:(?:signed|unsigned)\s+)?'
            r'(?:\[[^\]]+\]\s*)?'     # optional packed range
            r'(?:\[[^\]]+\]\s*)?'     # optional 2nd range (arrays)
            r'([^;=]+?)\s*;',
            line)
        if not m:
            continue
        kind, name_list = m.group(1), m.group(2)
        # Skip if this is inside a port/function/task
        for n in name_list.split(','):
            n = n.strip()
            # Strip array subscript from declaration list
            n = re.sub(r'\[.*', '', n).strip()
            if n and n not in VERILOG_KEYWORDS and re.match(r'^\w+$', n):
                decls.append((kind, n, lineno))
    return decls


def collect_lhs_set(src: str) -> Set[str]:
    """Collect every identifier that appears on the LHS of assign or always <=/=."""
    lhs = set()
    # assign X = ...  (ORGANIC #544 — allow MULTIPLE bracket subscripts so a
    # 2-D / unpacked-array slice assign `assign arr[i][j] = ...` registers
    # `arr` as driven; the old single-`[...]?` form failed on a second
    # subscript and false-flagged the array as undriven-wire.)
    for m in re.finditer(r'\bassign\s+(\w+)(?:\[[^\]]+\])*\s*=', src):
        lhs.add(m.group(1))
    # LHS concatenation / bit-grouping targets, e.g.
    #   assign {carry, sum} = a + b;
    #   {hi, lo} <= a * b;
    # Every identifier inside the `{...}` group on the LHS of `=`/`<=` is driven.
    # Without this, multi-driver concat targets (very common in CPU/arithmetic
    # IP — SERV's serv_alu `assign {add_cy,result_add} = ...`) were reported as
    # false-positive `undriven-wire` ERRORs. Chip-AGNOSTIC: pure structural.
    for m in re.finditer(r'(?:\bassign\s+)?\{([^{}]*)\}\s*(?:<=|=)(?!=)', src):
        for tok in re.findall(r'[a-zA-Z_]\w*', m.group(1)):
            if tok not in VERILOG_KEYWORDS and not tok.startswith("'"):
                lhs.add(tok)
    # X <= ... or X = ... inside procedural blocks (#544 — multiple subscripts)
    for m in re.finditer(r'(?<![<>!=])\b(\w+)(?:\[[^\]]+\])*\s*(<=|=)(?!=)', src):
        # Skip the tokens around 'begin', 'end', keywords
        name = m.group(1)
        if name not in VERILOG_KEYWORDS and not name.startswith("'"):
            lhs.add(name)
    return lhs


def collect_rhs_set(src: str) -> Set[str]:
    """
    Collect identifiers that appear on the RHS of expressions / conditions / ports.
    This is conservative — it counts ANY identifier token not matched as LHS.
    """
    used = set()
    # Strip out LHS tokens first pass
    #   assign LHS = RHS;  →  keep RHS
    #   X <= RHS;         →  keep RHS
    #   port connections  →  keep all
    # Simpler: tokenize all identifiers, then we'll intersect with known decls.
    for m in re.finditer(r'\b([a-zA-Z_]\w*)\b', src):
        tok = m.group(1)
        if tok not in VERILOG_KEYWORDS:
            used.add(tok)
    return used


def collect_instance_connections(src: str) -> Dict[str, str]:
    """
    For each `.port(signal)` connection in a module instance, return mapping
    port_name -> signal_name. We use this conservatively: any signal that
    appears in .port(signal) is considered both 'driven' and 'read' because
    we don't know the port direction without cross-module analysis.
    """
    connected = {}
    for m in re.finditer(r'\.(\w+)\s*\(\s*([^)]+)\s*\)', src):
        port, sig = m.group(1), m.group(2).strip()
        # ORGANIC #544 — a concat connection `.o({w_hi, w_lo})` drives EVERY
        # identifier inside the braces (the instance output fans out to all
        # of them). The old `^(\w+)` match failed on the leading `{` and
        # left w_hi/w_lo looking undriven. Register each concat member.
        if sig.startswith("{"):
            for tok in re.findall(r'[a-zA-Z_]\w*', sig):
                if tok not in VERILOG_KEYWORDS and not tok.startswith("'"):
                    connected[tok] = port
            continue
        # Take simple identifier from the signal side
        sm = re.match(r'^(\w+)', sig)
        if sm:
            connected[sm.group(1)] = port
    return connected


def rule_undriven_and_unread(src: str, path: str) -> List[Finding]:
    findings: List[Finding] = []
    decls = find_declarations(src)
    lhs = collect_lhs_set(src)
    rhs = collect_rhs_set(src)
    inst_sigs = collect_instance_connections(src)

    for kind, name, lineno in decls:
        driven = name in lhs or name in inst_sigs
        read = name in (rhs - {name})  # exclude itself
        # Conservative: an identifier appears in RHS if used anywhere;
        # but we already include LHS in rhs (tokenizer is blind).
        # Better: count only tokens NOT in decl line.
        # For now, focus on the clear-cut cases.

        if kind == 'wire' and not driven:
            findings.append(Finding(path, lineno, 'ERROR', 'undriven-wire', name,
                f"wire '{name}' declared but never driven (no assign, no instance output)."))
        # ORGANIC R8C3 (#782) — TOTALLY-DEAD reg/logic: declared but NEITHER
        # driven NOR read. The existing reg/logic arm below guards on
        # `name in lhs` (written-but-unread), so a `reg`/`logic` that is never
        # written AND never read fell through entirely and was silently
        # tolerated — only a dead `wire` was flagged (asymmetry). verilator
        # -Wall reports UNUSEDSIGNAL ("not driven, nor used") on such a dead
        # reg/logic. Flag it symmetrically. Carve-outs: skip a memory ARRAY
        # declaration (a storage element whose read port may live in a
        # sibling/future module — same INFO carve-out the unread-reg arm uses)
        # so no-leak holds for staged designs.
        #
        # The read-test MUST count occurrences (the `read = name in (rhs -
        # {name})` short-cut above wrongly removes the name itself from rhs, so
        # it always says "not read" — that mislabels a READ-BUT-UNDRIVEN signal
        # `q` in `w_ptr <= q;` as totally dead). A genuinely dead reg appears
        # ONLY at its own declaration: total token occurrences == 1 (the decl).
        # One extra occurrence means it is read somewhere (a different,
        # undriven-read concern that this TOTALLY-dead arm deliberately leaves
        # alone). chip-AGNOSTIC: pure structural token count.
        _tot_occ = len(re.findall(r'\b' + re.escape(name) + r'\b', src))
        if (kind in ('reg', 'logic') and not driven and _tot_occ <= 1):
            is_mem_array = re.search(
                r'\b(?:reg|logic)\b[^;\n]*\b' + re.escape(name)
                + r'\s*\[[^\]]+\]\s*[;,]', src)
            sev = 'INFO' if is_mem_array else 'WARN'
            note = (" (write-only/unused memory array — likely storage whose "
                    "ports are in a sibling/future module; advisory only)"
                    if is_mem_array else
                    " (declared but neither driven nor read — dead signal; "
                    "`verilator -Wall` UNUSEDSIGNAL).")
            findings.append(Finding(path, lineno, sev, 'unused-signal', name,
                f"{kind} '{name}' is declared but never used.{note}"))
        if kind in ('reg', 'logic') and name in lhs:
            # declared reg that is written but never read on any RHS
            # Heuristic: if the only occurrences are in always-block-LHS, it's unread.
            # Count RHS occurrences excluding LHS sites:
            lhs_pattern = re.compile(
                r'\b' + re.escape(name) + r'\b(?:\s*\[[^\]]+\])?\s*(?:<=|=)(?!=)')
            total_occ = len(re.findall(r'\b' + re.escape(name) + r'\b', src))
            lhs_occ = len(lhs_pattern.findall(src))
            decl_occ = 1  # the declaration itself
            # Reads = total - (LHS assignments) - (declaration)
            reads = total_occ - lhs_occ - decl_occ
            if reads <= 0 and name not in inst_sigs:
                # #754 / ORGANIC-20260616 (C4) — a write-only UNPACKED MEMORY
                # ARRAY (`reg [W-1:0] NAME [DEPTH]`) whose only use is an indexed
                # write is a legitimate single-port-RAM storage pattern whose
                # read port lives in a sibling/future module (staged/incremental
                # designs that store spec-mandated fields ahead of their
                # out-of-scope consumers, e.g. MSHR write_table_q/data_ram_q).
                # Such a write-only array MUST NOT BLOCK a correct submission, so
                # it is reported at INFO (advisory, non-blocking, excluded from
                # the rc=1 condition) rather than WARN. A genuinely dead SCALAR
                # reg still WARNs/blocks. This reuses the same structural
                # memory-array detection used by the autofix path so the two
                # agree, and is purely structural / chip-AGNOSTIC.
                is_mem_array = re.search(
                    r'\b(?:reg|logic)\b[^;\n]*\b' + re.escape(name)
                    + r'\s*\[[^\]]+\]\s*[;,]', src)
                sev = 'INFO' if is_mem_array else 'WARN'
                note = (" (write-only memory array — likely a RAM whose read "
                        "port is in a sibling/future module; advisory only)"
                        if is_mem_array else "")
                f = Finding(path, lineno, sev, 'unread-reg', name,
                    f"{kind} '{name}' declared and written but never read.{note}")
                # ORGANIC #770 round-2 — a scalar reg that is written ONLY by a
                # pure register-pass-through copy (`reg <= <single_identifier>;`)
                # inside a clocked block is the canonical CDC double-flop
                # SYNCHRONIZER stage (e.g. async-FIFO `wq2_rptr`): its reader is
                # the comparison/full-flag logic that lives in a SIBLING module /
                # the other clock domain, so it is NOT dead — it is a legitimate
                # cross-domain signal. The dead-reg structural inference is
                # PROSE_HEURISTIC and the RTL CONTRADICTS it (the flop is a
                # synchronizer feeding out of this submodule). Downgrade to
                # ADVISORY. No-leak: a reg written with COMPUTED logic
                # (`x <= a & b;`, a constant, an expression) is NOT a
                # pass-through sync flop → stays a hard WARN (block-eligible).
                if not is_mem_array and _is_sync_passthrough_reg(src, name):
                    f = _advisory(f, _prov.PROSE_HEURISTIC, _prov.CONTRADICTED)
                findings.append(f)
    return findings


# Single-identifier NBA write of a scalar reg inside a clocked always block —
# the register-to-register copy that defines a CDC synchronizer / pipeline-pass
# flop (ORGANIC #770 round-2). chip-AGNOSTIC: pure SystemVerilog structure.
def _is_sync_passthrough_reg(src: str, name: str) -> bool:
    """True iff EVERY NBA write of scalar `name` is either a SINGLE bare-
    identifier register copy (`q2 <= q1;`) or a reset-clear-to-zero
    (`q2 <= 0;`), AND at least one register-copy write exists inside a
    posedge/negedge (clocked) always block. That is the double-flop CDC
    synchronizer signature: reset to 0, then pass the prior stage straight
    through with no logic. A reg written with COMPUTED logic (operators, a
    non-zero literal/constant value, a slice/concat/index), or by blocking `=`
    only, is NOT a pass-through sync flop → returns False (keeps the hard
    WARN — no-leak biased). chip-AGNOSTIC pure structure."""
    # All NBA writes of `name` and their RHS up to `;`.
    write_re = re.compile(
        r'(?<![<>!=])\b' + re.escape(name) + r'\s*<=\s*([^;]+);')
    rhss = [m.group(1).strip() for m in write_re.finditer(src)]
    if not rhss:
        return False  # no NBA write at all → not a sync flop
    saw_passthrough = False
    for rhs in rhss:
        # A reset-clear write (`<= 0` / `<= 4'd0` / `<= '0` / `<= {N{1'b0}}`) is
        # allowed — it does not carry datapath logic.
        if _sized_literal_value(rhs) == 0 or re.fullmatch(
                r"(?:\d+'[bhdo]?0+|'0|0|\{[^{}]*1'b0[^{}]*\})", rhs):
            continue
        # Otherwise the RHS must be exactly ONE bare identifier (a register
        # pass-through). No operators, no non-zero literals, no slice/concat/
        # index — those carry logic and are NOT a synchronizer stage.
        if not re.fullmatch(r'[A-Za-z_]\w*', rhs) or rhs in VERILOG_KEYWORDS:
            return False
        saw_passthrough = True
    if not saw_passthrough:
        return False  # only reset-clears, no copy → not a synchronizer
    # At least one register-copy NBA write must sit inside a CLOCKED always
    # block (level-sensitive `@(*)` pass-throughs are not CDC synchronizers).
    name_domain = None
    src_ids: Set[str] = set()
    for sens, body, _pos in _iter_always_blocks(src):
        dom = _edge_domain(sens)
        if not dom:
            continue  # comb block — not a clocked synchronizer
        for m in write_re.finditer(body):
            rhs = m.group(1).strip()
            if re.fullmatch(r'[A-Za-z_]\w*', rhs) and rhs not in VERILOG_KEYWORDS:
                name_domain = dom
                src_ids.add(rhs)
    if name_domain is None:
        return False
    # ORGANIC #770 r2 Step-2.7 — a bare clocked `q2 <= q1` is a SYNCHRONIZER only
    # with structural corroboration that it crosses or feeds a domain; otherwise
    # a same-domain copy read NOWHERE is just a dead reg (must keep its WARN).
    # Corroborate by EITHER:
    #   (a) `name` is itself read on the RHS of ANOTHER reg's NBA (a 2-flop chain
    #       qN <= qN-1 downstream — the synchronizer continues), OR
    #   (b) a source it copies is written in a DIFFERENT clock domain (true CDC).
    downstream_re = re.compile(
        r'\b[A-Za-z_]\w*\s*(?:\[[^\]]*\])?\s*<=\s*[^;]*\b'
        + re.escape(name) + r'\b')
    feeds_downstream = False
    for m in downstream_re.finditer(src):
        # ignore name's own writes (`name <= ... name ...`); require a DIFFERENT LHS.
        lhs = re.match(r'\s*([A-Za-z_]\w*)', m.group(0))
        if lhs and lhs.group(1) != name:
            feeds_downstream = True
            break
    if feeds_downstream:
        return True
    # (b) true CDC: walk the copy chain back from `name`; if ANY stage copies a
    # source that is NBA-written in a DIFFERENT edge (clock) domain, the chain
    # crosses clock domains → genuine synchronizer (async_filo: `wq2 <= wq1 <=
    # rptr_gray`, rptr_gray registered in the rclk domain). A SINGLE-clock copy
    # chain (deadcopy: q2<=q1, both wclk, source a same-domain reg or a port) is
    # NOT a CDC → stays a dead-reg WARN (§4.05 no-leak biased). chip-AGNOSTIC.
    # Map every NBA-written name → its edge domain(s).
    dom_of: Dict[str, Set[str]] = {}
    for sens, body, _pos in _iter_always_blocks(src):
        dom = _edge_domain(sens)
        if not dom:
            continue
        for am in re.finditer(r'([A-Za-z_]\w*)(?:\s*\[[^\]]*\])?\s*<=', body):
            dom_of.setdefault(am.group(1), set()).add(dom)
    seen_chain: Set[str] = set()
    frontier = set(src_ids)
    while frontier:
        sid = frontier.pop()
        if sid in seen_chain:
            continue
        seen_chain.add(sid)
        # if this stage is written in a domain other than name's → CDC.
        if any(d != name_domain for d in dom_of.get(sid, set())):
            return True
        # follow the chain: what bare register does `sid` copy?
        for cm in re.finditer(
                r'(?<![<>!=])\b' + re.escape(sid) + r'\s*<=\s*([^;]+);', src):
            rhs = cm.group(1).strip()
            if re.fullmatch(r'[A-Za-z_]\w*', rhs) and rhs not in VERILOG_KEYWORDS:
                frontier.add(rhs)
    return False


