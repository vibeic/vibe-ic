# Sized integer literal: N'bxx / N'hxx / N'dxx / N'oxx (optional underscores,
# optional s for signed). Chip-AGNOSTIC: this is plain SystemVerilog syntax.
_SIZED_LITERAL_RE = re.compile(
    r"\b(\d+)\s*'\s*([sS]?)([bBoOdDhH])\s*([0-9a-fA-F_xXzZ]+)")


def _sized_literal_value(tok: str):
    """Return the integer value of a sized literal like 2'b10 / 8'hFF.

    Returns None when the literal is non-deterministic (contains x/z, or is not
    a clean sized literal) so the caller can stay conservative. ORGANIC #764.
    """
    m = _SIZED_LITERAL_RE.fullmatch(tok.strip())
    if not m:
        return None
    base = m.group(3).lower()
    digits = m.group(4).replace('_', '')
    if any(c in 'xXzZ' for c in digits):
        return None  # don't-care / hi-Z label — value not determinable
    try:
        if base == 'b':
            return int(digits, 2)
        if base == 'o':
            return int(digits, 8)
        if base == 'd':
            return int(digits, 10)
        if base == 'h':
            return int(digits, 16)
    except ValueError:
        return None
    return None


def _resolve_selector_width(src: str, expr: str):
    """Resolve the bit-width of a case selector from its declaration.

    Only succeeds for a SIMPLE scalar identifier selector whose declaration
    carries a CONCRETE numeric `[hi:lo]` range (hi/lo are plain integers, not
    parameter expressions). Returns the width in bits, or None when it cannot
    be deterministically resolved (parameterized width, no range, expression
    selector, …). Conservative-by-design: None -> keep the WARN. Chip-AGNOSTIC.
    ORGANIC #764.
    """
    name = expr.strip()
    # Selector must be a bare identifier (no concat/slice/expression).
    if not re.fullmatch(r'[A-Za-z_]\w*', name):
        return None
    # Find a declaration of this signal carrying a numeric [hi:lo] range.
    # Matches input/output/inout/reg/wire/logic ... [HI:LO] ... name
    decl_re = re.compile(
        r'\b(?:input|output|inout|reg|wire|logic)\b[^;\n]*?'
        r'\[\s*(\d+)\s*:\s*(\d+)\s*\][^;\n]*?\b' + re.escape(name) + r'\b')
    for m in decl_re.finditer(src):
        hi = int(m.group(1))
        lo = int(m.group(2))
        return abs(hi - lo) + 1
    return None


# ORGANIC #770 round-2 — resolve a SYMBOLIC state-localparam to its integer
# value so a fully-enumerated FSM written with localparam labels
# (`case (state) S_IDLE: ... S_DONE: ...`) is recognised as exhaustive exactly
# like a numeric-literal one. chip-AGNOSTIC: pure SystemVerilog constant parse.
def _localparam_int_values(src: str) -> Dict[str, int]:
    """Map every `localparam`/`parameter NAME = <const>;` to its integer value
    (when the RHS is a deterministically-resolvable constant). Earlier params
    feed later ones via `_eval_const_int`. Non-constant RHS are skipped."""
    vals: Dict[str, int] = {}
    for m in _LOCALPARAM_DECL_RE.finditer(src):
        name, rhs = m.group(1), m.group(2)
        # ORGANIC #770 r3 — a COMMA-SEPARATED multi-declaration
        # (`localparam IDLE=2'd0, LOAD=2'd1, RUN=2'd2, DONE=2'd3;`) captures the
        # FIRST name then the whole tail as `rhs`. Split the tail into the
        # remaining `NAME = value` continuations so every state localparam
        # resolves (a symbolic-localparam FSM declared on one line was otherwise
        # unrecognised → case-no-default false WARN, binary_search_tree FP).
        # Split only at TOP-LEVEL commas (depth-aware so a `{a,b}`/`(a,b)` value
        # stays intact).
        segs: List[str] = []
        depth = 0
        cur = ""
        for ch in rhs:
            if ch in "([{":
                depth += 1
            elif ch in ")]}":
                depth = max(0, depth - 1)
            if ch == "," and depth == 0:
                segs.append(cur)
                cur = ""
            else:
                cur += ch
        if cur:
            segs.append(cur)
        pairs = [(name, segs[0] if segs else rhs)]
        for seg in segs[1:]:
            pm = re.match(r"\s*([A-Za-z_]\w*)\s*=\s*(.+)$", seg, re.DOTALL)
            if pm:
                pairs.append((pm.group(1), pm.group(2)))
        for nm, vexpr in pairs:
            if nm in VERILOG_KEYWORDS:
                continue
            v = _eval_const_int(vexpr, vals)
            if v is not None:
                vals[nm] = v
    return vals


def _label_value(tok: str, params: Dict[str, int]):
    """Resolve ONE case-label token to its integer value: a sized numeric
    literal OR a known state-localparam name. Returns None when neither (a
    symbolic label whose value we cannot prove → caller stays conservative)."""
    v = _sized_literal_value(tok)
    if v is not None:
        return v
    if re.fullmatch(r'[A-Za-z_]\w*', tok) and tok in params:
        return params[tok]
    return None


def _case_is_exhaustive(src: str, expr: str, block: str):
    """Return True iff the case PROVABLY enumerates all 2**width selector values.

    Requirements (all must hold, else returns False = stay conservative):
      * selector width deterministically resolvable to N bits (<= a sane cap),
      * EVERY case label is a clean sized numeric literal OR a resolvable
        state-localparam (ORGANIC #770 round-2: a symbolic-localparam FSM whose
        labels are all `localparam`s of known value is just as enumerable as a
        numeric-literal one),
      * the distinct label values exactly cover {0 .. 2**N - 1}.
    Purely structural & chip-AGNOSTIC (no design/benchmark literal). ORGANIC #764.
    """
    width = _resolve_selector_width(src, expr)
    if width is None or width <= 0 or width > 12:
        return False  # unknown or too-wide to enumerate -> conservative
    # ORGANIC #770 round-2 — known localparam/parameter integer values so a
    # symbolic FSM label (`S_IDLE`/`S_DONE`/…) resolves to its numeric value.
    params = _localparam_int_values(src)

    # Isolate the case body: strip the leading `case (...)` head and the
    # trailing `endcase`.
    body = block
    body = re.sub(r'^\s*\bcase[szx]?\s*\([^)]*\)', '', body, count=1)
    body = re.sub(r'\bendcase\b.*$', '', body, flags=re.DOTALL)

    # Strip line + block comments so legend text ('// 90 deg') can't be parsed
    # as a label.
    body = re.sub(r'//[^\n]*', '', body)
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.DOTALL)

    # A branch label is the token-list that appears at a statement boundary and
    # is terminated by ':'. We find each ':' that directly follows a label head
    # (run of label tokens) at a statement boundary (body start, or just after a
    # top-level ';' / 'begin' / 'end'). The ':' must NOT be a part-select
    # (+:/-:), a ternary (?:), a scope resolution (::), or non-blocking-with-
    # equals (:=). A symbolic identifier sitting at a branch boundary => not
    # resolvable => bail conservatively. Chip-AGNOSTIC structural scan.
    labels = []
    label_re = re.compile(
        r"(?:(?<=^)|(?<=[;)])|(?<=\bbegin\b)|(?<=\bend\b))"  # statement boundary
        r"\s*([0-9A-Za-z_',\s]+?)\s*"
        r":(?![:=+\-])",
        re.MULTILINE)
    saw_any = False
    for m in label_re.finditer(body):
        head = m.group(1).strip()
        if not head:
            continue
        # ORGANIC #781 (round-8 cluster R8C2) — the label-head class
        # `[0-9A-Za-z_',\s]+?` admits whitespace, and the `(?<=\bbegin\b)` /
        # `(?<=\bend\b)` statement-boundary lookbehinds do NOT consume the
        # keyword. So when a branch body uses the ubiquitous
        # `LABEL: begin … end` idiom, the trailing `end`(s) of one branch
        # bleed into the NEXT label head, e.g. head = 'end\n end\n
        # ENTRY_PROCESSING'. The old comma-only split then yielded a single
        # un-resolvable part and `_label_value` returned None, so a fully-
        # enumerated begin/end FSM was wrongly judged non-exhaustive and
        # HARD-BLOCKED (case-no-default WARN). Split each head on whitespace
        # AND commas, then drop the structural `begin`/`end`/… keyword tokens
        # (they are never case labels) before resolving. A fully-enumerated
        # `begin/end` FSM is then recognised exactly like its single-statement
        # twin, while a genuinely symbolic-unknown label survives the keyword
        # filter and still bails to False below (§4.05 no-leak preserved — a
        # partial / symbolic / out-of-range begin/end FSM still hard-blocks).
        parts = [p for p in re.split(r'[\s,]+', head)
                 if p and p not in VERILOG_KEYWORDS]
        if not parts:
            continue
        for p in parts:
            v = _label_value(p, params)
            if v is None:
                # Symbolic-but-unknown / unsized / x-z / non-literal label at a
                # branch boundary -> not deterministically resolvable ->
                # conservative. (A symbolic label that IS a known state-localparam
                # resolves to its integer value via _label_value — ORGANIC #770
                # round-2 — so a fully-enumerated localparam FSM is recognised.)
                return False
            if v >= (1 << width):
                return False  # label out of declared range -> bail
            labels.append(v)
        saw_any = True

    if not saw_any or not labels:
        return False

    return set(labels) == set(range(1 << width))


def _clocked_always_spans(src: str) -> List[tuple]:
    """ORGANIC #770 r4 — (start, end) char-offset spans of every CLOCKED
    (edge-sensitive `@(posedge/negedge …)` / always_ff) always block. A `case`
    inside such a block CANNOT infer a latch: on an unlisted selector code the
    state register simply HOLDS its value (the canonical registered-FSM idiom).
    Latch risk only exists in a COMBINATIONAL `always @(*)` / always_comb / a
    level-sensitive block. chip-AGNOSTIC: pure edge-sensitivity grammar.

    r4 Step-2.7: the span END must be the clocked block's OWN matching `end`
    (or its single statement), NOT `_block_body_after`'s result — that extends to
    the NEXT always/endmodule, so a combinational case textually FOLLOWING a
    clocked block fell inside the over-extended span and was wrongly downgraded
    (a §4.05 leak). Compute the real end by `begin/end` depth tracking from the
    statement that opens the block body."""
    spans: List[tuple] = []
    for bm in re.finditer(
            r'\balways(?:_ff)?\s*@\s*\(([^)]*)\)', src):
        sens = bm.group(1)
        if not _edge_domain(sens):
            continue
        i = bm.end()
        n = len(src)
        # skip whitespace to the first body token.
        while i < n and src[i].isspace():
            i += 1
        if i < n and re.match(r'\bbegin\b', src[i:]):
            # a begin/end block — find the MATCHING end by depth counting over
            # begin/end keyword tokens (string/comment-free enough for our RTL).
            depth = 0
            for km in re.finditer(r'\b(begin|end)\b', src[i:]):
                depth += 1 if km.group(1) == 'begin' else -1
                if depth == 0:
                    spans.append((bm.start(), i + km.end()))
                    break
            else:
                spans.append((bm.start(), n))
        else:
            # a single (non-begin) statement — ends at the next ';'.
            semi = src.find(';', i)
            spans.append((bm.start(), (semi + 1) if semi != -1 else n))
    return spans


# ORGANIC #803 Step-2.7 §4.05 — `VERILOG_KEYWORDS` over-broadly includes the
# hi-Z / don't-care LITERAL-spelling tokens `x`/`z`, which are ALSO legal Verilog
# IDENTIFIERS. A token that appears as an assignment LHS (immediately before
# `=`/`<=`) is ALWAYS a real signal (you cannot assign to a literal), so it must
# never be dropped as a keyword — else a case-body output literally named `x`/`z`
# vanishes from the coverage set and a genuine inferred latch is masked.
_LHS_LITERAL_NAMES = frozenset({"x", "z"})


def _procedural_assigned_lhs(text: str) -> Set[str]:
    """ORGANIC #794 — set of identifiers assigned by a procedural `=` / `<=` at
    STATEMENT level (paren depth 0) inside `text`.

    Paren-depth gating is the key correctness point: a `<=` (or `=`) INSIDE
    `(...)` is an `if`/`while` condition or a call argument where `<=` is a
    COMPARISON, not a non-blocking assignment (e.g. `if (current_floor_reg <=
    min_request)`), and must NOT be counted as an LHS. `==` / `>=` / `!=` /
    `<=`-as-compare are rejected by the surrounding-operator guard. A
    CONCATENATION LHS `{a, b[1:0], c} =` records EVERY identifier inside the
    braces (Step-2.7 §4.05 — a missed concat LHS would falsely shrink the
    assigned set and mask a latch); a bit/part-select LHS records the BASE name
    (the caller separately refuses to PROVE coverage when a subscript is present
    — see `_lhs_has_subscript`). Purely structural & chip-AGNOSTIC."""
    out: Set[str] = set()
    depth = 0
    n = len(text)
    i = 0
    while i < n:
        c = text[i]
        if c == '(':
            depth += 1
            i += 1
            continue
        if c == ')':
            depth = max(0, depth - 1)
            i += 1
            continue
        if depth == 0 and ((c == '<' and text[i:i + 2] == '<=') or c == '='):
            if c == '<':
                op_end = i + 2
            else:
                if text[i:i + 2] == '==':       # equality compare, not assign
                    i += 2
                    continue
                if i > 0 and text[i - 1] in '<>!=':  # part of <= >= != ==
                    i += 1
                    continue
                op_end = i + 1
            # scan back to the LHS identifier, skipping a trailing [..] subscript
            j = i - 1
            while j >= 0 and text[j].isspace():
                j -= 1
            while j >= 0 and text[j] == ']':
                d2 = 0
                while j >= 0:
                    if text[j] == ']':
                        d2 += 1
                    elif text[j] == '[':
                        d2 -= 1
                    j -= 1
                    if d2 == 0:
                        break
                while j >= 0 and text[j].isspace():
                    j -= 1
            # ORGANIC #794 Step-2.7 §4.05 — a CONCATENATION LHS `{a, b[1:0], c} =`
            # assigns EVERY identifier inside the braces. The scalar scan-back
            # below would read only the brace `}` and yield an EMPTY name, so a
            # case arm assigning `{a,b}` would vanish from the assigned set and a
            # GENUINE latch on a/b would be falsely downgraded. Extract every
            # identifier inside the matching `{...}` (over-inclusion of an index
            # var is the SAFE direction — it can only KEEP a hard WARN).
            if j >= 0 and text[j] == '}':
                d3 = 0
                m = j
                while m >= 0:
                    if text[m] == '}':
                        d3 += 1
                    elif text[m] == '{':
                        d3 -= 1
                    if d3 == 0:
                        break
                    m -= 1
                concat = text[m:j + 1] if m >= 0 else ""
                for nm in re.findall(r'[A-Za-z_]\w*', concat):
                    if nm not in VERILOG_KEYWORDS or nm in _LHS_LITERAL_NAMES:
                        out.add(nm)
                i = op_end
                continue
            k = j
            while k >= 0 and (text[k].isalnum() or text[k] == '_'):
                k -= 1
            name = text[k + 1:j + 1]
            if (name and not name[0].isdigit()
                    and (name not in VERILOG_KEYWORDS
                         or name in _LHS_LITERAL_NAMES)):
                out.add(name)
            i = op_end
            continue
        i += 1
    return out


# ORGANIC #794 Step-2.7 §4.05 — a SUBSCRIPTED (bit/part-select) assignment LHS
# means the base-name assigned set CANNOT prove full-vector coverage: a pre-case
# default on `dout[3:2]` and a case-body write on `dout[1:0]` both reduce to the
# base `dout`, so a genuine latch on the unwritten slice would be falsely
# downgraded. These detect a subscripted scalar LHS (`name[...] =`) and a concat
# LHS containing a slice (`{ ... [..] ... } =`); the caller stays conservative
# (keeps the hard WARN) whenever EITHER region has one. A false hit (a `]<=` that
# is actually a condition compare) only KEEPS a hard WARN — the safe direction.
_SUBSCRIPTED_LHS_RE = re.compile(r'\][ \t]*(?:<=|=(?!=))')
_CONCAT_SLICE_LHS_RE = re.compile(r'\{[^{}]*\[[^{}]*\}[ \t]*(?:<=|=(?!=))')


def _lhs_has_subscript(text: str) -> bool:
    """True if any assignment in `text` has a SUBSCRIPTED LHS (a bit/part-select
    scalar, or a concat containing one). #794 Step-2.7 §4.05 — such an assign
    cannot prove full-vector coverage from a base name."""
    return bool(_SUBSCRIPTED_LHS_RE.search(text)
                or _CONCAT_SLICE_LHS_RE.search(text))


def _enclosing_always_body(src: str, case_off: int) -> Optional[Tuple[int, int]]:
    """ORGANIC #794 — (body_start_off, block_end_off) of the TIGHTEST always
    block textually containing `case_off`, where body_start_off is the char
    offset just AFTER the `always [@(...)]` header. Handles `always`,
    `always_comb`, `always_latch`, `always_ff` with or without a sensitivity
    list. chip-AGNOSTIC: pure begin/end depth tracking."""
    best: Optional[Tuple[int, int]] = None
    for bm in re.finditer(
            r'\balways(?:_ff|_comb|_latch)?\s*(?:@\s*\([^)]*\))?', src):
        i = bm.end()
        n = len(src)
        while i < n and src[i].isspace():
            i += 1
        if i < n and re.match(r'\bbegin\b', src[i:]):
            depth = 0
            blk_end = n
            for km in re.finditer(r'\b(begin|end)\b', src[i:]):
                depth += 1 if km.group(1) == 'begin' else -1
                if depth == 0:
                    blk_end = i + km.end()
                    break
        else:
            semi = src.find(';', i)
            blk_end = (semi + 1) if semi != -1 else n
        if bm.end() <= case_off < blk_end:
            if best is None or bm.end() > best[0]:
                best = (bm.end(), blk_end)
    return best


def _case_lhs_all_pre_assigned(src: str, case_head_off: int) -> bool:
    """ORGANIC #794 — True iff this combinational `case` is the canonical
    latch-FREE fallthrough idiom: EVERY identifier assigned inside the case body
    is ALSO unconditionally assigned (at statement-top — not under any
    if/else/case/for/while) in the SAME always block, textually BEFORE the case
    head. Then an unlisted selector code cannot infer a latch — the pre-case
    default holds — so verilator emits NO %Warning-LATCH (only CASEINCOMPLETE).
    §4.05 no-leak: returns False (keep the hard WARN) whenever ANY case-body LHS
    lacks such an unconditional pre-case default, when the pre-case region is not
    a flat statement-top list, OR when a SUBSCRIPTED (bit/part-select) LHS
    participates (a base name cannot prove a full-vector default — Step-2.7)."""
    body = _enclosing_always_body(src, case_head_off)
    if body is None:
        return False
    body_start, blk_end = body
    pre = src[body_start:case_head_off]
    # strip the single `begin` that opens the always body, then require the
    # pre-case region to be a FLAT statement-top list (no control construct). If
    # any if/else/for/while/case appears before the case, a pre-assignment might
    # be conditional → not provably unconditional → stay conservative.
    pre_body = re.sub(r'^\s*begin\b', '', pre, count=1)
    # ORGANIC #803 (extends #794): the unconditional pre-case defaults are the
    # LEADING FLAT statement-top prefix — from the body start up to the FIRST
    # control-construct token (if/else/for/while/case/repeat/forever). The
    # original #794 bailed entirely the moment ANY control token appeared in the
    # pre-case region, which MISSED the ubiquitous "priority-if-before-case" FSM
    # idiom: statement-top defaults, then `if (highest_priority) X; else
    # case(...)` (forced by any "from ANY state / regardless of current state"
    # spec). Those leading flat defaults provably HOLD on any unlisted selector
    # code REGARDLESS of an intervening priority if/else (whose own branches only
    # re-assign vars ALREADY defaulted in the flat prefix). §4.05 boundary
    # preserved: a case-LHS FIRST assigned only inside/after a conditional is NOT
    # in the flat prefix → body_lhs ⊄ uncond → hard WARN (proven latch).
    _ctrl = re.search(r'\b(if|else|for|while|case[szx]?|repeat|forever)\b',
                      pre_body)
    flat_prefix = pre_body[:_ctrl.start()] if _ctrl else pre_body
    uncond = _procedural_assigned_lhs(flat_prefix)
    if not uncond:
        return False
    # case body: from after the `(...)` head to the matching endcase.
    head_end = src.find(')', case_head_off)
    endcase_off = src.find('endcase', case_head_off)
    if head_end == -1 or endcase_off == -1 or endcase_off > blk_end:
        return False
    case_body = src[head_end + 1:endcase_off]
    # Step-2.7 §4.05 — a bit/part-select LHS in the case body or the FLAT prefix
    # defeats base-name coverage proof (a sliced default cannot cover a different
    # sliced write); stay conservative and keep the hard WARN.
    if _lhs_has_subscript(case_body) or _lhs_has_subscript(flat_prefix):
        return False
    body_lhs = _procedural_assigned_lhs(case_body)
    if not body_lhs:
        return False
    return body_lhs <= uncond


def rule_case_coverage(src: str, path: str) -> List[Finding]:
    findings: List[Finding] = []
    # Find every `case (expr) ... endcase` block with its starting line
    # Simple scan: find `case(...)` opening, find matching endcase
    lines = src.split('\n')
    clocked_spans = _clocked_always_spans(src)
    # char offset of the start of each line (for the clocked-span test).
    line_off = [0]
    for ln in lines:
        line_off.append(line_off[-1] + len(ln) + 1)
    case_starts = [(i, m.group(1))
                   for i, ln in enumerate(lines, start=1)
                   for m in re.finditer(r'\bcase[szx]?\s*\(([^)]+)\)', ln)]
    for start_line, expr in case_starts:
        # Find endcase
        end_line = start_line
        for j in range(start_line, len(lines) + 1):
            if j - 1 < len(lines) and 'endcase' in lines[j - 1]:
                end_line = j
                break
        block = '\n'.join(lines[start_line - 1:end_line])
        if not re.search(r'\bdefault\s*:', block):
            # ORGANIC #764 — suppress when the case is PROVABLY exhaustive: a
            # fully-enumerated case (all 2**width sized-literal labels present)
            # cannot infer a latch and has no un-enumerated value, so the WARN
            # is a false positive (it even fired on the golden/reference
            # module). Stay conservative: only suppress when the selector width
            # AND every label are deterministically resolvable; otherwise keep
            # the WARN (symbolic localparams, parameterized widths, partial
            # enumerations all stay flagged).
            if _case_is_exhaustive(src, expr, block):
                continue
            f = Finding(path, start_line, 'WARN', 'case-no-default', expr.strip(),
                f"case ({expr.strip()}) has no default branch — "
                "values not enumerated may generate latch or undefined behavior.")
            # ORGANIC #770 r4 — a case inside a CLOCKED (sequential) always block
            # cannot infer a LATCH (the state register HOLDS on an unlisted code,
            # the canonical registered-FSM idiom). Latch risk is COMBINATIONAL
            # only, so downgrade the sequential-case WARN to ADVISORY (reported,
            # never a hard block). A combinational `always @(*)` case with no
            # default STILL hard-WARNs (real latch risk — §4.05 no-leak).
            # char offset of the actual `case` token on the start line (not the
            # line start) — used for both the clocked-span test and the
            # pre-assigned-default test (#794).
            line_start = line_off[start_line - 1]
            cm = re.search(r'\bcase[szx]?\s*\(', lines[start_line - 1])
            case_off = line_start + (cm.start() if cm else 0)
            in_clocked = any(s <= case_off < e for s, e in clocked_spans)
            if in_clocked:
                f = _advisory(f, _prov.PROSE_HEURISTIC, _prov.CONTRADICTED)
                f.advisory_note = ("case in a CLOCKED block — on an unlisted code "
                                   "any assigned variable (state reg / temp) HOLDS "
                                   "its previous value; no latch / uninitialised "
                                   "state. Latch risk is COMBINATIONAL-only "
                                   "(always @(*)); advisory, not a hard block "
                                   "(ORGANIC #770 r4)")
            elif _case_lhs_all_pre_assigned(src, case_off):
                # ORGANIC #794 — a COMBINATIONAL `always @(*)` case with no
                # default, but EVERY case-body LHS is unconditionally assigned
                # (statement-top) before the case head. The pre-case default
                # holds on any unlisted selector code, so NO latch can be
                # inferred (verilator confirms: only CASEINCOMPLETE, no
                # %Warning-LATCH). This is the canonical latch-free
                # combinational-FSM idiom → downgrade to advisory. §4.05 no-leak:
                # _case_lhs_all_pre_assigned returns False when ANY case-body LHS
                # lacks an unconditional pre-case default, when a subscripted LHS
                # defeats base-name coverage, or when a concat LHS is missed.
                f = _advisory(f, _prov.PROSE_HEURISTIC, _prov.CONTRADICTED)
                f.advisory_note = ("combinational case with no default but every "
                                   "case-body LHS is unconditionally pre-assigned "
                                   "(statement-top) before the case head — the "
                                   "pre-case default holds on an unlisted code, so "
                                   "no latch can be inferred (latch-free "
                                   "fallthrough); advisory, not a hard block "
                                   "(ORGANIC #794)")
            findings.append(f)
    return findings


