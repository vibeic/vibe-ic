def autofix_uninit_registered_output(path: Path) -> Tuple[int, List[str]]:
    """Deterministically REPAIR the `uninit-registered-output` finding in-place.

    For every reset-less registered output with no power-up value, insert a
    separate `initial <name> = 0;` block just before the module's `endmodule`
    (Verilator-PROCASSINIT-clean, unlike a decl initializer). This makes the
    power-up-determinism lesson ENFORCED by the tool rather than dependent on a
    caller / prompt remembering to apply it (the v0.1.24 lesson: a fix that lives
    only in a free-text instruction is a fix you can typo). chip-AGNOSTIC, safe:
    only fires on the conservative reset-less / no-init case, and a redundant
    `initial 0` on a never-reset DFF is harmless for sim/FPGA and ignored on ASIC.

    Returns (count_fixed, [names]). No-op (0, []) if nothing to fix.
    """
    raw = path.read_text(errors='replace')
    src = strip_comments(raw)
    # v0.1.40 (re-audit NEW-1 fix) — restrict analysis to the TOP MODULE only.
    # The autofix inserts the `initial` block before the file's LAST
    # `endmodule`, which is the top module's. For single-module files this is a
    # no-op refinement. For multi-module files (e.g. RTLLM asyn_fifo, which
    # contains a `dual_port_RAM` submodule above the top), scanning the whole
    # file flatly would:
    #   • pull a name that's a `reg` in the submodule but a `wire` in the top
    #     module → `initial wire_name = 0;` → iverilog "not a valid l-value"
    #   • pull a memory array `reg [W-1:0] MEM [0:D-1]` from the submodule and
    #     emit it as a scalar `MEM = 0;` → iverilog "Could not find variable"
    # Scope the search to the top module's body to eliminate both classes.
    top_body, top_start = _extract_top_module_body(src)
    src_scope = top_body if top_body is not None else src
    names: List[str] = []
    seen: Set[str] = set()
    # (a) registered OUTPUT ports with no power-up (the WARN-rule set).
    for f in rule_uninit_registered_output(src_scope, str(path)):
        if f.rule == 'uninit-registered-output' and f.symbol not in seen:
            names.append(f.symbol); seen.add(f.symbol)
    # (b) INTERNAL registered regs that drive a module output via a continuous
    #     assign (e.g. `reg q; ... q<=...; assign out=q;`). Same power-up-X bug,
    #     just one hop removed. Reset-less modules only.
    input_decls = ' '.join(re.findall(r'\binput\b[^;)\n]*', src_scope))
    is_resetless = not _RESET_NAME_RE.search(input_decls)
    # v0.1.40 — also collect TOP-SCOPE wire names so case (c) can skip names
    # that are wires in this module (even if the same name is a reg in a
    # sibling submodule that lives in the same file).
    top_wires = set(re.findall(
        r'\b(?:wire|output\s+wire|input\s+wire|inout\s+wire)\b(?:\s+signed)?\s*'
        r'(?:\[[^\]]+\]\s*)?([A-Za-z_]\w*)\s*(?=[,;)=])', src_scope))
    if is_resetless:
        out_ports = set(re.findall(
            r'\boutput\b\s+(?:(?:reg|logic|wire)\s+)?(?:signed\s+)?(?:\[[^\]]+\]\s*)?'
            r'([A-Za-z_]\w*)\s*(?=[,;)=])', src_scope))
        registered = {mm.group(1) for mm in
                      re.finditer(r'(?<![<>!=])\b(\w+)(?:\[[^\]]+\])?\s*<=', src_scope)}
        has_initial = bool(re.search(r'\binitial\b', src_scope))
        for om in re.finditer(r'\bassign\s+([A-Za-z_]\w*)\s*=\s*([^;]+);', src_scope):
            if om.group(1) not in out_ports:
                continue
            for rhs_id in re.findall(r'\b([A-Za-z_]\w*)\b', om.group(2)):
                if rhs_id in registered and rhs_id not in seen \
                        and rhs_id not in VERILOG_KEYWORDS \
                        and rhs_id not in top_wires:
                    decl_init = re.search(
                        r'\b(?:reg|logic)\b[^;\n]*\b' + re.escape(rhs_id) + r'\s*=', src_scope)
                    in_initial = has_initial and re.search(
                        r'\binitial\b[\s\S]{0,200}?\b' + re.escape(rhs_id) + r'\s*(<=|=)', src_scope)
                    if not decl_init and not in_initial:
                        names.append(rhs_id); seen.add(rhs_id)
    # (c) v0.1.38 — ALL internal `reg` declarations in reset-less modules.
    # v0.1.40 — top-module-scoped; skip memory arrays; skip names that are
    # wires in this module's scope.
    # v0.1.41 — also skip regs declared inside `generate ... endgenerate`
    # blocks; those have generate-block scope (e.g. g[i].local_reg) and
    # cannot be referenced by an `initial begin local_reg = 0; end` block
    # at module scope (iverilog: "Could not find variable").
    if is_resetless:
        # Mask out generate-block bodies so the reg/wire/registered scans
        # don't see them. Replacement preserves character offsets for any
        # caller that re-resolves line numbers.
        src_no_gen = _mask_generate_blocks(src_scope)
        all_regs: Dict[str, int] = {}
        # v0.1.40 — match `reg [...] name1, name2;` OR `reg name [0:D-1];`
        # (memory) — the memory form is REJECTED at the per-name walk by the
        # trailing-`[…]` test.
        for m in re.finditer(
                r'\breg\b(?:\s+signed)?\s*(?:\[[^\]]+\]\s*)?([^;]+);', src_no_gen):
            lineno_d = src_no_gen[:m.start()].count('\n') + 1
            decl_body = m.group(1)
            # Walk the comma-separated names; reject any name whose decl has
            # a trailing `[...]` (memory array) — those need element-wise init
            # via an integer loop, which the scalar `name = 0;` autofix would
            # mis-emit as `MEM = 0;` (iverilog: 'Could not find variable').
            for nm_match in re.finditer(
                    r'([A-Za-z_]\w*)\s*(\[[^\]]+\])?\s*(?:=[^,;]+)?', decl_body):
                nm = nm_match.group(1)
                trailing_bracket = nm_match.group(2)
                if not nm or nm in VERILOG_KEYWORDS or nm in all_regs:
                    continue
                if trailing_bracket:
                    # memory array — skip; element-wise init is out of scope
                    # for this autofix (would need an integer loop).
                    continue
                all_regs[nm] = lineno_d
        registered = {mm.group(1) for mm in
                      re.finditer(r'(?<![<>!=])\b(\w+)(?:\[[^\]]+\])?\s*<=', src_no_gen)}
        has_initial = bool(re.search(r'\binitial\b', src_no_gen))
        for nm in all_regs:
            if nm in seen or nm not in registered or nm in top_wires:
                continue
            decl_init = re.search(
                r'\breg\b[^;\n]*\b' + re.escape(nm) + r'\s*=', src_no_gen)
            in_initial = has_initial and re.search(
                r'\binitial\b[\s\S]{0,200}?\b' + re.escape(nm) + r'\s*(<=|=)', src_no_gen)
            if decl_init or in_initial:
                continue
            names.append(nm); seen.add(nm)
    if not names:
        return 0, []
    # v0.1.41 (re-re-audit Issue 2 fix) — `rfind('endmodule')` must run on
    # the COMMENT-STRIPPED source so a trailing `// endmodule in a note`
    # comment doesn't poison the lookup. Conveniently, `strip_comments`
    # preserves character offsets (it replaces comment characters with
    # spaces and keeps newlines), so the offset in stripped IS the offset
    # in raw — no translation needed. The rstrip() also dissolves the
    # trailing comment-as-spaces so rfind lands on the real endmodule.
    src_stripped = strip_comments(raw)
    idx = src_stripped.rstrip().rfind('endmodule')
    if idx < 0:
        return 0, []
    block = "\n  // power-up determinism (rtl_hygiene_lint --fix): reset-less registered\n"
    block += "  // outputs default to 0 so they are not X at t=0.\n  initial begin\n"
    block += "".join(f"    {n} = 0;\n" for n in names)
    block += "  end\n\n"
    patched = raw[:idx] + block + raw[idx:]
    path.write_text(patched)
    return len(names), names


def _mask_generate_blocks(src: str) -> str:
    """v0.1.41 (re-re-audit Issue 1 fix) — replace every `generate ... endgenerate`
    block body with whitespace of equal length, so the caller's regex scans
    don't pick up regs declared inside generate-scope. Character offsets are
    preserved so any caller computing line numbers still gets the right answer.

    A more sophisticated solution would track per-block reg scope, but for
    the autofix's purpose (emit a module-scope `initial begin … end`), regs
    inside `generate` are simply not addressable from module scope and must
    be excluded from the candidate set.
    """
    out = list(src)
    depth = 0
    block_start = -1
    for m in re.finditer(r'\b(generate|endgenerate)\b', src):
        if m.group(1) == 'generate':
            if depth == 0:
                block_start = m.end()
            depth += 1
        else:  # endgenerate
            depth -= 1
            if depth == 0 and block_start >= 0:
                # Replace block_start..m.start() with spaces (preserve newlines).
                for i in range(block_start, m.start()):
                    if out[i] != '\n':
                        out[i] = ' '
                block_start = -1
    return "".join(out)


def _extract_top_module_body(src: str):
    """v0.1.40 (re-audit NEW-1 fix) — return the (text, start_offset) for the
    TOP module (its `endmodule` is the file's LAST `endmodule`). Returns
    (None, None) on parse failure — caller falls back to the whole-file source.

    Includes the module HEADER (declaration + port list) so the reset detector
    sees ANSI-style `input rst_n` inside the port list. Verilog disallows
    nested modules, so 'last `module …` declaration before the last `endmodule`'
    is the correct top-module opener.
    """
    last_endmod = src.rstrip().rfind('endmodule')
    if last_endmod < 0:
        return None, None
    last_mod_decl = -1
    for m in re.finditer(r'\bmodule\b\s+[A-Za-z_]\w*', src[:last_endmod]):
        last_mod_decl = m.start()
    if last_mod_decl < 0:
        return None, None
    return src[last_mod_decl:last_endmod], last_mod_decl


def main():
    ap = argparse.ArgumentParser(description='General RTL hygiene lint.')
    ap.add_argument('files', nargs='+', help='Verilog/SystemVerilog files')
    ap.add_argument('--json', help='Write findings as JSON to this path')
    ap.add_argument('--severity', choices=['ERROR', 'WARN', 'INFO'], default='INFO',
                    help='Minimum severity to report (default: INFO)')
    ap.add_argument('--fix', action='store_true',
                    help='Deterministically repair in-place: (a) the '
                         'uninit-registered-output finding (insert `initial <reg>=0;`), '
                         'enforcing the power-up determinism lesson; and (b) the '
                         'unguarded-sim-only-assert finding (fence immediate `assert` '
                         'statements in `// synthesis translate_off … translate_on` so '
                         'they stop false-failing the synth gate). Regardless of caller/prompt.')
    args = ap.parse_args()

    if args.fix:
        total = 0
        guarded_total = 0
        for f in args.files:
            p = Path(f)
            if not p.exists():
                print(f"WARNING: file not found: {f}", file=sys.stderr)
                continue
            n, names = autofix_uninit_registered_output(p)
            total += n
            if n:
                print(f"{f}: inserted `initial` power-up 0 for {names}")
            # Run the sim-only-assert fence AFTER the power-up fix (the latter
            # appends an `initial` block before endmodule; order is independent).
            g, glabels = autofix_guard_sim_only_assert(p)
            guarded_total += g
            if g:
                print(f"{f}: fenced sim-only assertion(s) in translate_off guard: {glabels}")
        print(f"rtl_hygiene_lint --fix: repaired {total} reset-less registered output(s), "
              f"fenced {guarded_total} sim-only assertion construct(s)")
        return 0

    sev_order = {'ERROR': 2, 'WARN': 1, 'INFO': 0}
    min_sev = sev_order[args.severity]

    all_findings: List[Finding] = []
    for f in args.files:
        p = Path(f)
        if not p.exists():
            print(f"WARNING: file not found: {f}", file=sys.stderr)
            continue
        try:
            all_findings += lint_file(p)
        except Exception as e:
            print(f"ERROR parsing {f}: {e}", file=sys.stderr)
            return 2

    filtered = [f for f in all_findings if sev_order[f.severity] >= min_sev]

    # Text report
    err = sum(1 for f in filtered if f.severity == 'ERROR')
    warn = sum(1 for f in filtered if f.severity == 'WARN')
    info = sum(1 for f in filtered if f.severity == 'INFO')
    print(f"rtl_hygiene_lint: {err} errors, {warn} warnings, {info} info")
    print("-" * 70)
    for fd in sorted(filtered, key=lambda x: (x.file, x.line, x.severity)):
        print(f"{fd.file}:{fd.line}: [{fd.severity}] {fd.rule}: {fd.message}")

    if args.json:
        Path(args.json).write_text(json.dumps([asdict(f) for f in filtered], indent=2))

    return 1 if err > 0 or warn > 0 else 0


if __name__ == '__main__':
    sys.exit(main())
