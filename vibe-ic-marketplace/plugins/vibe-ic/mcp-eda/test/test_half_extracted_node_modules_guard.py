def _wait_for(predicate):
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline:
        if predicate():
            return
        time.sleep(0.02)
    pytest.fail("controlled bootstrap interleaving did not reach its barrier")


@pytest.mark.parametrize("tree", ["missing", "half-extracted"])
def test_concurrent_bootstraps_share_one_repair(plugin, tree):
    """Hold the first real npm child while the second real bootstrap probes.

    The npm fixture refuses overlapping mutations with the field's exit 217.
    It also preserves #1931's incremental no-op, requiring exactly one wipe
    followed by one effective install for the half-extracted case.
    """
    if tree == "missing":
        shutil.rmtree(plugin["mcp"] / "node_modules")
    else:
        _half_extract(plugin["mcp"])
    shim = _fake_npm(plugin["tmp"], plugin["template"], "install-on-empty")
    tmp = plugin["tmp"]
    release = tmp / "release-npm"
    entered = tmp / "npm-entered"
    collision = tmp / "npm-collision"
    events = tmp / "npm-events.jsonl"
    (tmp / "fakebin" / "npm").write_text(f'''#!{sys.executable}
import json, os, pathlib, shutil, sys, time
root = pathlib.Path({str(tmp)!r})
active = root / "npm-active"
def event(kind):
    with (root / "npm-events.jsonl").open("a") as f:
        f.write(json.dumps(dict(event=kind, pid=os.getpid(), ppid=os.getppid(),
                               argv=sys.argv, cwd=os.getcwd())) + "\\n")
try:
    active.mkdir()
except FileExistsError:
    event("overlap")
    (root / "npm-collision").touch()
    sys.exit(217)
try:
    event("enter")
    (root / "npm-entered").touch()
    deadline = time.monotonic() + 10
    while not (root / "release-npm").exists():
        if time.monotonic() > deadline:
            sys.exit(98)
        time.sleep(0.02)
    if not pathlib.Path("node_modules").exists():
        shutil.copytree({str(plugin["template"])!r}, "node_modules")
        event("install")
    else:
        event("noop")
finally:
    active.rmdir()
''')
    # The second client uses an alias to the SAME canonical package root.
    alias = tmp / "package-alias"
    alias.symlink_to(plugin["source_mcp"], target_is_directory=True)
    clients = []
    handles = []
    records = []
    try:
        for i, mcp in enumerate([plugin["source_mcp"], alias]):
            out, err = tmp / f"client-{i}.stdout", tmp / f"client-{i}.stderr"
            handles.extend([out.open("w"), err.open("w")])
            argv = [shutil.which("node"), str(mcp / "src" / "bootstrap.mjs")]
            child = subprocess.Popen(argv, cwd=mcp, env=shim["env"],
                                     stdout=handles[-2], stderr=handles[-1])
            clients.append(child)
            records.append(dict(pid=child.pid, argv=argv, cwd=str(mcp),
                                stdout=str(out), stderr=str(err)))
            if i == 0:
                _wait_for(entered.exists)
        _wait_for(lambda: collision.exists() or "waiting for dependency repair" in
                  (tmp / "client-1.stderr").read_text())
    finally:
        release.touch()
        for child, record in zip(clients, records):
            try:
                record["rc"] = child.wait(timeout=15)
            except subprocess.TimeoutExpired:
                child.kill()  # this fixture's exact child only
                record["rc"] = child.wait(timeout=5)
        for handle in handles:
            handle.close()
        (tmp / "processes.json").write_text(json.dumps(records, indent=2))
    observed = [json.loads(line) for line in events.read_text().splitlines()]
    assert [r["rc"] for r in records] == [0, 0], {
        r["pid"]: Path(r["stderr"]).read_text() for r in records}
    assert all("SERVER_STARTED" in Path(r["stdout"]).read_text() for r in records)
    assert not collision.exists(), observed
    assert sum(e["event"] == "enter" for e in observed) == (1 if tree == "missing" else 2)
    assert sum(e["event"] == "install" for e in observed) == 1
    assert sum("wiping" in Path(r["stderr"]).read_text() for r in records) == (tree != "missing")
    _assert_complete(plugin["mcp"])


