#!/usr/bin/env python3
"""Regression for #1931: a HALF-EXTRACTED node_modules must go RED in BOTH
install guards, and the self-heal must actually heal it.

The field state (measured 2026-08-30, plugin update 1.13.21 -> 1.13.43,
`npm install` interrupted mid-extract):

  - 91 of 93 packages present; one package dir holding only `dist/` (no
    package.json); npm staging dirs (`.hono-565qHAHp`, ...) abandoned;
  - `node_modules/.package-lock.json` recording the install as COMPLETE —
    so a plain `npm install` judged the tree complete and NO-OPPED;
  - post_install.sh's `! -d node_modules` guard: PASSED over it;
  - bootstrap.mjs's single-file SDK probe: PASSED over it (variants), and
    when it did fire, the no-op npm left it FATAL on every start.

Both old predicates are pinned here as NEGATIVE CONTROLS on the fixture: the
half-extracted tree KEEPS the directory and KEEPS the SDK probe file, so any
future guard that decays back to either predicate goes green on this fixture
and the assertions about repair fail loudly.

The npm on PATH is a SHIM that reproduces the field behaviour exactly:
with node_modules present it no-ops (the .package-lock.json lie); only after
the guard wipes the corrupt tree does it install the full set. A mode where
it ALWAYS no-ops proves the guard ends RED-and-loud, never wedged-and-green.
"""
import json
import os
import shutil
import stat
import sys
from pathlib import Path

import pytest

for _anc in Path(__file__).resolve().parents:
    for _cand in (_anc / "vibe-ic-marketplace" / "plugins" / "vibe-ic" / "programs",
                  _anc / "programs"):
        if (_cand / "_progress_run.py").is_file():
            sys.path.insert(0, str(_cand))
            break
    else:
        continue
    break
import _progress_run as _pr  # noqa: E402

MCP_DIR = Path(__file__).resolve().parents[1]
HOOKS_DIR = MCP_DIR.parent / "hooks"

pytestmark = pytest.mark.skipif(
    shutil.which("node") is None or shutil.which("bash") is None,
    reason="NOT_VERIFIED: the guards are node+bash; remedy: install node")

#: Denominator: what the fixture's lockfile requires. `fake-d` is TRANSITIVE
#: (absent from package.json dependencies) — it pins that the denominator is
#: the LOCKFILE, not the one-line dependencies map.
PACKAGES = ["@modelcontextprotocol/sdk", "fake-hono", "fake-zod", "fake-d"]


def _write_pkg(nm: Path, name: str) -> None:
    d = nm / name
    d.mkdir(parents=True, exist_ok=True)
    (d / "package.json").write_text(
        json.dumps({"name": name, "version": "1.0.0"}) + "\n")
    (d / "index.js").write_text("export default 1;\n")


def _lock_content() -> str:
    return json.dumps({
        "name": "fixture", "version": "1.0.0", "lockfileVersion": 3,
        "packages": dict(
            {"": {"name": "fixture", "version": "1.0.0"}},
            **{f"node_modules/{n}": {"version": "1.0.0"} for n in PACKAGES}),
    }, indent=1) + "\n"


def _build_plugin(root: Path) -> Path:
    """A miniature CLAUDE_PLUGIN_ROOT: hooks/post_install.sh + mcp-eda/ with
    the REAL bootstrap + checker and a stub index.js, ready for a per-scenario
    node_modules."""
    mcp = root / "mcp-eda"
    (mcp / "src").mkdir(parents=True)
    (root / "hooks").mkdir()
    shutil.copy2(HOOKS_DIR / "post_install.sh", root / "hooks" / "post_install.sh")
    shutil.copy2(MCP_DIR / "src" / "bootstrap.mjs", mcp / "src" / "bootstrap.mjs")
    shutil.copy2(MCP_DIR / "src" / "deps_complete.mjs", mcp / "src" / "deps_complete.mjs")
    (mcp / "src" / "index.js").write_text('process.stdout.write("SERVER_STARTED\\n");\n')
    (mcp / "package.json").write_text(json.dumps({
        "name": "fixture", "version": "1.0.0", "type": "module",
        "dependencies": {"@modelcontextprotocol/sdk": "^1.0.0",
                         "fake-hono": "^1.0.0", "fake-zod": "^1.0.0"},
    }) + "\n")
    (mcp / "package-lock.json").write_text(_lock_content())
    return mcp


def _complete_tree(mcp: Path) -> None:
    nm = mcp / "node_modules"
    for n in PACKAGES:
        _write_pkg(nm, n)
    (nm / ".package-lock.json").write_text(_lock_content())


def _half_extract(mcp: Path) -> None:
    """The measured field state, denominator-preserving: probe file KEPT."""
    nm = mcp / "node_modules"
    shutil.rmtree(nm / "fake-hono")                       # missing entirely
    shutil.rmtree(nm / "fake-zod")                        # dir with only dist/
    (nm / "fake-zod" / "dist").mkdir(parents=True)        #   -> no package.json
    (nm / ".fake-hono-565qHAHp").mkdir()                  # abandoned staging dir
    # NEGATIVE CONTROLS — the two OLD predicates still say "all fine":
    assert nm.is_dir(), "old post_install predicate (-d node_modules) must hold"
    assert (nm / "@modelcontextprotocol" / "sdk" / "package.json").exists(), \
        "old bootstrap probe file must survive the half-extraction"


def _fake_npm(root: Path, template: Path, mode: str) -> dict:
    """An `npm` shim on PATH reproducing the field behaviour: node_modules
    present -> no-op (the .package-lock.json lie); absent -> full install."""
    bin_dir = root / "fakebin"
    bin_dir.mkdir(exist_ok=True)
    log = root / "npm_calls.log"
    log.unlink(missing_ok=True)
    npm = bin_dir / "npm"
    npm.write_text(f"""#!/usr/bin/env bash
echo "npm $*" >> "{log}"
[ "{mode}" = "always-noop" ] && exit 0
if [ ! -d node_modules ]; then cp -r "{template}" node_modules; fi
exit 0
""")
    npm.chmod(npm.stat().st_mode | stat.S_IEXEC)
    node_dir = Path(shutil.which("node")).parent
    # Every arm gets a THROWAWAY config dir: the repair path clears the MCP
    # client's needs-auth cache, and a test must never reach the real one.
    cfg_default = root / "cfg-default"
    cfg_default.mkdir(exist_ok=True)
    env = dict(os.environ,
               PATH=f"{bin_dir}:{node_dir}:/usr/bin:/bin",
               CLAUDE_CONFIG_DIR=str(cfg_default))
    return {"env": env, "log": log}


@pytest.fixture()
def plugin(tmp_path):
    root = tmp_path / "plugin"
    root.mkdir()
    mcp = _build_plugin(root)
    _complete_tree(mcp)
    template = tmp_path / "nm_template"
    shutil.copytree(mcp / "node_modules", template)
    return {"root": root, "mcp": mcp, "template": template, "tmp": tmp_path}


def _npm_calls(log: Path) -> list:
    return log.read_text().splitlines() if log.exists() else []


def _run_bootstrap(plugin, mode):
    shim = _fake_npm(plugin["tmp"], plugin["template"], mode)
    r = _pr.run(["node", str(plugin["mcp"] / "src" / "bootstrap.mjs")],
                cwd=str(plugin["mcp"]), env=shim["env"],
                capture_output=True, text=True)
    return r, shim


def _run_post_install(plugin, mode):
    shim = _fake_npm(plugin["tmp"], plugin["template"], mode)
    shim["env"]["CLAUDE_PLUGIN_ROOT"] = str(plugin["root"])
    r = _pr.run(["bash", str(plugin["root"] / "hooks" / "post_install.sh")],
                cwd=str(plugin["tmp"]), env=shim["env"],
                capture_output=True, text=True)
    return r, shim


def _assert_complete(mcp: Path) -> None:
    for n in PACKAGES:
        assert (mcp / "node_modules" / n / "package.json").exists(), n


def test_complete_tree_is_the_hot_path_and_calls_no_npm(plugin):
    r, shim = _run_bootstrap(plugin, "install-on-empty")
    assert r.returncode == 0, r.stderr
    assert "SERVER_STARTED" in r.stdout
    assert _npm_calls(shim["log"]) == [], "a complete tree must not churn npm"


def test_bootstrap_repairs_the_half_extracted_wedge_with_one_wipe(plugin):
    _half_extract(plugin["mcp"])
    r, shim = _run_bootstrap(plugin, "install-on-empty")
    assert r.returncode == 0, r.stderr
    assert "SERVER_STARTED" in r.stdout
    # call 1 = the field's no-op against the lying lockfile; the guard must
    # then WIPE and call again — exactly two, never an install loop.
    assert len(_npm_calls(shim["log"])) == 2, shim["log"].read_text()
    assert "wiping" in r.stderr.lower()
    _assert_complete(plugin["mcp"])
    assert not (plugin["mcp"] / "node_modules" / ".fake-hono-565qHAHp").exists(), \
        "the abandoned staging dir must not survive the repair"


def test_bootstrap_goes_red_and_loud_when_no_install_can_complete(plugin):
    _half_extract(plugin["mcp"])
    r, _ = _run_bootstrap(plugin, "always-noop")
    assert r.returncode == 1
    assert "FATAL" in r.stderr
    assert "fake-hono" in r.stderr, \
        "the refusal must NAME what is missing, not just count it"
    assert "SERVER_STARTED" not in r.stdout


def test_post_install_sees_the_half_extracted_tree_and_repairs_it(plugin):
    _half_extract(plugin["mcp"])
    r, shim = _run_post_install(plugin, "install-on-empty")
    assert r.returncode == 0, "the SessionStart hook must NEVER block startup"
    assert len(_npm_calls(shim["log"])) == 2, shim["log"].read_text()
    _assert_complete(plugin["mcp"])


def test_post_install_control_complete_tree_stays_untouched(plugin):
    r, shim = _run_post_install(plugin, "install-on-empty")
    assert r.returncode == 0
    assert _npm_calls(shim["log"]) == [], \
        "the old guard skipped on `-d node_modules`; the new one must still " \
        "skip on a COMPLETE tree — the real question, not no question"


def test_lockfile_is_the_denominator_not_package_json(plugin):
    # fake-d is transitive-only: absent from dependencies, required by the
    # lockfile. Deleting it must go red, or the check has the old blindness
    # one level down.
    shutil.rmtree(plugin["mcp"] / "node_modules" / "fake-d")
    r = _pr.run(["node", str(plugin["mcp"] / "src" / "deps_complete.mjs"),
                 "--pkg-root", str(plugin["mcp"])],
                capture_output=True, text=True)
    assert r.returncode == 1
    assert "node_modules/fake-d" in r.stdout


def test_repair_clears_only_our_stale_needs_auth_cache_entry(plugin):
    cfg = plugin["tmp"] / "claude-config"
    cfg.mkdir()
    cache = cfg / "mcp-needs-auth-cache.json"
    cache.write_text(json.dumps({
        "plugin:vibe-ic:eda-tools": {"timestamp": 1, "id": "stale"},
        "some-other-server": {"timestamp": 2, "id": "keep"},
    }))
    _half_extract(plugin["mcp"])
    shim = _fake_npm(plugin["tmp"], plugin["template"], "install-on-empty")
    shim["env"]["CLAUDE_CONFIG_DIR"] = str(cfg)
    r = _pr.run(["node", str(plugin["mcp"] / "src" / "bootstrap.mjs")],
                cwd=str(plugin["mcp"]), env=shim["env"],
                capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    left = json.loads(cache.read_text())
    assert "plugin:vibe-ic:eda-tools" not in left, \
        "the stale exit-217 entry must not outlive the repair"
    assert left.get("some-other-server", {}).get("id") == "keep", \
        "other servers' cache entries are not ours to touch"


def test_control_no_repair_means_the_cache_file_is_not_touched(plugin):
    cfg = plugin["tmp"] / "claude-config"
    cfg.mkdir()
    cache = cfg / "mcp-needs-auth-cache.json"
    before = json.dumps({"plugin:vibe-ic:eda-tools": {"timestamp": 1, "id": "x"}})
    cache.write_text(before)
    shim = _fake_npm(plugin["tmp"], plugin["template"], "install-on-empty")
    shim["env"]["CLAUDE_CONFIG_DIR"] = str(cfg)
    r = _pr.run(["node", str(plugin["mcp"] / "src" / "bootstrap.mjs")],
                cwd=str(plugin["mcp"]), env=shim["env"],
                capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    assert cache.read_text() == before, \
        "the hot path must not rewrite the client's cache"
