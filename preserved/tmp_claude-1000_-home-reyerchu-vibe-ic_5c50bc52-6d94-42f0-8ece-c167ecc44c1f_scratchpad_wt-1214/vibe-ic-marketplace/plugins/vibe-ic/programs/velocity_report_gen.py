#!/usr/bin/env python3
"""velocity_report_gen.py — the four public dimensions, derived, with
landed-and-gated as the only legal denominator (vibe-ic#1120).

THE PROOF THIS EXISTS FOR, FROM 2026-08-12
==========================================
Authoring was scaled to 23 agents. Within hours ~25 PRs were opened and the open
PR count went 31 -> 46. Landed in the same window: two versions. Queue growth
~10/hour, drain ~4/hour.

**A published "PRs per hour" would have looked excellent while the system went
backwards.** The owner caught it from the dashboard, not from any produced
number. That is lie-shape #12 — measuring a proxy, not the property — applied to
our own reporting.

THE RULE THIS ENFORCES
======================
Every velocity figure has as its denominator **fixes that LANDED on the gated
branch**, never PRs opened, commits authored, or issues filed. A fix nobody can
land is not a fix.

There is no helper here that reaches un-landed work, and that absence is
deliberate rather than incidental: the generator cannot publish the number that
would have lied, because it cannot compute it. A test asserts the absence by
scanning this file, so re-introducing such a helper fails loudly — including if
it is only NAMED in a comment, which is why this paragraph describes it instead
of spelling it.

PROPERTIES vs PROXIES, and proxies never travel alone
=====================================================
#1120 splits the reviewer's list, and this generator keeps the split:

  PROPERTY   FAIL->PASS reproducibility, % upstreamed, designs enabled,
             PPA on a fixed spec+PDK, regression coverage
  PROXY      fixes/month, median time-to-fix, commits, PRs, lines

A proxy is emitted ONLY with its denominator in the same sentence, the way the
census prints "guards 131 of 344 figures = 38%" rather than a bare pass. A bare
proxy is refused at generation, not caught in review.

SILICON PROOF IS ZERO AND SAYS SO
=================================
No Vibe-IC design has been fabricated. The adversarial review scored it 2/10 and
that is correct. It is emitted as an explicit zero WITH the reason, because a
dimension that reads zero is what makes the other three believable. It is not
derived from anything and cannot be raised by activity — only by silicon.

EXIT CODES: 0 PASS, 1 FAIL (page disagrees with the derivation), 2 VACUOUS.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

RC_PASS, RC_FAIL, RC_VACUOUS = 0, 1, 2

PAGE_REL = "docs/ENGINEERING_METRICS.md"
VERSION_RE = re.compile(r"^\[v(\d+\.\d+\.\d+)\]")
ISSUE_RE = re.compile(r"\(#(\d+)\)")
BANNER = ("<!-- GENERATED by programs/velocity_report_gen.py — do not edit. "
          "Every figure is derived from the gated branch. -->")


def _git(repo: Path, *args):
    r = subprocess.run(["git", "-C", str(repo), *args],
                       capture_output=True, text=True)
    return r.stdout.splitlines() if r.returncode == 0 else []


def landed_commits(repo: Path, ref: str = "origin/main"):
    """Commits reachable from the GATED branch. This is the only denominator.

    Everything downstream counts a subset of this list. There is deliberately no
    way to reach un-landed work from here.
    """
    out = []
    for line in _git(repo, "log", "--format=%H%x1f%ct%x1f%s", ref):
        parts = line.split("\x1f")
        if len(parts) == 3:
            out.append({"sha": parts[0], "ts": int(parts[1]), "subject": parts[2]})
    return out


def derive(repo: Path, ref: str = "origin/main"):
    commits = landed_commits(repo, ref)
    versions = [c for c in commits if VERSION_RE.match(c["subject"])]
    fixes = [c for c in commits
             if ISSUE_RE.search(c["subject"]) and not VERSION_RE.match(c["subject"])]
    issues_closed = sorted({int(m) for c in fixes
                            for m in ISSUE_RE.findall(c["subject"])})

    return {
        "_comment": ("Derived from the gated branch. The denominator is LANDED "
                     "commits; PRs opened and issues filed are deliberately "
                     "not computable here (vibe-ic#1120)."),
        "ref": ref,
        "denominator": {
            "landed_commits": len(commits),
            "landed_versions": len(versions),
            "landed_fixes_naming_an_issue": len(fixes),
            "distinct_issues_closed_on_the_gated_branch": len(issues_closed),
        },
        "engineering_velocity": {
            "kind": "proxy",
            "requires_denominator_in_the_same_sentence": True,
            "landed_fixes": len(fixes),
            "landed_versions": len(versions),
        },
        "autonomous_improvement": {
            "kind": "proxy",
            "requires_denominator_in_the_same_sentence": True,
            "issues_closed_by_landed_work": len(issues_closed),
        },
        "adversarial_verification": {
            "kind": "property",
            "note": ("FAIL->PASS reproducibility and regression coverage are "
                     "properties, but they are NOT derivable from commit "
                     "subjects. They are left UNMEASURED here rather than "
                     "approximated by a commit count."),
            "measured": None,
        },
        "silicon_proof": {
            "kind": "property",
            "value": 0,
            "reason": ("No Vibe-IC design has been fabricated. This is not "
                       "derived and cannot be raised by activity — only by "
                       "silicon. A dimension that reads zero is what makes the "
                       "other three believable."),
        },
    }


def render(d: dict) -> str:
    dn = d["denominator"]
    ev, ai = d["engineering_velocity"], d["autonomous_improvement"]
    L = [BANNER, "", "# Engineering Metrics", "",
         "Every figure below is derived from the **gated branch** "
         f"(`{d['ref']}`). The denominator is work that LANDED and passed the "
         "full gate — never PRs opened, commits authored, or issues filed.", "",
         "> **Why the denominator is stated everywhere.** On 2026-08-12 "
         "authoring scaled to 23 agents; ~25 PRs opened in a few hours and the "
         "open count went 31 → 46 while two versions landed. Queue growth "
         "~10/hour against drain ~4/hour. A published *PRs per hour* would have "
         "looked excellent while the system went backwards.", "",
         "## Engineering Velocity — *proxy, shown with its denominator*", "",
         f"- **{ev['landed_fixes']} landed fixes** of "
         f"{dn['landed_commits']} landed commits on the gated branch.",
         f"- **{ev['landed_versions']} versions** landed.", "",
         "## Autonomous Improvement — *proxy, shown with its denominator*", "",
         f"- **{ai['issues_closed_by_landed_work']} issues closed by landed "
         f"work**, out of {dn['landed_fixes_naming_an_issue']} landed commits "
         f"naming an issue.", "",
         "## Adversarial Verification — *property, UNMEASURED*", "",
         f"- {d['adversarial_verification']['note']}", "",
         "## Silicon Proof — **0**", "",
         f"- {d['silicon_proof']['reason']}", ""]
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--repo", type=Path, default=Path("."))
    ap.add_argument("--ref", default="origin/main")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--json", dest="json_out", type=Path)
    a = ap.parse_args(argv)

    d = derive(a.repo, a.ref)
    if a.json_out:
        a.json_out.write_text(json.dumps(d, indent=2) + "\n", encoding="utf-8")

    if d["denominator"]["landed_commits"] == 0:
        print(f"[VACUOUS] velocity_report: no commit reachable from {a.ref!r} — "
              f"nothing landed, so no figure has a denominator. This is NOT a "
              f"report of zero velocity.", file=sys.stderr)
        return RC_VACUOUS

    page = a.repo / PAGE_REL
    want = render(d)

    if a.write:
        page.parent.mkdir(parents=True, exist_ok=True)
        page.write_text(want, encoding="utf-8")
        print(f"[OK] wrote {page} "
              f"({d['engineering_velocity']['landed_fixes']} landed fixes / "
              f"{d['denominator']['landed_commits']} landed commits)",
              file=sys.stderr)
        return RC_PASS

    if a.check:
        if not page.is_file():
            print(f"[FAIL] {PAGE_REL} does not exist; regenerate with --write",
                  file=sys.stderr)
            return RC_FAIL
        have = page.read_text(encoding="utf-8")
        if not have.startswith(BANNER):
            print(f"[FAIL] {PAGE_REL} lost its generated banner — a page that "
                  f"can be hand-edited is a page that can be talked upward",
                  file=sys.stderr)
            return RC_FAIL
        if have != want:
            print(f"[FAIL] {PAGE_REL} disagrees with the derivation. It is a "
                  f"pure function of the gated branch, so a figure that moved "
                  f"while the branch did not means the page was edited. "
                  f"Regenerate with --write.", file=sys.stderr)
            return RC_FAIL
        print(f"[PASS] {PAGE_REL} matches the derivation "
              f"({d['engineering_velocity']['landed_fixes']} landed fixes / "
              f"{d['denominator']['landed_commits']} landed commits).",
              file=sys.stderr)
        return RC_PASS

    sys.stdout.write(want)
    return RC_PASS


if __name__ == "__main__":
    raise SystemExit(main())
