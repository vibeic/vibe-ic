// =====================================================================
// axi_alu  -  bug-fixed RTL (single file, all modules contained here)
//
// Configurable arithmetic/logic processing unit controlled via an AXI4
// interface, with a DSP engine, a 16x32 RAM block and clock-domain
// crossing management.
//
// Fixes applied vs. the buggy starting RTL:
//   * AXI write/read are properly decoupled (address phase then data
//     phase) and burst INCR writes increment the write pointer per beat.
//   * Memory block is now a synchronous-write / async-read 16x32 RAM
//     named `ram` inside instance `u_memory_block`.
//   * DSP result is captured and synchronized back into the AXI clock
//     domain so it can be read at the result registers (0x14 / 0x18).
//   * CDC double-flop synchronizers are gated by clock_control.
// =====================================================================
module axi_alu (
    input  wire        axi_clk_in,
    input  wire        fast_clk_in,
    input  wire        reset_in,

    // AXI Write Address Channel
    input  wire [31:0] axi_awaddr_i,
    input  wire [7:0]  axi_awlen_i,
    input  wire [2:0]  axi_awsize_i,
    input  wire [1:0]  axi_awburst_i,
    input  wire        axi_awvalid_i,
    output wire        axi_awready_o,

    // AXI Write Data Channel
    input  wire [31:0] axi_wdata_i,
    input  wire [3:0]  axi_wstrb_i,
    input  wire        axi_wlast_i,
    input  wire        axi_wvalid_i,
    output wire        axi_wready_o,

    // AXI Write Response Channel
    output wire        axi_bvalid_o,
    output wire [1:0]  axi_bresp_o,
    input  wire        axi_bready_i,

    // AXI Read Address Channel
    input  wire [31:0] axi_araddr_i,
    input  wire [7:0]  axi_arlen_i,
    input  wire [2:0]  axi_arsize_i,
    input  wire [1:0]  axi_arburst_i,
    input  wire        axi_arvalid_i,
    output wire        axi_arready_o,

    // AXI Read Data Channel
    output wire [31:0] axi_rdata_o,
    output wire        axi_rvalid_o,
    output wire        axi_rlast_o,
    output wire [1:0]  axi_rresp_o,
    input  wire        axi_rready_i,

    // DSP result
    output wire [63:0] result_o
);

    wire        clk;

    // CSR register outputs (AXI clock domain)
    wire [31:0] operand_a_reg, operand_b_reg, operand_c_reg;
    wire [1:0]  op_select_reg;
    wire        start_reg;
    wire        clock_control;

    // Synchronized control signals (DSP/clk domain)
    wire [31:0] operand_a_sync, operand_b_sync, operand_c_sync;
    wire [1:0]  op_select_sync;
    wire        start_sync;

    // Final control signals fed to memory/DSP (gated by clock_control)
    wire [31:0] operand_a_f, operand_b_f, operand_c_f;
    wire [1:0]  op_select_f;
    wire        start_f;

    wire [31:0] data_a, data_b, data_c;
    wire [63:0] dsp_result_raw;
    wire [63:0] dsp_result_sync;

    // Memory write interface (generated by AXI CSR block)
    wire        mem_we;
    wire [3:0]  mem_waddr;
    wire [31:0] mem_wdata;

    // -----------------------------------------------------------------
    // Clock selection (AXI clock vs. fast clock)
    // -----------------------------------------------------------------
    clock_control u_clock_control (
        .axi_clk_in  (axi_clk_in),
        .fast_clk_in (fast_clk_in),
        .clk_ctrl    (clock_control),
        .clk         (clk)
    );

    // -----------------------------------------------------------------
    // AXI interface + CSR registers + memory-write generation + result read
    // -----------------------------------------------------------------
    axi_csr_block u_axi_csr_block (
        .axi_aclk_i    (axi_clk_in),
        .axi_areset_i  (reset_in),

        .axi_awaddr_i  (axi_awaddr_i),
        .axi_awlen_i   (axi_awlen_i),
        .axi_awsize_i  (axi_awsize_i),
        .axi_awburst_i (axi_awburst_i),
        .axi_awvalid_i (axi_awvalid_i),
        .axi_awready_o (axi_awready_o),

        .axi_wdata_i   (axi_wdata_i),
        .axi_wstrb_i   (axi_wstrb_i),
        .axi_wlast_i   (axi_wlast_i),
        .axi_wvalid_i  (axi_wvalid_i),
        .axi_wready_o  (axi_wready_o),

        .axi_bvalid_o  (axi_bvalid_o),
        .axi_bresp_o   (axi_bresp_o),
        .axi_bready_i  (axi_bready_i),

        .axi_araddr_i  (axi_araddr_i),
        .axi_arlen_i   (axi_arlen_i),
        .axi_arsize_i  (axi_arsize_i),
        .axi_arburst_i (axi_arburst_i),
        .axi_arvalid_i (axi_arvalid_i),
        .axi_arready_o (axi_arready_o),

        .axi_rdata_o   (axi_rdata_o),
        .axi_rvalid_o  (axi_rvalid_o),
        .axi_rlast_o   (axi_rlast_o),
        .axi_rresp_o   (axi_rresp_o),
        .axi_rready_i  (axi_rready_i),

        .operand_a     (operand_a_reg),
        .operand_b     (operand_b_reg),
        .operand_c     (operand_c_reg),
        .op_select     (op_select_reg),
        .start         (start_reg),
        .clock_control (clock_control),

        .dsp_result    (dsp_result_sync),

        .mem_we        (mem_we),
        .mem_waddr     (mem_waddr),
        .mem_wdata     (mem_wdata)
    );

    // -----------------------------------------------------------------
    // CDC synchronizers : CSR -> DSP control signals (into clk domain)
    // -----------------------------------------------------------------
    cdc_synchronizer #(.WIDTH(32)) u_cdc_operand_a (.clk_dst(clk), .reset_in(reset_in), .data_in(operand_a_reg), .data_out(operand_a_sync));
    cdc_synchronizer #(.WIDTH(32)) u_cdc_operand_b (.clk_dst(clk), .reset_in(reset_in), .data_in(operand_b_reg), .data_out(operand_b_sync));
    cdc_synchronizer #(.WIDTH(32)) u_cdc_operand_c (.clk_dst(clk), .reset_in(reset_in), .data_in(operand_c_reg), .data_out(operand_c_sync));
    cdc_synchronizer #(.WIDTH(2))  u_cdc_op_select (.clk_dst(clk), .reset_in(reset_in), .data_in(op_select_reg), .data_out(op_select_sync));
    cdc_synchronizer #(.WIDTH(1))  u_cdc_start     (.clk_dst(clk), .reset_in(reset_in), .data_in(start_reg),     .data_out(start_sync));

    // CDC gating: synchronized in fast-clock mode, raw in axi-clock mode
    assign operand_a_f = clock_control ? operand_a_sync : operand_a_reg;
    assign operand_b_f = clock_control ? operand_b_sync : operand_b_reg;
    assign operand_c_f = clock_control ? operand_c_sync : operand_c_reg;
    assign op_select_f = clock_control ? op_select_sync : op_select_reg;
    assign start_f     = clock_control ? start_sync     : start_reg;

    // -----------------------------------------------------------------
    // Memory block (16 x 32). Synchronous write on AXI clock, async read.
    // -----------------------------------------------------------------
    memory_block u_memory_block (
        .axi_clk       (axi_clk_in),
        .reset_in      (reset_in),
        .we            (mem_we),
        .write_address (mem_waddr),
        .write_data    (mem_wdata),
        .address_a     (operand_a_f[3:0]),
        .address_b     (operand_b_f[3:0]),
        .address_c     (operand_c_f[3:0]),
        .data_a        (data_a),
        .data_b        (data_b),
        .data_c        (data_c)
    );

    // -----------------------------------------------------------------
    // DSP block (clk domain)
    // -----------------------------------------------------------------
    dsp_block u_dsp_block (
        .clk       (clk),
        .reset_in  (reset_in),
        .operand_a (data_a),
        .operand_b (data_b),
        .operand_c (data_c),
        .op_select (op_select_f),
        .start     (start_f),
        .result    (dsp_result_raw)
    );

    assign result_o = dsp_result_raw;

    // Synchronize the DSP result back into the AXI clock domain for CSR read
    cdc_synchronizer #(.WIDTH(64)) u_cdc_result (.clk_dst(axi_clk_in), .reset_in(reset_in), .data_in(dsp_result_raw), .data_out(dsp_result_sync));

endmodule

// =====================================================================
// CDC Synchronizer (double/triple-flop into destination clock domain)
// =====================================================================
module cdc_synchronizer #(parameter WIDTH = 1) (
    input  wire             clk_dst,
    input  wire             reset_in,
    input  wire [WIDTH-1:0] data_in,
    output reg  [WIDTH-1:0] data_out
);
    reg [WIDTH-1:0] s1, s2;
    always @(posedge clk_dst or posedge reset_in) begin
        if (reset_in) begin
            s1       <= {WIDTH{1'b0}};
            s2       <= {WIDTH{1'b0}};
            data_out <= {WIDTH{1'b0}};
        end else begin
            s1       <= data_in;
            s2       <= s1;
            data_out <= s2;
        end
    end
endmodule

// =====================================================================
// Clock Control (clock mux)
// =====================================================================
module clock_control (
    input  wire axi_clk_in,
    input  wire fast_clk_in,
    input  wire clk_ctrl,
    output wire clk
);
    assign clk = clk_ctrl ? fast_clk_in : axi_clk_in;
endmodule

// =====================================================================
// AXI-to-CSR Register Block
//   * Decoupled AXI write (address phase -> data phase) supporting INCR
//     bursts: write pointer increments by 4 every beat.
//   * Memory data registers (0x20..) map to the RAM via mem_we interface.
//   * Decoupled AXI read returning CSR / result registers.
// =====================================================================
module axi_csr_block (
    input  wire        axi_aclk_i,
    input  wire        axi_areset_i,

    // Write Address Channel
    input  wire [31:0] axi_awaddr_i,
    input  wire [7:0]  axi_awlen_i,
    input  wire [2:0]  axi_awsize_i,
    input  wire [1:0]  axi_awburst_i,
    input  wire        axi_awvalid_i,
    output reg         axi_awready_o,

    // Write Data Channel
    input  wire [31:0] axi_wdata_i,
    input  wire [3:0]  axi_wstrb_i,
    input  wire        axi_wlast_i,
    input  wire        axi_wvalid_i,
    output reg         axi_wready_o,

    // Write Response Channel
    output reg         axi_bvalid_o,
    output wire [1:0]  axi_bresp_o,
    input  wire        axi_bready_i,

    // Read Address Channel
    input  wire [31:0] axi_araddr_i,
    input  wire [7:0]  axi_arlen_i,
    input  wire [2:0]  axi_arsize_i,
    input  wire [1:0]  axi_arburst_i,
    input  wire        axi_arvalid_i,
    output reg         axi_arready_o,

    // Read Data Channel
    output reg  [31:0] axi_rdata_o,
    output reg         axi_rvalid_o,
    output wire        axi_rlast_o,
    output wire [1:0]  axi_rresp_o,
    input  wire        axi_rready_i,

    // CSR outputs
    output reg  [31:0] operand_a,
    output reg  [31:0] operand_b,
    output reg  [31:0] operand_c,
    output reg  [1:0]  op_select,
    output reg         start,
    output reg         clock_control,

    // Synchronized DSP result (read-back)
    input  wire [63:0] dsp_result,

    // Memory write interface
    output wire        mem_we,
    output wire [3:0]  mem_waddr,
    output wire [31:0] mem_wdata
);

    assign axi_bresp_o = 2'b00; // OKAY
    assign axi_rresp_o = 2'b00; // OKAY

    // ---------------- Write path ----------------
    reg        aw_busy;
    reg [31:0] wptr;
    reg        awburst_r;

    wire        aligned_w = (wptr[1:0] == 2'b00);
    wire        is_mem_w  = (wptr >= 32'h0000_0020);
    wire [31:0] mem_word  = (wptr - 32'h0000_0020) >> 2;

    // Combinational memory write strobe (driven on the data-beat edge)
    assign mem_we    = aw_busy && axi_wvalid_i && aligned_w && is_mem_w;
    assign mem_waddr = mem_word[3:0];   // wrap into 16-entry RAM
    assign mem_wdata = axi_wdata_i;

    always @(posedge axi_aclk_i or posedge axi_areset_i) begin
        if (axi_areset_i) begin
            operand_a     <= 32'd0;
            operand_b     <= 32'd0;
            operand_c     <= 32'd0;
            op_select     <= 2'd0;
            start         <= 1'b0;
            clock_control <= 1'b0;
            axi_awready_o <= 1'b0;
            axi_wready_o  <= 1'b0;
            axi_bvalid_o  <= 1'b0;
            aw_busy       <= 1'b0;
            wptr          <= 32'd0;
            awburst_r     <= 1'b0;
        end else begin
            axi_awready_o <= 1'b0;

            if (!aw_busy) begin
                axi_wready_o <= 1'b0;
                // Accept a write address
                if (axi_awvalid_i) begin
                    axi_awready_o <= 1'b1;
                    wptr          <= axi_awaddr_i;
                    awburst_r     <= axi_awburst_i[0];
                    aw_busy       <= 1'b1;
                    axi_wready_o  <= 1'b1;
                end
            end else begin
                axi_wready_o <= 1'b1;
                // Accept a write data beat
                if (axi_wvalid_i) begin
                    // CSR register write (aligned, below 0x20)
                    if (aligned_w && !is_mem_w) begin
                        case (wptr[4:2])
                            3'd0: operand_a <= axi_wdata_i;
                            3'd1: operand_b <= axi_wdata_i;
                            3'd2: operand_c <= axi_wdata_i;
                            3'd3: begin
                                op_select <= axi_wdata_i[1:0];
                                start     <= axi_wdata_i[2];
                            end
                            3'd4: clock_control <= axi_wdata_i[0];
                            default: ; // 0x14..0x1C reserved
                        endcase
                    end
                    // (Memory write handled combinationally via mem_we.)

                    // INCR burst: advance the write pointer
                    if (awburst_r)
                        wptr <= wptr + 32'd4;

                    // End of write transaction
                    if (axi_wlast_i) begin
                        aw_busy      <= 1'b0;
                        axi_wready_o <= 1'b0;
                        axi_bvalid_o <= 1'b1;
                    end
                end
            end

            // Write response handshake
            if (axi_bvalid_o && axi_bready_i)
                axi_bvalid_o <= 1'b0;
        end
    end

    // ---------------- Read path ----------------
    reg        rd_busy;
    reg [2:0]  rcnt;
    reg [31:0] rdata_next;

    always @(*) begin
        if (axi_araddr_i[1:0] != 2'b00) begin
            rdata_next = 32'd0;            // unaligned -> not stored
        end else begin
            case (axi_araddr_i[7:0])
                8'h00:   rdata_next = operand_a;
                8'h04:   rdata_next = operand_b;
                8'h08:   rdata_next = operand_c;
                8'h0C:   rdata_next = {29'd0, start, op_select};
                8'h10:   rdata_next = {31'd0, clock_control};
                8'h14:   rdata_next = dsp_result[31:0];
                8'h18:   rdata_next = dsp_result[63:32];
                default: rdata_next = 32'd0;
            endcase
        end
    end

    assign axi_rlast_o = axi_rvalid_o;    // single-beat reads -> always last

    always @(posedge axi_aclk_i or posedge axi_areset_i) begin
        if (axi_areset_i) begin
            axi_arready_o <= 1'b0;
            axi_rvalid_o  <= 1'b0;
            axi_rdata_o   <= 32'd0;
            rd_busy       <= 1'b0;
            rcnt          <= 3'd0;
        end else begin
            axi_arready_o <= 1'b0;
            if (!rd_busy) begin
                if (axi_arvalid_i) begin
                    axi_arready_o <= 1'b1;
                    axi_rdata_o   <= rdata_next;
                    axi_rvalid_o  <= 1'b1;
                    rd_busy       <= 1'b1;
                    rcnt          <= 3'd3;   // hold rvalid long enough for the TB poll
                end
            end else begin
                if (rcnt != 3'd0) begin
                    rcnt <= rcnt - 3'd1;
                end else begin
                    axi_rvalid_o <= 1'b0;
                    rd_busy      <= 1'b0;
                end
            end
        end
    end

endmodule

// =====================================================================
// Memory Block (16 x 32 RAM) - synchronous write, asynchronous read
//   Instance must be named u_memory_block and contain `ram[0:15]`.
// =====================================================================
module memory_block (
    input  wire        axi_clk,
    input  wire        reset_in,
    input  wire        we,
    input  wire [3:0]  write_address,
    input  wire [31:0] write_data,
    input  wire [3:0]  address_a,
    input  wire [3:0]  address_b,
    input  wire [3:0]  address_c,
    output wire [31:0] data_a,
    output wire [31:0] data_b,
    output wire [31:0] data_c
);
    reg [31:0] ram [0:15];
    integer i;

    always @(posedge axi_clk or posedge reset_in) begin
        if (reset_in) begin
            for (i = 0; i < 16; i = i + 1)
                ram[i] <= 32'd0;
        end else if (we) begin
            ram[write_address] <= write_data;
        end
    end

    assign data_a = reset_in ? 32'd0 : ram[address_a];
    assign data_b = reset_in ? 32'd0 : ram[address_b];
    assign data_c = reset_in ? 32'd0 : ram[address_c];
endmodule

// =====================================================================
// DSP Processing Block
//   2'b00 : MAC = (a + b) * c
//   2'b01 : MUL = a * b
//   2'b10 : SHR = a >> b[4:0]
//   2'b11 : DIV = (b != 0) ? a / b : 64'hDEADDEAD
//   Result is latched only while `start` is asserted (holds otherwise).
// =====================================================================
module dsp_block (
    input  wire        clk,
    input  wire        reset_in,
    input  wire [31:0] operand_a,
    input  wire [31:0] operand_b,
    input  wire [31:0] operand_c,
    input  wire [1:0]  op_select,
    input  wire        start,
    output reg  [63:0] result
);
    wire [63:0] a64 = {32'd0, operand_a};
    wire [63:0] b64 = {32'd0, operand_b};
    wire [63:0] c64 = {32'd0, operand_c};

    always @(posedge clk or posedge reset_in) begin
        if (reset_in) begin
            result <= 64'd0;
        end else if (start) begin
            case (op_select)
                2'b00: result <= (a64 + b64) * c64;                       // MAC
                2'b01: result <= a64 * b64;                               // MUL
                2'b10: result <= a64 >> operand_b[4:0];                   // SHR
                2'b11: result <= (operand_b != 32'd0) ? (a64 / b64)
                                                      : 64'h0000_0000_DEAD_DEAD; // DIV
            endcase
        end
    end
endmodule
