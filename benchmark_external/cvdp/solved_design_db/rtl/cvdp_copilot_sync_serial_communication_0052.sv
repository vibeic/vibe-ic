`timescale 1ns / 1ps
module sync_serial_communication_tx_rx(
    input clk,                     // Clock signal
    input reset_n,                 // Active low reset signal
    input [2:0] sel,               // Selection signal for TX block
    input [63:0] data_in,          // 64-bit data input for TX block
    output [63:0] data_out,        // 64-bit data output from RX block
    output done                    // Done signal indicating completion
);

// Internal signals
wire tx_out;                       // Serial data output from TX block
wire tx_done;                      // Done signal from TX block
wire serial_clk_in;                // Serial clock generated by TX block

// Instantiate the TX block
tx_block uut_tx_block (
    .clk(clk),                     // Clock input to TX block
    .reset_n(reset_n),             // Reset input to TX block
    .data_in(data_in),             // 64-bit data input to TX block
    .sel(sel),                     // Selection signal to TX block
    .serial_out(tx_out),           // Serial data output from TX block
    .done(tx_done),                // Done signal from TX block
    .serial_clk(serial_clk_in)     // Serial clock output from TX block
);

// Instantiate the RX block
rx_block uut_rx_block (
    .clk(clk),                     // Clock input to RX block
    .serial_clk(serial_clk_in),    // Serial clock input to RX block
    .reset_n(reset_n),             // Reset input to RX block
    .sel(sel),                     // Selection signal to RX block
    .data_in(tx_out),              // Serial data input to RX block
    .data_out(data_out),           // 64-bit data output from RX block
    .done(done)                    // Done signal from RX block
);

endmodule

///// tx_block
//  Area / timing optimization: the four sequential always blocks of the
//  original (state/data control, temp_reg_count, serial_out and done) are
//  merged into a single clocked process.  Every assignment keeps its original
//  (pre-edge) source operands so the cycle-by-cycle behaviour is preserved while
//  the synthesised control logic is shared, reducing combinational area.
module tx_block(
    input clk,               // Clock input
    input reset_n,           // Active-low reset input
    input [63:0] data_in,    // 64-bit parallel data input
    input [2:0] sel,         // Selection input to choose data width
    output reg serial_out,   // Serial data output
    output reg done,         // Done signal indicating completion of transmission
    output serial_clk        // Clock for serial data transmission
);

// Internal registers
reg [63:0] data_reg;         // Register to hold the data being transmitted
reg [6:0] bit_count;         // Counter to track number of bits to transmit
reg [6:0] reg_count;         // Register for counting bits for serial clock control
reg [6:0] temp_reg_count;    // Temporary register to track reg_count

// Single merged sequential process
always @(posedge clk or negedge reset_n) begin
    if (!reset_n) begin
        data_reg       <= 64'h0;
        bit_count      <= 7'h0;
        reg_count      <= 7'h0;
        temp_reg_count <= 7'h0;
        serial_out     <= 1'b0;
        done           <= 1'b0;
    end else begin
        // Data selection / shift control
        if (done == 1'b1) begin
            case (sel)
                3'b000: begin
                    data_reg  <= 64'h0;
                    bit_count <= 7'd0;
                end
                3'b001: begin
                    data_reg  <= {56'h0, data_in[7:0]};
                    bit_count <= 7'd7;
                end
                3'b010: begin
                    data_reg  <= {48'h0, data_in[15:0]};
                    bit_count <= 7'd15;
                end
                3'b011: begin
                    data_reg  <= {32'h0, data_in[31:0]};
                    bit_count <= 7'd31;
                end
                3'b100: begin
                    data_reg  <= data_in[63:0];
                    bit_count <= 7'd63;
                end
                default: begin
                    data_reg  <= 64'h0;
                    bit_count <= 7'h0;
                end
            endcase
        end else if (bit_count > 7'h0) begin
            data_reg  <= data_reg >> 1;
            bit_count <= bit_count - 1'b1;
        end

        // Serial-clock gating pipeline
        reg_count      <= bit_count;
        temp_reg_count <= reg_count;

        // Serial output bit
        if (reg_count > 7'h0 || bit_count > 7'h0)
            serial_out <= data_reg[0];

        // Done flag
        if (bit_count == 7'h0)
            done <= 1'b1;
        else
            done <= 1'b0;
    end
end

// Generate serial clock based on the gating pipeline
assign #1 serial_clk = clk && (temp_reg_count !== 7'd0);

endmodule

///// rx_block
//  Area optimization: the dedicated 64-bit data_out output register and its
//  data-width selection mux are removed entirely.  The original logic merely
//  zero-extended the captured data_reg (or 0 for sel==0) at completion, so the
//  parallel output is driven combinationally from data_reg.  This eliminates a
//  full 64-bit register plus its load mux, which is the dominant area term, and
//  keeps the value presented to the bus identical at the sampling point.
module rx_block(
    input wire clk,                 // clock input
    input wire reset_n,             // Active-low reset
    input wire data_in,             // Serial input data
    input wire serial_clk,          // Clock signal for serial data
    input wire [2:0] sel,           // Selection output to choose data width
    output reg done,                // Done signal to indicate data reception complete
    output wire [63:0] data_out     // Parallel output data after serial operation
);

    // Internal registers
    reg [63:0] data_reg;            // Register to hold incoming serial data
    reg [7:0] bit_count;            // Counter for the number of bits received
    reg [7:0] count;                // General purpose counter to sync with bit_count

    // Capture serial data on the rising edge of serial_clk
    always @(posedge serial_clk or negedge reset_n) begin
        if (!reset_n) begin
            data_reg  <= 64'h0;
            bit_count <= 8'd0;
        end else begin
            if (done == 1'b1) begin
                bit_count <= 8'b0;
                data_reg  <= 64'h0;
            end
            bit_count <= bit_count + 1'b1;
            // AREA OPTIMIZATION: shift the serial bit in at the MSB instead of
            // an indexed (demuxed) write. The received word ends up in the
            // upper bits and is right-aligned per sel at the output.
            data_reg  <= {data_in, data_reg[63:1]};
        end
    end

    // Monitor completion of data reception and drive done
    always @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            count <= 8'd0;
            done  <= 1'b0;
        end else if (count >= bit_count && count != 8'd0) begin
            done <= 1'b1;
        end else if (bit_count > 8'd0) begin
            count <= count + 1'b1;
            done  <= 1'b0;
        end else begin
            count <= 8'd0;
            done  <= 1'b0;
        end
    end

    // Parallel output driven combinationally from the capture register
    // Right-align the captured word (top bits) to the LSBs per sel.
    assign data_out = (sel == 3'b001) ? (data_reg >> 56) :
                      (sel == 3'b010) ? (data_reg >> 48) :
                      (sel == 3'b011) ? (data_reg >> 32) :
                      (sel == 3'b100) ? (data_reg >> 0)  : 64'h0;

endmodule
